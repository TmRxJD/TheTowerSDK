#!/usr/bin/env node
/**
 * Generate the Tower asset manifest from the files that actually exist.
 *
 * The images themselves live in `tower-assets` and are not part of this package — they are
 * TechTree Games' artwork, and a manifest of filenames is not artwork. What ships here is
 * the part that is genuinely useful and genuinely ours to give away: which file belongs to
 * which module or card.
 *
 * That mapping is not guessable. Module images are keyed by rarity prefix and the module's
 * INITIALS, cards by id with at least one alias that does not match its id at all. A tool
 * that derives the path by hand gets those wrong and renders nothing — silently, because a
 * missing image is not an exception.
 *
 * Scanned rather than transcribed, so an added or renamed file moves the manifest instead of
 * quietly disagreeing with it. `--check` fails when the two have diverged.
 *
 *   node scripts/build-asset-manifest.mjs [--check]
 */
import { existsSync } from 'node:fs'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const PACKAGE_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const ASSETS_ROOT = path.resolve(PACKAGE_ROOT, '..', 'tower-assets', 'assets', 'site')
const OUT_FILE = path.join(PACKAGE_ROOT, 'src', 'assets', 'manifest.generated.ts')

/** Module category directories, and the category each maps to. */
const MODULE_DIRS = {
  modules_armor: 'Armor',
  modules_cannon: 'Cannon',
  modules_core: 'Core',
  modules_generator: 'Generator',
}

const CARD_DIR = 'cards'

/**
 * Directories that are site chrome rather than game artwork.
 *
 * Everything else under `assets/site` is inventoried automatically, so a domain added to
 * `tower-assets` — bots, guardians, relics — appears in the manifest without anyone editing
 * this script. A domain with no typed resolver yet is still listed, and
 * `assets.test.ts` reports it rather than letting it pass unnoticed.
 */
const NOT_GAME_ART = new Set(['ocr'])

/**
 * Card ids whose file is not named after the id.
 *
 * Exactly the reason this manifest exists. `slow-aura` is stored as `sa.jpg`; a tool that
 * builds `cards/slow-aura.jpg` gets a 404 and an empty image with no error anywhere.
 */
const CARD_ID_ALIASES = {
  'slow-aura': 'sa',
}

async function listFiles(dir) {
  const full = path.join(ASSETS_ROOT, dir)
  if (!existsSync(full)) return []
  return (await readdir(full)).filter(name => /\.(png|jpg|jpeg|webp|svg)$/i.test(name)).sort()
}

async function build() {
  if (!existsSync(ASSETS_ROOT)) {
    throw new Error(
      `tower-assets not found at ${ASSETS_ROOT}. The manifest is generated from those files; `
      + 'without them it would be invented rather than derived.',
    )
  }

  const modules = {}
  for (const [dir, category] of Object.entries(MODULE_DIRS)) {
    const files = await listFiles(dir)
    if (files.length === 0) throw new Error(`No images found in ${dir}`)
    modules[category] = { dir, files }
  }

  const cards = await listFiles(CARD_DIR)
  if (cards.length === 0) throw new Error(`No images found in ${CARD_DIR}`)

  // Every other directory, discovered rather than listed.
  const known = new Set([...Object.keys(MODULE_DIRS), CARD_DIR, ...NOT_GAME_ART])
  const other = {}
  for (const entry of await readdir(ASSETS_ROOT, { withFileTypes: true })) {
    if (!entry.isDirectory() || known.has(entry.name)) continue
    const files = await listFiles(entry.name)
    if (files.length > 0) other[entry.name] = files
  }

  const lines = []
  lines.push('/**')
  lines.push(' * Which artwork file belongs to which module or card.')
  lines.push(' *')
  lines.push(' * GENERATED by scripts/build-asset-manifest.mjs from the files in `tower-assets`.')
  lines.push(' * Do not edit — run `npm run assets:manifest`.')
  lines.push(' *')
  lines.push(' * The images are not in this package. They are TechTree Games\' artwork and live in')
  lines.push(' * `tower-assets`, which claims no licence over them. This file is a list of names.')
  lines.push(' */')
  lines.push('')
  lines.push('/** Directory each module category\'s images live in, under `assets/site`. */')
  lines.push('export const MODULE_ASSET_DIRS = {')
  for (const [category, { dir }] of Object.entries(modules)) {
    lines.push(`  ${category}: '${dir}',`)
  }
  lines.push('} as const')
  lines.push('')
  lines.push('/** Every module image that exists, by category. Filenames are `<rarity>_<initials>`. */')
  lines.push('export const MODULE_ASSET_FILES: Readonly<Record<string, readonly string[]>> = {')
  for (const [category, { files }] of Object.entries(modules)) {
    lines.push(`  ${category}: [${files.map(f => `'${f}'`).join(', ')}],`)
  }
  lines.push('}')
  lines.push('')
  lines.push('/** Directory the card images live in, under `assets/site`. */')
  lines.push(`export const CARD_ASSET_DIR = '${CARD_DIR}' as const`)
  lines.push('')
  lines.push('/** Every card image that exists. */')
  lines.push('export const CARD_ASSET_FILES: readonly string[] = [')
  for (const file of cards) lines.push(`  '${file}',`)
  lines.push(']')
  lines.push('')
  lines.push('/**')
  lines.push(' * Card ids whose file is not named after the id.')
  lines.push(' *')
  lines.push(' * The reason a manifest is needed at all: building the path from the id gives a')
  lines.push(' * missing file for these, and a missing image does not throw.')
  lines.push(' */')
  lines.push('export const CARD_ID_ALIASES: Readonly<Record<string, string>> = {')
  for (const [id, file] of Object.entries(CARD_ID_ALIASES)) {
    lines.push(`  '${id}': '${file}',`)
  }
  lines.push('}')
  lines.push('')
  lines.push('/**')
  lines.push(' * Every other artwork directory, discovered rather than listed.')
  lines.push(' *')
  lines.push(' * A domain added to `tower-assets` shows up here immediately, before anyone writes a')
  lines.push(' * typed resolver for it — its naming rule is not guessable from the filenames alone, so')
  lines.push(' * the inventory ships and the resolver follows. `assets.test.ts` reports any entry here')
  lines.push(' * that has no resolver, so a new domain cannot sit unnoticed.')
  lines.push(' */')
  lines.push('export const OTHER_ASSET_FILES: Readonly<Record<string, readonly string[]>> = {')
  for (const [dir, files] of Object.entries(other).sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  '${dir}': [${files.map(f => `'${f}'`).join(', ')}],`)
  }
  lines.push('}')
  lines.push('')

  return lines.join('\n')
}

const built = await build()
const check = process.argv.includes('--check')

if (check) {
  const current = existsSync(OUT_FILE) ? await readFile(OUT_FILE, 'utf8') : ''
  if (current.replace(/\r\n/g, '\n') !== built) {
    console.error('Asset manifest is out of date. Run `npm run assets:manifest`.')
    process.exit(1)
  }
  const count = (built.match(/\.(png|jpg|jpeg|webp|svg)'/g) ?? []).length
  console.log(`Asset manifest OK — ${count} file(s), all current.`)
}
else {
  await mkdir(path.dirname(OUT_FILE), { recursive: true })
  await writeFile(OUT_FILE, built)
  const count = (built.match(/\.(png|jpg|jpeg|webp|svg)'/g) ?? []).length
  console.log(`Wrote ${count} asset name(s) to ${path.relative(PACKAGE_ROOT, OUT_FILE)}`)
}
