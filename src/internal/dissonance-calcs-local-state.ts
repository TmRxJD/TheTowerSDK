export function clampDissonanceInt(value: unknown, fallback: number, min: number, max: number): number {
  const numberValue = Number(value)
  if (!Number.isFinite(numberValue)) return fallback
  return Math.floor(Math.min(max, Math.max(min, numberValue)))
}

