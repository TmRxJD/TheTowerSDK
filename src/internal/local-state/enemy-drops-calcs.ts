export function normalizeSharedEnemyDropsInputs(
  value: unknown,
  fallback: SharedEnemyDropsInputs = defaultSharedEnemyDropsInputs,
): SharedEnemyDropsInputs {
  const source = value && typeof value === 'object' ? value as Record<string, unknown> : {}
  const parseNonNegative = (key: keyof SharedEnemyDropsInputs, defaultValue: number): number => {
    const parsed = Number(source[key as string])
    return Number.isFinite(parsed) && parsed >= 0 ? parsed : defaultValue
  }
  const legacyThemePct = (() => {
    if (source.themeCoinBonusPct !== undefined) return null
    const tower = Number(source.towerThemesOwned)
    const background = Number(source.backgroundThemesOwned)
    const menu = Number(source.menuThemesOwned)
    const guardian = Number(source.guardianThemesOwned)
    if (![tower, background, menu, guardian].some(n => Number.isFinite(n) && n > 0)) return null
    const mult = 1
      + Math.max(0, tower || 0) * 0.004
      + Math.max(0, background || 0) * 0.008
      + Math.max(0, menu || 0) * 0.006
      + Math.max(0, guardian || 0) * 0.006
    return Math.max(0, (mult - 1) * 100)
  })()
  const iapToggles = iapTogglesFromLegacyMults(source)
  return sharedEnemyDropsInputsSchema.parse({
    shatterCommonModules: source.shatterCommonModules === undefined
      ? fallback.shatterCommonModules
      : source.shatterCommonModules === true,
    shatterRareModules: source.shatterRareModules === true,
    themeCoinBonusPct: legacyThemePct ?? parseNonNegative('themeCoinBonusPct', fallback.themeCoinBonusPct),
    relicCoinBonusPct: parseNonNegative('relicCoinBonusPct', fallback.relicCoinBonusPct),
    hasStarterPack: source.hasStarterPack === undefined
      ? iapToggles.hasStarterPack
      : source.hasStarterPack === true,
    hasEpicPack: source.hasEpicPack === undefined
      ? iapToggles.hasEpicPack
      : source.hasEpicPack === true,
    hasDisableAds: source.hasDisableAds === undefined
      ? iapToggles.hasDisableAds
      : source.hasDisableAds === true,
    allCoinPerkLevel: Math.min(5, Math.max(0, Math.floor(parseNonNegative('allCoinPerkLevel', fallback.allCoinPerkLevel)))),
    goldenBotBonusLevel: Math.min(30, Math.max(0, Math.floor(parseNonNegative('goldenBotBonusLevel', fallback.goldenBotBonusLevel)))),
    useGoldenBotCoinBonus: source.useGoldenBotCoinBonus === undefined
      ? fallback.useGoldenBotCoinBonus
      : source.useGoldenBotCoinBonus === true,
    assumeSyncedUwCoinWindows: source.assumeSyncedUwCoinWindows === undefined
      ? fallback.assumeSyncedUwCoinWindows
      : source.assumeSyncedUwCoinWindows === true,
    hasCoinTradeOffPerk: source.hasCoinTradeOffPerk === true,
    assumeIntroSprintActive: source.assumeIntroSprintActive === true,
    freeUpgradePerkLevel: Math.min(5, Math.max(0, Math.floor(parseNonNegative('freeUpgradePerkLevel', fallback.freeUpgradePerkLevel)))),
  })
}

export function migrateLegacyEnemyDropsActiveTab(
  value: unknown,
): Pick<EnemyDropsCalcsLocalState, 'activeTab' | 'activePathsTab'> | null {
  const parsed = legacyEnemyDropsTabSchema.safeParse(value)
  if (!parsed.success) return null
  switch (parsed.data) {
    case 'inputs':
      return { activeTab: 'calculator', activePathsTab: 'cells' }
    case 'cells':
      return { activeTab: 'paths', activePathsTab: 'cells' }
    case 'shards':
      return { activeTab: 'paths', activePathsTab: 'shards' }
    case 'fetch':
      return { activeTab: 'paths', activePathsTab: 'fetch' }
    default:
      return null
  }
}

export function normalizeEnemyDropsCalcsLocalState(
  value: unknown,
  fallback: EnemyDropsCalcsLocalState = defaultEnemyDropsCalcsLocalState(),
): EnemyDropsCalcsLocalState {
  const source = value && typeof value === 'object' ? value as Record<string, unknown> : {}

  const topTab = enemyDropsTopTabSchema.safeParse(source.activeTab)
  const legacyTab = migrateLegacyEnemyDropsActiveTab(source.activeTab)
  const pathsTab = enemyDropsPathsTabSchema.safeParse(source.activePathsTab)
  const legacyPathsTab = enemyDropsPathsTabSchema.safeParse(source.activeTab)

  const activeTab = topTab.success
    ? topTab.data
    : legacyTab?.activeTab ?? fallback.activeTab

  const activePathsTab = pathsTab.success
    ? pathsTab.data
    : legacyTab?.activePathsTab
      ?? (legacyPathsTab.success ? legacyPathsTab.data : fallback.activePathsTab)

  return {
    activeTab,
    activePathsTab,
    inputsExpanded: source.inputsExpanded === false ? false : (source.inputsExpanded === true || fallback.inputsExpanded),
  }
}

