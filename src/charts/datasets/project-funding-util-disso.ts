/**
 * Project Funding under Utility Dissonance, as a function of the Starting Cash lab.
 *
 * ## Why this chart exists
 *
 * Utility Dissonance disables the utility upgrades, so no cash is earned during
 * the run. Project Funding — "tower damage is multiplied by X% of the number of
 * digits in your current cash" — therefore reads one number and one number
 * only: whatever the Starting Cash lab granted at wave 1. On every other run
 * type the module scales with cash the player actually accumulates, and the lab
 * is a rounding error; on this one it is the whole input.
 *
 * ## What it is NOT
 *
 * Not the coin cost of the lab, and not a research plan. The question this
 * answers is "how much damage does the next band of Starting Cash levels buy",
 * which is a different question from whether those coins are better spent
 * elsewhere.
 *
 * ## Everything here is derived
 *
 * The rate per digit comes from `MODULE_TEMPLATES`, the starting cash per level
 * from the `starting_cash` lab in `LAB_CATALOG`, and the level cap from the lab
 * itself. Nothing is transcribed, so a rebalance to any of the three moves the
 * chart rather than silently disagreeing with it.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    PROJECT_FUNDING_RARITIES, projectFundingUtilDissoCash, projectFundingUtilDissoMultiplierData, projectFundingUtilDissoGainPer10Data
 * depends    src/charts/tables/types, src/data, src/mechanics/effective-paths/damage-base
 * used by    src/calculators/specs.generated, src/charts/datasets/index, src/charts/index, src/charts/tables/lookup
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { LAB_CATALOG, MODULE_TEMPLATES } from '../../data'
import { projectFundingCash, projectFundingMultiplier } from '../../mechanics/effective-paths/damage-base'
import type { SharedChartTableDataset } from '../tables/types'

/** The Starting Cash lab, which is the only cash a Utility Dissonance run has. */
const STARTING_CASH_LAB = LAB_CATALOG.find(lab => lab.slug === 'starting_cash')

/**
 * The rarities Project Funding can be, and the per-digit rate each pays.
 *
 * Read off the module's own `rarityBonuses` — a value per 100, because the
 * catalog stores the effect as the percentage the game's description quotes.
 * Ancestral is the ceiling: one module is equipped per category, and Project
 * Funding has no substat that reaches this effect.
 */
export const PROJECT_FUNDING_RARITIES: readonly { rarity: string, perDigitRate: number }[]
  = (MODULE_TEMPLATES.find(entry => entry.id === 'project-funding')?.rarityBonuses ?? [])
    .map(bonus => ({ rarity: bonus.rarity, perDigitRate: bonus.value / 100 }))

/** Starting cash at a lab level, which is what the module reads on this run. */
export function projectFundingUtilDissoCash(labLevel: number): number {
  return projectFundingCash('Util Disso', labLevel, 0)
}

/** Every tenth level, plus the cap — which is not a multiple of ten. */
function sampledLevels(): number[] {
  const max = STARTING_CASH_LAB?.levels.length ?? 0
  const levels: number[] = []
  for (let level = 0; level < max; level += 10) levels.push(level)
  if (levels[levels.length - 1] !== max) levels.push(max)
  return levels
}

interface ProjectFundingLevelRow {
  labLevel: number
  startingCash: number
  [rarity: string]: number
}

/** The damage multiplier the module contributes, by lab level and rarity. */
export const projectFundingUtilDissoMultiplierData: SharedChartTableDataset<ProjectFundingLevelRow> = {
  title: 'Project Funding Damage Multiplier by Starting Cash Lab Level (Utility Dissonance)',
  columns: [
    { key: 'labLevel', label: 'Starting Cash Lab Level' },
    { key: 'startingCash', label: 'Starting Cash' },
    ...PROJECT_FUNDING_RARITIES.map(({ rarity }) => ({ key: rarity, label: rarity })),
  ],
  rows: sampledLevels().map(labLevel => {
    const cash = projectFundingUtilDissoCash(labLevel)
    const row: ProjectFundingLevelRow = { labLevel, startingCash: cash }
    for (const { rarity, perDigitRate } of PROJECT_FUNDING_RARITIES) {
      row[rarity] = Number(projectFundingMultiplier({ perDigitRate, cash }).toFixed(3))
    }
    return row
  }),
}

interface ProjectFundingBandRow {
  labLevels: string
  startingCash: string
  [rarity: string]: string
}

/**
 * The damage GAINED across each band of ten levels.
 *
 * This is the column that answers the question people actually ask. The term is
 * `1 + rate × log10(cash)` over a cash figure that is linear in the level, so
 * the gain per level falls away steeply — the first ten levels are worth more
 * than levels 60 to 99 put together, at every rarity. Levels 40 to 99 together
 * still beat them, by roughly a quarter; the stronger claim was written here
 * first and the test caught it.
 */
export const projectFundingUtilDissoGainPer10Data: SharedChartTableDataset<ProjectFundingBandRow> = {
  title: 'Project Funding Damage Gained per 10 Starting Cash Lab Levels (Utility Dissonance)',
  columns: [
    { key: 'labLevels', label: 'Lab Levels' },
    { key: 'startingCash', label: 'Starting Cash' },
    ...PROJECT_FUNDING_RARITIES.map(({ rarity }) => ({ key: rarity, label: rarity })),
  ],
  rows: sampledLevels().slice(0, -1).map((from, index) => {
    const to = sampledLevels()[index + 1]
    const fromCash = projectFundingUtilDissoCash(from)
    const toCash = projectFundingUtilDissoCash(to)
    const row: ProjectFundingBandRow = {
      labLevels: `${from}-${to}`,
      startingCash: `${fromCash}-${toCash}`,
    }
    for (const { rarity, perDigitRate } of PROJECT_FUNDING_RARITIES) {
      const before = projectFundingMultiplier({ perDigitRate, cash: fromCash })
      const after = projectFundingMultiplier({ perDigitRate, cash: toCash })
      row[rarity] = `+${((after / before - 1) * 100).toFixed(2)}%`
    }
    return row
  }),
}
