/**
 * Every compartment, as one graph.
 *
 * Version 3: compartments, orthogonal claimType/verification, provenance with
 * source versions, and machine-comparable assertions.
 */
export const GAME_KNOWLEDGE: KnowledgeGraph = {
  version: 3,
  compartments: TOWER_COMPARTMENTS,
}

/** One entity by id, or `null` — never a guess. */
export function knowledgeFor(id: string): KnowledgeNode | null {
  return nodeById(GAME_KNOWLEDGE, id)
}

/** Everything asserted about an entity, in both directions. */
export function relationsOf(id: string): readonly KnowledgeEdge[] {
  return relationsOfIn(GAME_KNOWLEDGE, id)
}

/** Ids one hop away, in either direction. */
export function neighboursOf(id: string): readonly string[] {
  return neighboursOfIn(GAME_KNOWLEDGE, id)
}

/** Every trap recorded against an entity and its immediate relations. */
export function trapsFor(id: string): readonly string[] {
  return trapsForIn(GAME_KNOWLEDGE, id)
}

/** Traps split by whether they came from a fact or an opinion. */
export function trapsByClaimType(id: string) {
  return trapsByClaimTypeIn(GAME_KNOWLEDGE, id)
}

/** Free-text search across the whole graph. */
export function search(query: string, limit = 10) {
  return searchIn(GAME_KNOWLEDGE, query, limit)
}

/** Resolve a plain-language name to an entity id, or null below the confidence floor. */
export function resolve(query: string): string | null {
  return resolveIn(GAME_KNOWLEDGE, query)
}

/** Resolve, reporting confidence and alternatives. Prefer this where the answer drives a decision. */
export function resolveWithConfidence(query: string) {
  return resolveWithConfidenceIn(GAME_KNOWLEDGE, query)
}

/** Every `(subject, predicate)` asserted with more than one value. */
export function findContradictions(): readonly Contradiction[] {
  return findContradictionsIn(GAME_KNOWLEDGE)
}

/**
 * Maturity per compartment.
 *
 * `asOf` is required rather than defaulted to the clock: a metric that changes
 * when nothing changed cannot be tested, diffed, or trusted in a report.
 */
export function compartmentMaturity(asOf: string): readonly CompartmentMaturity[] {
  return scoreAll(GAME_KNOWLEDGE, asOf)
}

