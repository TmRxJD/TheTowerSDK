/**
 * tower-oracle — game knowledge for building correct tools.
 *
 * ## Shape
 *
 * ```
 * substrate/     repo-agnostic: schema, queries, maturity, contradictions
 * compartments/  The Tower's actual claims
 * index.ts       binds one to the other  ← you are here
 * ```
 *
 * The split is the design. A substrate entangled with its first content is a
 * bespoke system wearing a framework's name; keeping them apart is what lets
 * the substrate be lifted into another repo and pointed at different claims.
 *
 * ## Using it
 *
 * The convenience functions below close over `GAME_KNOWLEDGE` for ergonomics.
 * The substrate versions take a graph argument and are what you want if you
 * ever hold more than one graph — serving several agents, or diffing an
 * imported pack against local knowledge before accepting it.
 */
