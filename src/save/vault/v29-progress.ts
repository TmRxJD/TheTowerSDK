export interface VaultV29TrackerTarget {
  key: string
  maxLevel: number
}

/** VaultID → level key + max level (from catalog ladder length). */
export function buildVaultV29TrackerKeyIndex(): ReadonlyMap<number, VaultV29TrackerTarget> {
  const index = new Map<number, VaultV29TrackerTarget>()

  for (const upgrade of VAULT_V29_HARMONY.upgrades) {
    if (upgrade.vaultId == null) continue
    index.set(upgrade.vaultId, {
      key: vaultV29RowKey('harmony', upgrade.category, upgrade.name),
      maxLevel: Math.max(1, upgrade.levelCosts.length),
    })
  }
  for (const upgrade of VAULT_V29_POWER.upgrades) {
    if (upgrade.vaultId == null) continue
    index.set(upgrade.vaultId, {
      key: vaultV29RowKey('power', upgrade.category, upgrade.name),
      maxLevel: Math.max(1, upgrade.levelCosts.length),
    })
  }
  for (const upgrade of VAULT_V29_ENEMY.upgrades) {
    if (upgrade.vaultId == null) continue
    index.set(upgrade.vaultId, {
      key: vaultV29RowKey('enemy', upgrade.category, `${upgrade.enemy}:${upgrade.stat}`),
      maxLevel: Math.max(1, upgrade.levelCosts.length),
    })
  }

  return index
}

let cachedTrackerKeyIndex: ReadonlyMap<number, VaultV29TrackerTarget> | null = null

function trackerKeyIndex(): ReadonlyMap<number, VaultV29TrackerTarget> {
  if (!cachedTrackerKeyIndex) cachedTrackerKeyIndex = buildVaultV29TrackerKeyIndex()
  return cachedTrackerKeyIndex
}

function unwrapBackingField(container: Record<string, unknown>, logicalName: string): unknown {
  const direct = container[logicalName]
  if (direct !== undefined) return direct
  const backing = container[`<${logicalName}>k__BackingField`]
  if (backing !== undefined) return backing
  return undefined
}

function readUnlockedGroupIds(raw: unknown): number[] {
  if (!raw || typeof raw !== 'object') return []
  const record = raw as Record<string, unknown>
  const elements = Array.isArray(record.Elements)
    ? record.Elements
    : Array.isArray(record.elements)
      ? record.elements
      : Array.isArray(raw)
        ? raw
        : []
  const out: number[] = []
  for (const entry of elements) {
    const id = readSaveEnumValue(entry)
    if (id != null) out.push(Math.floor(id))
  }
  return out
}

function readUpgradeLevelPairs(raw: unknown): Array<{ vaultId: number; level: number }> {
  if (!raw || typeof raw !== 'object') return []
  const record = raw as Record<string, unknown>
  const pairs = Array.isArray(record.KeyValuePairs)
    ? record.KeyValuePairs
    : Array.isArray(record.keyValuePairs)
      ? record.keyValuePairs
      : []

  const out: Array<{ vaultId: number; level: number }> = []
  for (const pair of pairs) {
    if (!pair || typeof pair !== 'object') continue
    const entry = pair as Record<string, unknown>
    const vaultId = readSaveEnumValue(entry.key)
    const level = coerceSaveNumber(entry.value)
    if (vaultId == null || level == null) continue
    out.push({ vaultId: Math.floor(vaultId), level: Math.max(0, Math.floor(level)) })
  }
  return out
}

export interface VaultV29ProgressExtract {
  /** Level keys (`v29:…`) → purchased level. */
  levels: Record<string, number>
  unlockedGroupCount: number
  upgradeCount: number
  unknownVaultIds: number[]
  unknownGroups: number[]
  warnings: string[]
}

/**
 * Read `root.vault` into consumer-ready v29 level keys.
 * Returns null when the save has no `VaultPlayerProgress` object.
 */
export function readVaultV29ProgressFromSaveRoot(
  root: Record<string, unknown> | null,
): VaultV29ProgressExtract | null {
  if (!root) return null
  const vaultRaw = root.vault
  if (!vaultRaw || typeof vaultRaw !== 'object') return null

  const vault = vaultRaw as Record<string, unknown>
  const warnings: string[] = []
  const levels: Record<string, number> = {}
  const unknownVaultIds: number[] = []
  const unknownGroups: number[] = []
  const index = trackerKeyIndex()

  const groupIds = readUnlockedGroupIds(unwrapBackingField(vault, 'UnlockedGroups'))
  for (const groupId of groupIds) {
    const unlockKey = VAULT_V29_GROUP_UNLOCK_KEYS[groupId]
    if (!unlockKey) {
      unknownGroups.push(groupId)
      continue
    }
    levels[unlockKey] = 1
  }

  const upgrades = readUpgradeLevelPairs(unwrapBackingField(vault, 'UpgradesLevel'))
  for (const { vaultId, level } of upgrades) {
    if (level <= 0) continue
    const target = index.get(vaultId)
    if (!target) {
      unknownVaultIds.push(vaultId)
      continue
    }
    levels[target.key] = Math.min(target.maxLevel, level)
  }

  if (unknownGroups.length > 0) {
    warnings.push(`Unknown VaultGroup id(s): ${unknownGroups.join(', ')}`)
  }
  if (unknownVaultIds.length > 0) {
    warnings.push(`Unknown VaultID(s) not in v29 catalog: ${unknownVaultIds.join(', ')}`)
  }

  return {
    levels,
    unlockedGroupCount: groupIds.length,
    upgradeCount: upgrades.filter(row => row.level > 0).length,
    unknownVaultIds,
    unknownGroups,
    warnings,
  }
}
