/**
 * v29 vault progress lives on `PlayerData.vault` (`VaultPlayerProgress`):
 * `UnlockedGroups` (HashSet&lt;VaultGroup&gt;) and `UpgradesLevel` (Dictionary&lt;VaultID,int&gt;).
 *
 * The old `harmonyNodesUnlocked` / `powerNodesLevel` arrays still exist on the save but are
 * empty after the rework — reading only those arrays imports nothing for v29 vault progress.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    vaultV29RowKey, VAULT_V29_GROUP_UNLOCK_KEYS, VaultV29TrackerTarget, buildVaultV29TrackerKeyIndex, VaultV29ProgressExtract, readVaultV29ProgressFromSaveRoot
 * depends    src/data/generated/vault-v29.generated, src/save/access/values
 * used by    src/mechanics/calculators/specs-generated, src/save/vault/index, src/save/vault/read
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import {
  VAULT_V29_ENEMY,
  VAULT_V29_HARMONY,
  VAULT_V29_POWER,
} from '../../data/generated/vault-v29.generated'
import { coerceSaveNumber, readSaveEnumValue } from '../access/values'

/** Level key for a v29 vault row (matches the vault rowKey convention). */
export function vaultV29RowKey(tree: string, category: string, name: string): string {
  return `v29:${tree}:${category}:${name}`
}

