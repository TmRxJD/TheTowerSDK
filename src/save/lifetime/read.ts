function lifetimeImportValuesMatch(left: unknown, right: unknown): boolean {
  if (left == null && right == null) return true
  if (left == null || right == null) return false
  const a = String(left).trim().replace(/,/g, '')
  const b = String(right).trim().replace(/,/g, '')
  if (!a || !b) return a === b
  const numA = Number(a)
  const numB = Number(b)
  if (Number.isFinite(numA) && Number.isFinite(numB)) {
    return Math.floor(numA) === Math.floor(numB)
  }
  return a === b
}

export function countLifetimeImportFieldDifferences(
  importFields: LifetimeImportEntryFields,
  stored: LifetimeImportEntryFields,
): number {
  let diffCount = 0
  for (const key of LIFETIME_IMPORT_COMPARABLE_KEYS) {
    if (!lifetimeImportValuesMatch(importFields[key], stored[key])) {
      diffCount += 1
    }
  }
  return diffCount
}

export function findBestMatchingLifetimeEntryIndex(
  entries: readonly LifetimeStoredEntry[],
  fields: LifetimeImportEntryFields,
): { index: number; diffCount: number } {
  if (entries.length === 0) {
    return { index: -1, diffCount: LIFETIME_IMPORT_COMPARABLE_KEYS.length }
  }

  let bestIndex = 0
  let bestDiff = countLifetimeImportFieldDifferences(fields, entries[0]!)
  for (let index = 1; index < entries.length; index += 1) {
    const diffCount = countLifetimeImportFieldDifferences(fields, entries[index]!)
    if (diffCount < bestDiff) {
      bestDiff = diffCount
      bestIndex = index
    }
  }
  return { index: bestIndex, diffCount: bestDiff }
}

export function shouldApplyLifetimeImport(
  entries: readonly LifetimeStoredEntry[],
  fields: LifetimeImportEntryFields,
): boolean {
  if (entries.length === 0) return true
  const { diffCount } = findBestMatchingLifetimeEntryIndex(entries, fields)
  return diffCount >= LIFETIME_MIN_IMPORT_DIFF_COUNT
}

export function findLifetimeEntryIndexByGameStarted(
  entries: readonly LifetimeStoredEntry[],
  gameStarted: string,
): number {
  const key = normalizeLifetimeDate(gameStarted)
  if (!key) return -1
  return entries.findIndex(
    entry => normalizeLifetimeDate(entry.gameStarted) === key,
  )
}

export function upsertLifetimeImportEntry(
  entries: LifetimeStoredEntry[],
  fields: LifetimeImportEntryFields,
  createId: () => string,
): { nextEntries: LifetimeStoredEntry[]; entryId: string; created: boolean } {
  const normalized = normalizeLifetimeImportFields(fields)

  // Lifetime entries are time-series snapshots, so several legitimately share a
  // gameStarted date — it is not a unique key. Identity is therefore fuzzy: an
  // import that differs in fewer than LIFETIME_MIN_IMPORT_DIFF_COUNT stats is
  // treated as a re-import of an existing snapshot and skipped, while a
  // meaningfully different one becomes a new row.
  const { index, diffCount } = findBestMatchingLifetimeEntryIndex(entries, normalized)

  if (entries.length > 0 && diffCount < LIFETIME_MIN_IMPORT_DIFF_COUNT) {
    const existing = entries[index >= 0 ? index : 0]!
    return { nextEntries: entries.slice(), entryId: existing.id, created: false }
  }

  const entryId = createId()
  const nextEntry: LifetimeStoredEntry = {
    ...normalized,
    id: entryId,
    verified: false,
    blocked: false,
  }
  return { nextEntries: [nextEntry, ...entries], entryId, created: true }
}

export function canImportLifetimeFromSave(extract: LifetimeSaveExtract | null): boolean {
  if (!extract) return false
  return Boolean(extract.values.gameStarted)
    && Boolean(extract.values.coinsEarned || extract.values.cashEarned || extract.values.wavesCompleted)
}
