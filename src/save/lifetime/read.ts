export interface LifetimeSaveExtract {
  values: Record<string, string>
  warnings: string[]
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return !!value && typeof value === 'object' && !Array.isArray(value)
}

function readSaveField(root: Record<string, unknown>, key: string): unknown {
  return root[key] ?? null
}

function parseSaveNumericMagnitude(value: unknown): number | null {
  if (value === null || value === undefined) return null
  if (typeof value === 'number' && Number.isFinite(value)) return value

  if (typeof value === 'string' && value.trim() !== '') {
    const parsed = Number(value.trim().replace(/,/g, ''))
    return Number.isFinite(parsed) ? parsed : null
  }

  if (!isRecord(value)) return null

  if (value.__type === 'BigInt' && value.__value != null) {
    const parsed = Number(String(value.__value).replace(/,/g, ''))
    return Number.isFinite(parsed) ? parsed : null
  }

  if (typeof value.mantissa === 'number' && typeof value.exponent === 'number') {
    const magnitude = value.mantissa * (10 ** value.exponent)
    return Number.isFinite(magnitude) ? magnitude : null
  }

  if ('__value' in value) {
    return parseSaveNumericMagnitude(value.__value)
  }

  return coerceSaveNumber(value)
}

export function saveValueToNumericString(value: unknown): string {
  const magnitude = parseSaveNumericMagnitude(value)
  if (magnitude === null) return '0'
  if (Math.abs(magnitude) < 1000) {
    return normalizeNumericValue(String(Math.round(magnitude)))
  }
  return normalizeNumericValue(formatNumberForDisplay(magnitude))
}

function saveDateToIsoDay(value: unknown): string {
  const ms = parseSaveDateTimeToMs(value)
  if (ms == null) return ''
  const date = new Date(ms)
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  return normalizeLifetimeDate(`${year}-${month}-${day}`)
}

function readSaveValue(root: Record<string, unknown>, saveKey: string | readonly string[]): unknown {
  if (typeof saveKey === 'string') {
    return readSaveField(root, saveKey)
  }

  const parts = saveKey
    .map(key => coerceSaveNumber(readSaveField(root, key)))
    .filter((value): value is number => value !== null)

  if (!parts.length) return null
  return parts.reduce((sum, value) => sum + value, 0)
}

export function readLifetimeFromSaveRoot(parsedRoot: unknown): LifetimeSaveExtract | null {
  if (!parsedRoot || typeof parsedRoot !== 'object') return null

  const root = parsedRoot as Record<string, unknown>
  const warnings: string[] = []
  const values: Record<string, string> = {
    date: new Date().toISOString().split('T')[0],
  }

  let mappedCount = 0

  for (const row of LIFETIME_SAVE_FIELD_ROWS) {
    let raw = readSaveValue(root, row.saveKey)
    for (const older of row.renamedFrom ?? []) {
      if (raw !== null && raw !== undefined && raw !== '') break
      raw = readSaveValue(root, older)
    }
    if (raw === null || raw === undefined || raw === '') {
      if (!row.optional) {
        warnings.push(`Missing save field for ${row.label}.`)
      }
      continue
    }

    if (row.targetKey === 'gameStarted') {
      const isoDay = saveDateToIsoDay(raw)
      if (!isoDay) {
        warnings.push('Could not parse game started date from save.')
        continue
      }
      values.gameStarted = isoDay
      mappedCount += 1
      continue
    }

    values[row.targetKey] = saveValueToNumericString(raw)
    mappedCount += 1
  }

  // Not a root field — the game's own panel derives it from battle history
  // (mean of the three best run rates). Prefer that over a silent zero.
  if (!values.recentCoinsPerHour) {
    const inferred = computeCoinsPerHourFromSaveRoot(root)
    values.recentCoinsPerHour = inferred != null && inferred > 0
      ? saveValueToNumericString(inferred)
      : '0'
  }

  if (mappedCount === 0) return null

  return { values, warnings }
}

