export function clampBotStatLevel(botLabel: string, statIndex: number, level: number): number {
  const bot = bots.find(item => item.label === botLabel)
  if (!bot) return Math.max(0, Math.floor(level))
  const bounds = getBotStatBoundsByIndex(bot, statIndex)
  return Math.min(bounds.max, Math.max(bounds.min, Math.floor(level)))
}

export function clampBotPlusStatLevel(botLabel: string, statIndex: number, level: number): number {
  const bot = bots.find(item => item.label === botLabel)
  if (!bot) return Math.max(0, Math.floor(level))
  const bounds = getBotPlusStatBoundsByIndex(bot, statIndex)
  return Math.min(bounds.max, Math.max(bounds.min, Math.floor(level)))
}

export function buildBotsTrackerImportPayload(extract: BotsSaveExtract): BotsTrackerSaveImportPayload | null {
  if (!extract.bots.some(row => row.unlocked || row.statLevels.some(level => level > 0))) {
    if (!extract.levels.some(level => level > 0)) return null
  }

  const levels: Record<string, number[]> = {}
  const unlocked: Record<string, boolean> = {}
  const plusLevels: Record<string, number[]> = {}
  const plusUnlocked: Record<string, boolean> = {}

  bots.forEach((bot, index) => {
    const saveRow = extract.bots[index]
    const statLevels = saveRow?.statLevels ?? []
    const statCount = getBotStatValues(bot).length
    const isUnlocked = saveRow?.unlocked === true

    unlocked[bot.label] = isUnlocked
    plusUnlocked[bot.label] = saveRow?.plusUnlocked === true
    if (isUnlocked) {
      levels[bot.label] = Array.from({ length: statCount }, (_, statIndex) => (
        clampBotStatLevel(bot.label, statIndex, statLevels[statIndex] ?? 0)
      ))
    }

    const plusStatCount = getBotPlusStatValues(bot).length
    if (plusStatCount > 0) {
      const plusLevel = saveRow?.plusLevel ?? 0
      const isPlusUnlocked = plusUnlocked[bot.label] === true
      if (isPlusUnlocked) {
        plusLevels[bot.label] = Array.from({ length: plusStatCount }, (_, statIndex) => (
          clampBotPlusStatLevel(bot.label, statIndex, statIndex === 0 ? plusLevel : 0)
        ))
      }
    }
  })

  if (Object.keys(levels).length === 0 && !Object.values(unlocked).some(Boolean)) return null

  return {
    levels,
    unlocked,
    plusLevels: Object.keys(plusLevels).length ? plusLevels : undefined,
    plusUnlocked,
    labLevels: Object.keys(extract.labLevels).length ? extract.labLevels : undefined,
    activePreset: extract.currentPreset ?? undefined,
    presetNames: extract.presetNames.length ? extract.presetNames : undefined,
  }
}

export function applyBotsTrackerImportPayloadToSnapshot(
  current: Record<string, unknown>,
  payload: BotsTrackerSaveImportPayload,
): Record<string, unknown> {
  const next: Record<string, unknown> = { ...current }

  if (payload.levels) {
    const levels = { ...(typeof next.levels === 'object' && next.levels ? next.levels as Record<string, number[]> : {}) }
    const targets = { ...(typeof next.targets === 'object' && next.targets ? next.targets as Record<string, number[]> : {}) }
    for (const [botLabel, values] of Object.entries(payload.levels)) {
      if (!Array.isArray(values) || values.length === 0) continue
      levels[botLabel] = [...values]
      targets[botLabel] = [...values]
    }
    next.levels = levels
    next.targets = targets
  }

  if (payload.unlocked) {
    next.unlocked = {
      ...(typeof next.unlocked === 'object' && next.unlocked ? next.unlocked as Record<string, boolean> : {}),
      ...payload.unlocked,
    }
  }

  if (payload.plusUnlocked) {
    next.plusUnlocked = {
      ...(typeof next.plusUnlocked === 'object' && next.plusUnlocked ? next.plusUnlocked as Record<string, boolean> : {}),
      ...payload.plusUnlocked,
    }
  }

  if (payload.plusLevels) {
    const plusLevels = { ...(typeof next.plusLevels === 'object' && next.plusLevels ? next.plusLevels as Record<string, number[]> : {}) }
    const plusTargets = { ...(typeof next.plusTargets === 'object' && next.plusTargets ? next.plusTargets as Record<string, number[]> : {}) }
    for (const [botLabel, values] of Object.entries(payload.plusLevels)) {
      if (!Array.isArray(values) || values.length === 0) continue
      if (payload.plusUnlocked?.[botLabel] !== true) continue
      plusLevels[botLabel] = [...values]
      plusTargets[botLabel] = [...values]
    }
    next.plusLevels = plusLevels
    next.plusTargets = plusTargets
  }

  if (payload.labLevels) {
    next.labLevels = {
      ...(typeof next.labLevels === 'object' && next.labLevels ? next.labLevels as Record<string, unknown> : {}),
      ...payload.labLevels,
    }
  }

  if (payload.presetNames?.length || payload.activePreset !== undefined) {
    const ui = typeof next.ui === 'object' && next.ui ? { ...(next.ui as Record<string, unknown>) } : {}
    if (payload.activePreset !== undefined) {
      ui.activePreset = payload.activePreset
    }
    if (payload.presetNames?.length) {
      const presets = Array.isArray(ui.presets) ? [...ui.presets as Array<Record<string, unknown>>] : []
      for (let index = 0; index < Math.min(BOT_SAVE_PRESET_COUNT, payload.presetNames.length); index += 1) {
        const name = payload.presetNames[index]?.trim()
        if (!name) continue
        const existing = presets[index] && typeof presets[index] === 'object'
          ? { ...(presets[index] as Record<string, unknown>) }
          : { name: `Preset ${index + 1}` }
        presets[index] = { ...existing, name }
      }
      ui.presets = presets
    }
    next.ui = ui
  }

  return next
}
