function readUserBotDataRow(raw: unknown): UserBotDataSaveRow {
  if (!raw || typeof raw !== 'object') {
    return {
      unlocked: false,
      active: false,
      levels: [],
      selectedLevels: [],
      plusUnlocked: false,
      plusLevel: 0,
    }
  }

  const record = raw as Record<string, unknown>
  const levels = toNumberArrayPreserveLength(record.levels, BOT_SAVE_STAT_STRIDE)
  const selectedLevels = toNumberArrayPreserveLength(
    record.selectedLevels ?? record.levels,
    BOT_SAVE_STAT_STRIDE,
  )

  return {
    unlocked: readSaveBoolean(record.unlocked),
    active: readSaveBoolean(record.active),
    levels: remapBotLevelsFromGameSaveOrder(levels),
    selectedLevels: remapBotLevelsFromGameSaveOrder(selectedLevels),
    plusUnlocked: readSaveBoolean(record.plusUnlocked),
    plusLevel: coerceSaveNumber(record.plusLevel) ?? 0,
  }
}

function readBotCooldownLabLevels(root: Record<string, unknown>): Record<string, BotLabLevels> {
  const labLevels: Record<string, BotLabLevels> = {}

  bots.forEach(bot => {
    const key = BOT_COOLDOWN_LAB_SELECTED_KEYS[bot.label]
    if (!key) return

    const level = coerceSaveNumber(root[key])
    if (level === null || level <= 0) return

    labLevels[bot.label] = {
      ...(labLevels[bot.label] ?? {}),
      Cooldown: level,
    }
  })

  return labLevels
}

function readUserBotPresetList(raw: unknown): UserBotDataSaveRow[] {
  return readListItems(raw).map(readUserBotDataRow)
}

function resolvePresetIndex(root: Record<string, unknown>): number {
  const presetNames = readStringArray(root[BOTS_SAVE_PRESET_NAME_KEY])
  const maxPresetIndex = Math.max(presetNames.length, BOT_SAVE_PRESET_COUNT) - 1
  const current = coerceSaveNumber(root[BOTS_SAVE_CURRENT_PRESET_KEY]) ?? 0
  return Math.max(0, Math.min(maxPresetIndex, current))
}

function hasLegacyBotProgress(unlocked: boolean[], levels: number[]): boolean {
  return unlocked.some(Boolean) || levels.some(level => level > 0)
}

function hasV28BotProgress(root: Record<string, unknown>): boolean {
  return BOT_V28_PRESET_LIST_KEYS.some(key => {
    const rows = readUserBotPresetList(root[key])
    return rows.some(row => row.unlocked || row.active || row.levels.some(level => level > 0))
  })
}

function shouldUseV28BotData(root: Record<string, unknown>): boolean {
  if (readSaveBoolean(root[BOTS_SAVE_MIGRATED_V28_KEY])) return true
  return hasV28BotProgress(root)
}

function buildBotRowsFromV28(root: Record<string, unknown>, presetIndex: number): BotSaveRow[] {
  return bots.map((bot, index) => {
    const listKey = BOT_V28_PRESET_LIST_KEYS[index]
    const presetRows = listKey ? readUserBotPresetList(root[listKey]) : []
    const activeRow = presetRows[presetIndex] ?? readUserBotDataRow(null)

    const statLevels = mergeLevelRows(activeRow.selectedLevels, activeRow.levels)
    const unlocked = activeRow.unlocked

    return {
      index,
      name: findBotCatalogRow(index)?.name ?? bot.name ?? null,
      label: getBotSaveLabel(index) || bot.label,
      unlocked,
      active: activeRow.active,
      statLevels,
      plusUnlocked: activeRow.plusUnlocked,
      plusLevel: activeRow.plusLevel,
    }
  })
}

