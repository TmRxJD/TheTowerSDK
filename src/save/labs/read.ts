import { estimateLabLevelRemainingSeconds } from './remaining'
import { findLabResearchByIndex } from '../../data/labs/research'

import { RESEARCH_CATEGORY_ENUM } from '../../data/player-stats/fields.data'
import {
  findLabResearchCategory,
  findLabResearchDisplayName,
  findLabResearchImportRow,
  findLabResearchSlug,
  labResearchImportRowCount,
} from '../../data/labs/display-overrides'
import { coerceSaveNumber } from '../access/values'
import { readFavoriteLabSlugsFromSaveRoot, saveHasFavoriteLabs } from './favorites'
import type { LabQueueSaveRow, LabResearchSaveRow, LabsSaveExtract } from './types'

export const LABS_SAVE_UNLOCKED_KEY = 'labsUnlocked'
export const LABS_SAVE_RESEARCH_LEVEL_KEY = 'researchLevel'
export const LABS_SAVE_RESEARCH_PERCENT_KEY = 'researchPercentComplete'
export const LABS_SAVE_LAB_LEVEL_KEY = 'labLevel'
export const LABS_SAVE_LAB_RESEARCH_INT_KEY = 'labResearchInt'
export const LABS_SAVE_LAB_ACTIVE_KEY = 'labActiveBool'
export const LABS_SAVE_LAB_SPEED_UP_SPEED_KEY = 'labSpeedUpSpeed'
export const LABS_SAVE_LAB_SPEED_UP_REMAINING_KEY = 'labSpeedUpRemainingSeconds'
export const LABS_SAVE_RESEARCHES_COMPLETE_KEY = 'researchesComplete'
export const LABS_SAVE_COINS_SPENT_KEY = 'totalCoinsSpentOnResearch'

function readSaveBoolean(value: unknown): boolean {
  return value === true
}

export function computeLabResearchLevelMax(index: number): number {
  return findLabResearchByIndex(index)?.levelMax ?? 99
}

export function isLabResearchMaxed(index: number, level: number): boolean {
  return level >= computeLabResearchLevelMax(index)
}

function readResearchRow(
  index: number,
  level: number,
  percentComplete: number | null,
  labSpeedLevel = 0,
): LabResearchSaveRow {
  const catalog = findLabResearchImportRow(index)
  const displayName = findLabResearchDisplayName(index, catalog?.displayName ?? null)
  const slug = findLabResearchSlug(index, catalog?.slug ?? null)
  const category = findLabResearchCategory(index, displayName, catalog?.category ?? null)
  return {
    index,
    level,
    displayName,
    slug,
    category,
    gameField: catalog?.gameField ?? null,
    percentComplete,
    remainingSeconds: estimateLabLevelRemainingSeconds(displayName, level, percentComplete, labSpeedLevel),
  }
}

export function readLabsFromSaveRoot(root: Record<string, unknown> | null): LabsSaveExtract | null {
  if (!root) return null

  const warnings: string[] = []
  const readPositions = (key: string): (number | null)[] => {
    const raw = root[key]
    if (!Array.isArray(raw)) return []
    return Array.from(raw, (value, index) => {
      const number = coerceSaveNumber(value)
      if (number === null) warnings.push(`${key}[${index}] is unreadable; its position is preserved as unknown.`)
      return number
    })
  }
  const researchLevels = readPositions(LABS_SAVE_RESEARCH_LEVEL_KEY)
  const researchPercents = readPositions(LABS_SAVE_RESEARCH_PERCENT_KEY)
  if (researchLevels.length === 0) {
    warnings.push('No researchLevel array found in save.')
  }
  if (researchLevels.length > 0 && researchLevels.length !== labResearchImportRowCount()) {
    const expected = labResearchImportRowCount()
    if (researchLevels.length < expected) {
      warnings.push(
        `researchLevel has ${researchLevels.length} entries; catalog has ${expected}. `
          + `Labs ${researchLevels.length}-${expected - 1} are absent from this save, not unresearched.`,
      )
    } else {
      warnings.push(
        `researchLevel has ${researchLevels.length} entries; catalog expects ${expected}.`,
      )
    }
  }

  const researches = researchLevels.flatMap((level, index) => level === null ? [] : [readResearchRow(
    index,
    level,
    researchPercents[index] ?? null,
  )])
  const researchedCount = researches.filter(row => row.level > 0).length
  const maxedCount = researches.filter(row => isLabResearchMaxed(row.index, row.level)).length
  const namedResearchCount = researches.filter(row => row.displayName).length
  const hiddenUnnamedCount = researches.filter(row => !row.displayName).length

  const labLevels = readPositions(LABS_SAVE_LAB_LEVEL_KEY)
  const labResearchInts = readPositions(LABS_SAVE_LAB_RESEARCH_INT_KEY)
  const hasActiveQueueData = Array.isArray(root[LABS_SAVE_LAB_RESEARCH_INT_KEY]) && Array.isArray(root[LABS_SAVE_LAB_ACTIVE_KEY])
  if (labLevels.length > 0 && !hasActiveQueueData) {
    warnings.push('Active lab queue fields are not included in this save/export; researched levels remain readable.')
  }
  const labActive = Array.isArray(root[LABS_SAVE_LAB_ACTIVE_KEY])
    ? (root[LABS_SAVE_LAB_ACTIVE_KEY] as unknown[]).map(readSaveBoolean)
    : []
  const speedUpSpeed = readPositions(LABS_SAVE_LAB_SPEED_UP_SPEED_KEY)
  const speedUpRemainingSeconds = readPositions(LABS_SAVE_LAB_SPEED_UP_REMAINING_KEY)

  const slotCount = hasActiveQueueData ? Math.max(labLevels.length, labResearchInts.length, labActive.length, speedUpSpeed.length) : 0
  const activeQueue: LabQueueSaveRow[] = []
  for (let slotIndex = 0; slotIndex < slotCount; slotIndex += 1) {
    const rawResearchInt = labResearchInts[slotIndex]
    const researchInt = rawResearchInt != null && Number.isInteger(rawResearchInt) && rawResearchInt >= 0 ? rawResearchInt : null
    if (rawResearchInt != null && researchInt === null) warnings.push(`labResearchInt[${slotIndex}] is not a valid research index.`)
    const slotSpeed = speedUpSpeed[slotIndex] ?? null
    activeQueue.push({
      slotIndex,
      labLevel: labLevels[slotIndex] ?? null,
      researchInt,
      active: labActive[slotIndex] ?? false,
      speedUp: slotSpeed,
      speedUpRemainingSeconds: speedUpRemainingSeconds[slotIndex] ?? null,
      research: researchInt === null || researchLevels[researchInt] == null
        ? null
        : readResearchRow(
          researchInt,
          researchLevels[researchInt] ?? 0,
          researchPercents[researchInt] ?? null,
          slotSpeed ?? 0,
        ),
    })
  }

  return {
    labsUnlocked: coerceSaveNumber(root[LABS_SAVE_UNLOCKED_KEY]),
    researchesComplete: coerceSaveNumber(root[LABS_SAVE_RESEARCHES_COMPLETE_KEY]),
    totalCoinsSpentOnResearch: root[LABS_SAVE_COINS_SPENT_KEY] ?? null,
    speedUpSpeed,
    speedUpRemainingSeconds,
    activeQueue,
    hasActiveQueueData,
    researches,
    researchedCount,
    maxedCount,
    namedResearchCount,
    hiddenUnnamedCount,
    favoriteLabs: readFavoriteLabSlugsFromSaveRoot(root),
    hasFavoriteLabs: saveHasFavoriteLabs(root),
    warnings,
  }
}

export function formatLabResearchLabel(row: LabResearchSaveRow): string {
  if (row.displayName) return row.displayName
  if (row.slug) return row.slug.replace(/_/g, ' ')
  if (row.gameField) return row.gameField
  return `Research #${row.index}`
}

export function researchCategoryLabel(category: string | null | undefined): string {
  if (!category) return 'Other'
  const normalized = category.trim()
  const match = RESEARCH_CATEGORY_ENUM.find(
    entry => entry.name.toLowerCase() === normalized.toLowerCase(),
  )
  return match?.name ?? normalized
}
