function sliceBotStatLevelsForAllBots(flatLevels: number[]): number[][] {
  return bots.map((bot, index) => {
    const start = index * BOT_SAVE_STAT_STRIDE
    const statCount = getBotStatValues(bot).length
    const rawChunk = flatLevels.slice(start, start + statCount)
    return remapBotLevelsFromGameSaveOrder(rawChunk)
  })
}

function resolveUnlockSlotCount(root: Record<string, unknown>): number {
  const candidates = [
    root[BOTS_SAVE_UNLOCKED_KEY],
    root[BOTS_SAVE_UNLOCKED_PRESETS_KEY],
    root[BOTS_SAVE_ACTIVE_KEY],
    root[BOTS_SAVE_ACTIVE_PRESETS_KEY],
  ]
  let maxLength: number = BOT_IMPORT_CATALOG.length
  for (const raw of candidates) {
    if (Array.isArray(raw)) {
      maxLength = Math.max(maxLength, raw.length)
      if (Array.isArray(raw[0])) {
        for (const row of raw) {
          if (Array.isArray(row)) maxLength = Math.max(maxLength, row.length)
        }
      }
    }
  }
  return maxLength
}

function resolveLegacyBotLevelRow(root: Record<string, unknown>, presetIndex: number, warnings: string[]): number[] {
  const presetMatrix = normalizeSaveMatrix(
    root[BOTS_SAVE_LEVEL_PRESETS_KEY],
    BOT_SAVE_PRESET_COUNT,
    BOT_SAVE_LEVEL_SLOT_COUNT,
  )
  const selectionMatrix = normalizeSaveMatrix(
    root[BOTS_SAVE_LEVEL_SELECTION_PRESETS_KEY],
    BOT_SAVE_PRESET_COUNT,
    BOT_SAVE_LEVEL_SLOT_COUNT,
  )
  const liveRow = toNumberArrayPreserveLength(root[BOTS_SAVE_LEVEL_KEY], BOT_SAVE_LEVEL_SLOT_COUNT)
  const allRows = [...presetMatrix, ...selectionMatrix, liveRow]

  const activeRow = presetMatrix[presetIndex]
    ?? selectionMatrix[presetIndex]
    ?? []

  if (activeRow.length > 0 && activeRow.every(level => level <= 0) && sumLevelRow(mergeLevelRows(...allRows)) > 0) {
    warnings.push(
      `Active bot preset ${presetIndex + 1} has no upgrades in legacy arrays; using the strongest preset row from your save.`,
    )
  }

  if (sumLevelRow(activeRow) > 0) {
    return mergeLevelRows(activeRow, selectionMatrix[presetIndex] ?? [], liveRow)
  }

  let bestRow = activeRow
  let bestScore = sumLevelRow(bestRow)
  for (const row of allRows) {
    const score = sumLevelRow(row)
    if (score > bestScore) {
      bestRow = row
      bestScore = score
    }
  }

  return mergeLevelRows(bestRow, liveRow)
}

function resolveLegacyBotUnlockedRow(root: Record<string, unknown>, presetIndex: number): boolean[] {
  const slotCount = resolveUnlockSlotCount(root)
  const presetMatrix = normalizeSaveBooleanMatrix(
    root[BOTS_SAVE_UNLOCKED_PRESETS_KEY],
    BOT_SAVE_PRESET_COUNT,
    slotCount,
  )
  const flatRow = readBooleanRow(root[BOTS_SAVE_UNLOCKED_KEY], slotCount)
  const activePresetRow = presetMatrix[presetIndex] ?? []
  return mergeBooleanRows(flatRow, activePresetRow)
}

function resolveLegacyBotActiveRow(root: Record<string, unknown>, presetIndex: number): boolean[] {
  const slotCount = resolveUnlockSlotCount(root)
  const presetMatrix = normalizeSaveBooleanMatrix(
    root[BOTS_SAVE_ACTIVE_PRESETS_KEY],
    BOT_SAVE_PRESET_COUNT,
    slotCount,
  )
  const flatRow = readBooleanRow(root[BOTS_SAVE_ACTIVE_KEY], slotCount)
  const activePresetRow = presetMatrix[presetIndex] ?? []
  return mergeBooleanRows(flatRow, activePresetRow)
}

function buildLegacyBotRows(
  unlocked: boolean[],
  active: boolean[],
  flatLevels: number[],
): BotSaveRow[] {
  const statSlices = sliceBotStatLevelsForAllBots(flatLevels)
  const slotCount = Math.max(
    unlocked.length,
    active.length,
    statSlices.length,
    BOT_IMPORT_CATALOG.length,
  )

  return Array.from({ length: slotCount }, (_, index) => {
    const statLevels = statSlices[index] ?? []
    return {
      index,
      name: findBotCatalogRow(index)?.name ?? null,
      label: getBotSaveLabel(index),
      unlocked: unlocked[index] === true,
      active: active[index] ?? false,
      statLevels,
      plusUnlocked: false,
      plusLevel: 0,
    }
  })
}

function buildLegacyPresetExtracts(root: Record<string, unknown>, warnings: string[]): BotPresetSaveExtract[] {
  const presetNames = readStringArray(root[BOTS_SAVE_PRESET_NAME_KEY])
  const activePresetIndex = resolvePresetIndex(root)

  return Array.from({ length: BOT_SAVE_PRESET_COUNT }, (_, index) => {
    const presetWarnings = index === activePresetIndex ? warnings : []
    const unlocked = resolveLegacyBotUnlockedRow(root, index)
    const active = resolveLegacyBotActiveRow(root, index)
    const levels = resolveLegacyBotLevelRow(root, index, presetWarnings)

    return {
      index,
      name: presetNames[index]?.trim() || `Preset ${index + 1}`,
      bots: buildLegacyBotRows(unlocked, active, levels),
    }
  })
}

function snapshotFromPreset(preset: BotPresetSaveExtract): Pick<BotsSaveExtract, 'bots' | 'unlocked' | 'active' | 'levels'> {
  return {
    bots: preset.bots,
    unlocked: preset.bots.map(row => row.unlocked),
    active: preset.bots.map(row => row.active),
    levels: preset.bots.flatMap(row => row.statLevels),
  }
}

export function findBotsExtractForPreset(
  extract: BotsSaveExtract | null,
  presetIndex: number,
): BotsSaveExtract | null {
  if (!extract) return null
  const preset = extract.presets[presetIndex]
  if (!preset) return extract

  return {
    ...extract,
    ...snapshotFromPreset(preset),
  }
}

export function readBotsFromSaveRoot(root: Record<string, unknown> | null): BotsSaveExtract | null {
  if (!root) return null

  const warnings: string[] = []
  const presetIndex = resolvePresetIndex(root)
  const usesV28BotData = shouldUseV28BotData(root)

  const labLevels = readBotCooldownLabLevels(root)

  if (usesV28BotData) {
    const presets = buildV28PresetExtracts(root)
    const activePresetIndex = presetIndex
    const activePreset = presets[activePresetIndex] ?? presets[0]
    const snapshot = activePreset ? snapshotFromPreset(activePreset) : { bots: [], unlocked: [], active: [], levels: [] }

    if (!presets.some(preset => preset.bots.some(row => row.unlocked || row.statLevels.some(level => level > 0)))) {
      warnings.push('No bot upgrade data found in v28 UserBotData preset lists.')
    }

    return {
      currentPreset: coerceSaveNumber(root[BOTS_SAVE_CURRENT_PRESET_KEY]),
      presetNames: readStringArray(root[BOTS_SAVE_PRESET_NAME_KEY]),
      totalCoins: root[BOTS_SAVE_COINS_KEY] ?? null,
      totalDamage: root[BOTS_SAVE_DAMAGE_KEY] ?? null,
      totalStuns: root[BOTS_SAVE_STUNS_KEY] ?? null,
      totalStonesSpent: root[BOTS_SAVE_STONES_SPENT_KEY] ?? null,
      totalMedalsSpent: root[BOTS_SAVE_MEDALS_SPENT_KEY] ?? null,
      ...snapshot,
      presets,
      labLevels,
      synchronicity: readBotSynchronicityFromSaveRoot(root),
      usesV28BotData: true,
      warnings,
    }
  }

  const presets = buildLegacyPresetExtracts(root, warnings)
  const activePreset = presets[presetIndex] ?? presets[0]
  const snapshot = activePreset ? snapshotFromPreset(activePreset) : { bots: [], unlocked: [], active: [], levels: [] }
  const unlocked = snapshot.unlocked
  const levels = snapshot.levels

  if (!hasLegacyBotProgress(unlocked, levels)) {
    warnings.push('No bot arrays found in save (botsUnlocked, botsActive, botsLevel).')
  }

  if (!IMPORT_CATALOG_META.populated.bots) {
    warnings.push('Bot name catalog is not imported from game data yet.')
  } else if (unlocked.length > BOT_IMPORT_CATALOG.length) {
    // Shorter arrays are older saves missing later bots (e.g. Bot Bot) — not a fault.
    warnings.push(
      `botsUnlocked has ${unlocked.length} entries; catalog expects ${BOT_IMPORT_CATALOG.length}.`,
    )
  }

  return {
    currentPreset: coerceSaveNumber(root[BOTS_SAVE_CURRENT_PRESET_KEY]),
    presetNames: readStringArray(root[BOTS_SAVE_PRESET_NAME_KEY]),
    totalCoins: root[BOTS_SAVE_COINS_KEY] ?? null,
    totalDamage: root[BOTS_SAVE_DAMAGE_KEY] ?? null,
    totalStuns: root[BOTS_SAVE_STUNS_KEY] ?? null,
    totalStonesSpent: root[BOTS_SAVE_STONES_SPENT_KEY] ?? null,
    totalMedalsSpent: root[BOTS_SAVE_MEDALS_SPENT_KEY] ?? null,
    ...snapshot,
    presets,
    labLevels,
    synchronicity: readBotSynchronicityFromSaveRoot(root),
    usesV28BotData: false,
    warnings,
  }
}

export function countBotPlusUnlocksFromSaveExtract(extract: BotsSaveExtract): number {
  return extract.bots.filter(row => row.plusUnlocked).length
}

/**
 * Synchronicity from `synchronicityUnlocked`, `synchronicityLevel` and the active preset's
 * `synchronicityBots` — the fields the game writes. A save from before synchronicity has none
 * of them and reads as locked.
 *
 * `synchronicityBots` is by SLOT, not by bot: each entry is the bot type sitting in that slot, or
 * null for an empty one, and the game finds a bot by searching the array. The bot type is the
 * bot's catalog `index` — 0 Flame Bot through 4 Bot Bot. The active preset is `currentBotPreset`.
 */
export function readBotSynchronicityFromSaveRoot(
  root: Record<string, unknown> | null | undefined,
): BotSynchronicitySaveExtract {
  const inSave = Boolean(root) && ['synchronicityUnlocked', 'synchronicityLevel', 'synchronicityPresets', 'synchronicityBots']
    .some(key => Object.prototype.hasOwnProperty.call(root, key))
  const unlocked = root ? readSaveBoolean(root.synchronicityUnlocked) : false
  const level = Math.max(0, Math.trunc(coerceSaveNumber(root?.synchronicityLevel) ?? 0))
  const slotCount = unlocked ? Math.min(BOT_SYNC_SLOT_UPGRADE_COSTS.length, level + 2) : 0
  const unrecognizedSlotValues: unknown[] = []
  const activeSlots = root ? activeSynchronicityBots(root) : []
  const slots = activeSlots.map(value => {
    if (value === null || value === undefined) return null
    const label = botLabelForSaveBotType(value)
    if (label === null) unrecognizedSlotValues.push(value)
    return label
  })
  const syncedBots = slots.filter((label): label is string => label !== null)
  return {
    inSave,
    unlocked,
    level,
    slotCount,
    slots,
    bots: syncedBots,
    occupiedSlots: activeSlots.slice(0, slotCount).filter(slot => slot !== null && slot !== undefined).length,
    unrecognizedSlotValues,
    stonesSpentOnBetaSynchronicity: coerceSaveNumber(root?.stonesSpentOnBetaSynchronicity) ?? 0,
  }
}

/** A save bot type — a number, or the decoder's boxed `{ value__ }` — as a bot label, or null. */
function botLabelForSaveBotType(value: unknown): string | null {
  const type = typeof value === 'number'
    ? value
    : value && typeof value === 'object'
      ? (value as Record<string, unknown>).value__
      : undefined
  if (typeof type !== 'number' || !Number.isSafeInteger(type)) return null
  const label = findBotCatalogRow(type)?.label
  return label && bots.some(bot => bot.label === label) ? label : null
}

function activeSynchronicityBots(root: Record<string, unknown>): unknown[] {
  const preset = readListItems(root.synchronicityPresets)[resolvePresetIndex(root)]
  const fromPreset = preset && typeof preset === 'object'
    ? (preset as Record<string, unknown>).synchronicityBots
    : undefined
  const slots = fromPreset ?? root.synchronicityBots
  return Array.isArray(slots) ? slots : []
}

/** How many synchronicity slots the save owns — `synchronicityLevel + 2` once unlocked. */
export function countBotSyncUnlocksFromSaveRoot(root: Record<string, unknown> | null | undefined): number {
  return readBotSynchronicityFromSaveRoot(root).slotCount
}

/**
 * Stones spent on Bots+ and synchronicity, from per-bot flags.
 *
 * Synchronicity is priced by slots, not by bot: each flagged bot needs a slot, so the flags are
 * counted as the slots owned and priced with {@link sumBotSyncSlotCosts}.
 */
export function computeBotsStonesSpent(
  plusUnlocked: Record<string, boolean>,
  syncUnlocked: Record<string, boolean>,
): number {
  let plus = 0
  let synced = 0
  for (const bot of bots) {
    if (plusUnlocked[bot.label]) plus += BOT_PLUS_UNLOCK_COST
    if (syncUnlocked[bot.label]) synced += 1
  }
  return plus + sumBotSyncSlotCosts(synced)
}

export function readBotsPlusAndSyncStonesSpent(
  extract: BotsSaveExtract,
  root?: Record<string, unknown> | null,
): number {
  const plusStones = sumBotPlusUnlockCosts(countBotPlusUnlocksFromSaveExtract(extract))
  const syncStones = sumBotSyncSlotCosts(countBotSyncUnlocksFromSaveRoot(root))
  return plusStones + syncStones
}

/** Medals spent on bot unlocks and stat upgrades (matches the in-game summary). */
export function readBotsMedalsSpentFromSave(extract: BotsSaveExtract): number {
  let total = 0
  const unlockedBotLabels = bots
    .filter((bot, index) => extract.bots[index]?.unlocked === true)
    .map(bot => bot.label)
  const unlockOrdinals = buildBotUnlockOrdinalByLabel(unlockedBotLabels)

  bots.forEach((bot, index) => {
    const row = extract.bots[index]
    if (!row) return

    if (row.unlocked) {
      const unlockOrdinal = unlockOrdinals.get(bot.label) ?? 0
      total += getBotUnlockCost(unlockOrdinal)
    }

    const labLevels = extract.labLevels[bot.label] ?? {}
    normalizeBotStats(bot, labLevels).forEach((stat, statIndex) => {
      const bounds = getBotStatBoundsByIndex(bot, statIndex)
      const current = clampBotStatLevel(bot.label, statIndex, row.statLevels[statIndex] ?? 0)
      if (current <= bounds.min) return
      total += sumBotStatCostsBetween(stat, bounds.min - 1, current - 1)
    })

    if (row.plusUnlocked) {
      normalizeBotPlusStats(bot).forEach((stat, statIndex) => {
        const bounds = getBotPlusStatBoundsByIndex(bot, statIndex)
        const rawLevel = statIndex === 0 ? (row.plusLevel ?? 0) : 0
        const current = clampBotPlusStatLevel(bot.label, statIndex, rawLevel)
        if (current <= bounds.min) return
        total += sumBotStatCostsBetween(stat, bounds.min - 1, current - 1)
      })
    }
  })
  return total
}

export { BOT_PLUS_UNLOCK_COST, BOT_SYNC_SLOT_COST }

export function clampBotStatLevel(botLabel: string, statIndex: number, level: number): number {
  const bot = bots.find(item => item.label === botLabel)
  if (!bot) return Math.max(0, Math.floor(level))
  const bounds = getBotStatBoundsByIndex(bot, statIndex)
  return Math.min(bounds.max, Math.max(bounds.min, Math.floor(level)))
}

export function clampBotPlusStatLevel(botLabel: string, statIndex: number, level: number): number {
  const bot = bots.find(item => item.label === botLabel)
  if (!bot) return Math.max(0, Math.floor(level))
  const bounds = getBotPlusStatBoundsByIndex(bot, statIndex)
  return Math.min(bounds.max, Math.max(bounds.min, Math.floor(level)))
}
