/**
 * Where a module's or card's artwork lives.
 *
 * **The images are not in this package.** They are artwork from The Tower, owned by
 * TechTree Games, and they live in [`tower-assets`](https://www.npmjs.com/package/tower-assets),
 * which claims no licence over them and asserts no authorship. What ships here is the
 * mapping — which file belongs to which module or card — because a list of filenames is not
 * artwork, and it is the part that is genuinely hard to get right.
 *
 * ```bash
 * npm install tower-assets
 * ```
 *
 * ```ts
 * import { moduleAssetPath, cardAssetPath } from 'thetowersdk/assets'
 *
 * moduleAssetPath('Om Chip')          // 'assets/site/modules_core/epic_oc.png'
 * cardAssetPath('slow-aura')          // 'assets/site/cards/sa.jpg'
 * ```
 *
 * ## Why this is not a string template
 *
 * A module's file is named after its **initials** and its rarity prefix, not its id or its
 * name — `Om Chip` at Epic is `epic_oc.png`. Cards are named after their id, except
 * where they are not: `slow-aura` is stored as `sa.jpg`.
 *
 * Both failures are silent. A wrong path yields a missing image, and a missing image does
 * not throw — it renders as nothing, on one card, for one rarity, and nobody notices until
 * a player mentions it. Every function here returns `null` for something that does not
 * exist, so a caller can tell the difference between "no art" and "wrong path".
 *
 * The manifest is generated by scanning `tower-assets`, so an added or renamed file moves it
 * rather than quietly disagreeing with it.
 */
import { getModuleTemplate, MODULE_TEMPLATES } from '../data/index'
import { ownLookup } from '../internal/own-lookup'
import {
  CARD_ASSET_DIR,
  CARD_ASSET_FILES,
  CARD_ID_ALIASES,
  MODULE_ASSET_DIRS,
  MODULE_ASSET_FILES,
} from './manifest.generated'

export * from './manifest.generated'

/** Root the paths are relative to, inside the `tower-assets` package. */
export const TOWER_ASSETS_ROOT = 'assets/site'

/** Normalise a rarity to the prefix used in a module filename: `Epic+` → `epic`. */
function rarityPrefix(rarity: string): string {
  return rarity.toLowerCase().replace(/[^a-z]/g, '')
}

/** Normalise initials the way the filenames are written. */
function initialsKey(initials: string): string {
  return initials.replace(/[^a-z0-9]/gi, '').toLowerCase()
}

/**
 * Rarity as it appears in a FRAME filename.
 *
 * Frames are per-rarity chrome drawn around any module, so they follow a different rule from
 * the module art: a `+` tier has its own frame (`epic_plus`), where the module art does not.
 */
function frameKey(rarity: string): string {
  const cleaned = rarity.toLowerCase().replace(/\s+/g, '')
  if (!cleaned) return 'empty'
  if (cleaned.startsWith('ancestral')) return 'ancestral'
  return cleaned.endsWith('+') ? `${cleaned.slice(0, -1)}_plus` : cleaned
}

function hasFile(category: string, file: string): boolean {
  return (ownLookup(MODULE_ASSET_FILES, category) ?? []).includes(file)
}

function joinPath(dir: string, file: string): string {
  return `${TOWER_ASSETS_ROOT}/${dir}/${file}`
}

/** Look a module up by id, then by exact name, then case-insensitively by name. */
function resolveTemplate(moduleIdOrName: string) {
  const byId = getModuleTemplate(moduleIdOrName)
  if (byId) return byId

  const wanted = moduleIdOrName.trim().toLowerCase()
  return MODULE_TEMPLATES.find(template => template.name.toLowerCase() === wanted) ?? null
}

/**
 * The artwork for a module, or `null` when there is none.
 *
 * `rarity` overrides the module's own minimum — the same module has different art at
 * different rarities. Falls back to the minimum rarity when the requested one has no file,
 * because that is a real situation (not every module is drawn at every tier) rather than an
 * error, and reports `null` only when neither exists.
 */
export function moduleAssetPath(moduleIdOrName: string, rarity?: string | null): string | null {
  const template = resolveTemplate(moduleIdOrName)
  if (!template) return null

  const dir = ownLookup(MODULE_ASSET_DIRS as Readonly<Record<string, string>>, template.type)
  if (!dir) return null

  const initials = initialsKey(template.initials)
  const candidates = [
    rarity ? `${rarityPrefix(rarity)}_${initials}.png` : null,
    `${rarityPrefix(template.minRarity)}_${initials}.png`,
  ].filter((file): file is string => file !== null)

  for (const file of candidates) {
    if (hasFile(template.type, file)) return joinPath(dir, file)
  }
  return null
}

/**
 * The rarity frame drawn around a module, or `null` when that rarity has none.
 *
 * Frames are per-category files, so a category is required — they are not interchangeable
 * even though the rarities are the same.
 */
export function moduleFrameAssetPath(category: string, rarity?: string | null): string | null {
  const dir = ownLookup(MODULE_ASSET_DIRS as Readonly<Record<string, string>>, category)
  if (!dir) return null

  const file = `mf_${rarity ? frameKey(rarity) : 'empty'}.png`
  return hasFile(category, file) ? joinPath(dir, file) : null
}

/** The artwork for a card, or `null` when there is none. Handles the id aliases. */
export function cardAssetPath(cardId: string): string | null {
  const name = ownLookup(CARD_ID_ALIASES, cardId) ?? cardId
  const file = `${name}.jpg`
  return CARD_ASSET_FILES.includes(file) ? `${TOWER_ASSETS_ROOT}/${CARD_ASSET_DIR}/${file}` : null
}

/** Every module that has artwork, with its path. For building a picker. */
export function allModuleAssetPaths(): { id: string, name: string, path: string }[] {
  const out: { id: string, name: string, path: string }[] = []
  for (const template of MODULE_TEMPLATES) {
    const path = moduleAssetPath(template.id)
    if (path) out.push({ id: template.id, name: template.name, path })
  }
  return out
}

/**
 * Turn a manifest path into something a bundler or a server can load.
 *
 * The manifest is deliberately transport-agnostic — a Vite `import.meta.glob`, an Express
 * static mount and a CDN all want a different prefix, and guessing one would be wrong for
 * the other two.
 *
 * ```ts
 * const url = towerAssetUrl(cardAssetPath('aoe'), '/node_modules/tower-assets')
 * ```
 */
export function towerAssetUrl(assetPath: string | null, baseUrl: string): string | null {
  if (!assetPath) return null
  return `${baseUrl.replace(/\/+$/, '')}/${assetPath}`
}
