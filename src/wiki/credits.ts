/**
 * Attribution for the community wikis this package reads.
 *
 * The wiki helpers here fetch and reformat pages that other people wrote. Nothing in
 * `thetowersdk/wiki` produces knowledge of its own — it is a transport and a parser over
 * work contributed by the wikis' editors, who are volunteers.
 *
 * Anything that surfaces wiki text to a user should carry this credit somewhere visible;
 * {@link WIKI_ATTRIBUTION} is a ready-made line for that.
 *
 * The names of individual editors are not listed here on purpose. Wiki authorship changes
 * continuously and is recorded per page in each wiki's own history — a snapshot copied
 * into this package would be wrong within a week and would silently drop people. Link to
 * the page instead: `fetchWikiPage()` returns a `url` for exactly this reason.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    WIKI_CREDIT_SOURCES, WIKI_ATTRIBUTION
 * depends    src/wiki/sources
 * used by    src/contributions/index, src/wiki/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

import { WIKI_SOURCES } from './sources'

/** The wikis this package reads, as `{ label, url }` for rendering a credit list. */
export const WIKI_CREDIT_SOURCES = WIKI_SOURCES.map(source => ({
  label: source.label,
  url: source.pageUrlBase,
})) as readonly { readonly label: string, readonly url: string }[]

/** A one-line credit suitable for a footer or an about box. */
export const WIKI_ATTRIBUTION =
  'Wiki content is written and maintained by the contributors to '
  + `${WIKI_SOURCES.map(source => source.label).join(' and ')}. `
  + 'Each page links back to its source, where its authors and edit history are recorded.'
