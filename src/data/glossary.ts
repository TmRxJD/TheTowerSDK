/**
 * The SDK's dictionary of terms: every name in the shipped catalogs, plus the
 * community shorthand and concepts that catalogs do not carry.
 *
 * Names are generated from the catalogs, so a term cannot appear here unless it
 * exists in the data. Acronym expansions are checked against those same names.
 *
 * ```ts
 * import { lookupGlossary } from 'thetowersdk/data'
 *
 * lookupGlossary('ILM')   // → Inner Land Mines, ultimate-weapon
 * lookupGlossary('SR')    // → two entries; the term is ambiguous
 * ```
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    GLOSSARY, lookupGlossary, expandAcronym, listGlossaryByDomain, listAmbiguousGlossaryTerms, GLOSSARY_CONCEPTS, GLOSSARY_NAMES
 * depends    src/data/glossary-concepts, src/data/glossary-names.generated, src/data/glossary-types
 * used by    scripts/check-acronym-expansions, src/data/index, src/knowledge/compartments/jargon, src/mechanics/calculators/specs-generated
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { GLOSSARY_CONCEPTS } from './glossary-concepts'
import { GLOSSARY_NAMES } from './glossary-names.generated'
import type { GlossaryDomain, GlossaryEntry, GlossaryKind } from './glossary-types'

export type { GlossaryDomain, GlossaryEntry, GlossaryKind }
export { GLOSSARY_CONCEPTS, GLOSSARY_NAMES }

/** Every term the SDK defines, catalog names first. */
export const GLOSSARY: readonly GlossaryEntry[] = [...GLOSSARY_NAMES, ...GLOSSARY_CONCEPTS]

const byTerm = new Map<string, GlossaryEntry[]>()
for (const entry of GLOSSARY) {
  const key = entry.term.toLowerCase()
  const bucket = byTerm.get(key)
  if (bucket) bucket.push(entry)
  else byTerm.set(key, [entry])
}

/**
 * Every meaning of a term, case-insensitively. More than one result means the
 * term is genuinely ambiguous — `SR` is both Shrink Ray and Solar Reflector —
 * so pick by `domain` rather than taking the first.
 */
export function lookupGlossary(term: string): readonly GlossaryEntry[] {
  return byTerm.get(String(term).trim().toLowerCase()) ?? []
}

/** Resolve an acronym to the name it stands for, or `null` when it is not one. */
export function expandAcronym(acronym: string, domain?: GlossaryDomain): string | null {
  const matches = lookupGlossary(acronym)
    .filter(entry => entry.kind === 'acronym' && entry.expansion)
    .filter(entry => !domain || entry.domain === domain)
  if (matches.length !== 1) return null
  return matches[0].expansion ?? null
}

export function listGlossaryByDomain(domain: GlossaryDomain): readonly GlossaryEntry[] {
  return GLOSSARY.filter(entry => entry.domain === domain)
}

/** Terms that mean more than one thing, so a caller knows to disambiguate. */
export function listAmbiguousGlossaryTerms(): readonly string[] {
  return [...new Set(GLOSSARY.filter(entry => entry.ambiguous).map(entry => entry.term))].sort()
}
