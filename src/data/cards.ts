export interface CardTemplate {
  id: string
  name: string
  // Static human-readable description of the card's effect (doesn't change per level)
  description: string
  rarity: 'common' | 'rare' | 'epic'
  // Type for all levels
  levelType: 'percent' | 'flat' | 'duration' | 'multi'
  // Numeric values for each level (index 0 -> level 1)
  levelValues: number[]
  // Name for mastery
  masteryName: string
  // Description for mastery
  masteryDescription: string
  // Type for all mastery levels
  masteryType: 'percent' | 'flat' | 'duration' | 'multi'
  // Numeric values for each mastery level (index 0 -> mastery 1)
  masteryValues: number[]
}

