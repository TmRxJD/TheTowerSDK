// from tracks.ts

export type MilestoneTrackKey = 'standard' | 'premium'

export type MilestoneRewardKind = 'resource' | 'unlock' | 'skin' | 'relic' | 'tier'

export interface MilestoneWaveRewardData {
  wave: number
  rewards: readonly string[]
}

export interface MilestoneTrackTotals {
  coinsText: string
  coinsValue: number
  gemsText: string
  gemsValue: number
  stonesText: string
  stonesValue: number
}

export interface MilestoneTierTrackData {
  tier: number
  track: MilestoneTrackKey
  waveRewards: readonly MilestoneWaveRewardData[]
  totals: MilestoneTrackTotals
}

export interface MilestoneTierData {
  tier: number
  standard: MilestoneTierTrackData
  premium: MilestoneTierTrackData
}

export interface MilestoneRewardRow {
  tier: number
  track: MilestoneTrackKey
  wave: number
  rewardIndex: number
  reward: string
  kind: MilestoneRewardKind
}

export interface MilestoneTrackTotalRow {
  tier: number
  track: MilestoneTrackKey
  coinsText: string
  coinsValue: number
  gemsText: string
  gemsValue: number
  stonesText: string
  stonesValue: number
}

// from unlocks.ts

export interface MilestoneSystemUnlock {
  /** Knowledge-graph entity id, where one exists. */
  readonly system: string
  /** The reward string as the milestone table writes it. */
  readonly reward: string
  readonly tier: number
  readonly wave: number
}
