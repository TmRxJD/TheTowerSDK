/**
 * Guilds — the system that gates the Guardian, bits and guild tokens.
 *
 * ## Why this file exists
 *
 * `MILESTONE_SYSTEM_UNLOCK_ROWS` says guilds open at tier 3 wave 10, and
 * `GUARDIAN_UNLOCK_BIT_COST` says the Guardian costs 200 bits. Between those
 * two facts there was nothing: no entity called "guild", no statement that bits
 * come from guild chests, no way to answer "can this account get a Guardian".
 * The graph could price the Guardian and could not tell you it was unreachable.
 *
 * ## What is derived and what is transcribed
 *
 * The season list is DERIVED from the relic catalog, because that catalog is
 * the only place in the repo that enumerates guild seasons at all. Everything
 * else is transcribed from the reference table shipped with the site, and each
 * transcribed total is checked against the table it came from in
 * `guild.test.ts` — a second copy of a number with no owner is how the tier
 * coin-bonus conflict got shipped.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    GUILD_BOX_REWARD_TABLE_KEY, guildSeasonFromRelicEvent, guildSeasonLabel, GuildSeasonRelics, GUILD_SEASONS, GUILD_SEASON_RELIC_TOKEN_COST, GuildChestPayout, GUILD_CHEST_PAYOUTS (+5 more)
 * depends    src/data/reference/data, src/data/relics/data
 * used by    src/data/guild/index, src/data/index, src/knowledge/compartments/guild, src/mechanics/calculators/specs-generated
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { REFERENCE_TABLES } from '../reference/data'
import { RELIC_TEMPLATES } from '../relics/data'

/** The reference table the box rewards are read from. */
export const GUILD_BOX_REWARD_TABLE_KEY = 'guilds-rewards-guild-box-rewards' as const

/**
 * Guild season numbers, in order, however the relic catalog spells them.
 *
 * The catalog writes seasons 1–7 as `Guild Season 3` and seasons 8–10 as
 * `Purchased from the Season 8 Guild Store` — a whole sentence in the `event`
 * field. Grouping relics by `event` therefore produces ten buckets under two
 * different naming schemes, and any filter written as
 * `event === 'Guild Season 8'` silently finds nothing.
 *
 * This is the repo's signature defect: supported by the model, never
 * reconciled, nothing anywhere reports it. The catalog is left alone because
 * `event` is also matched against save-file text; the drift is absorbed here.
 */
const SEASON_PATTERNS = [
  /^Guild Season (\d+)$/,
  /Season (\d+) Guild Store/,
] as const

/** Season number for a relic's `event` string, or `null` when it is not a guild season. */
export function guildSeasonFromRelicEvent(event: string | null | undefined): number | null {
  if (!event) return null
  for (const pattern of SEASON_PATTERNS) {
    const match = pattern.exec(event)
    if (match) return Number(match[1])
  }
  return null
}

/** Canonical spelling for a guild season, whatever the source wrote. */
export function guildSeasonLabel(season: number): string {
  return `Guild Season ${season}`
}

export interface GuildSeasonRelics {
  readonly season: number
  readonly label: string
  /** Relic ids awarded or sold in that season, in catalog order. */
  readonly relicIds: readonly string[]
  /** The distinct `event` strings the catalog used for this season. */
  readonly catalogEventSpellings: readonly string[]
}

function buildSeasons(): readonly GuildSeasonRelics[] {
  const bySeason = new Map<number, { ids: string[], spellings: Set<string> }>()
  for (const relic of RELIC_TEMPLATES) {
    const season = guildSeasonFromRelicEvent(relic.event)
    if (season === null) continue
    const bucket = bySeason.get(season) ?? { ids: [], spellings: new Set<string>() }
    bucket.ids.push(relic.id)
    if (relic.event) bucket.spellings.add(relic.event)
    bySeason.set(season, bucket)
  }
  return [...bySeason.entries()]
    .sort(([a], [b]) => a - b)
    .map(([season, bucket]) => ({
      season,
      label: guildSeasonLabel(season),
      relicIds: bucket.ids,
      catalogEventSpellings: [...bucket.spellings].sort(),
    }))
}

/** Every guild season the relic catalog knows about, under one spelling. */
export const GUILD_SEASONS: readonly GuildSeasonRelics[] = buildSeasons()

/**
 * Token price of a guild-season relic, by rarity.
 *
 * Only seasons 1–7 record a price; the seasons 8–10 rows put the purchase
 * sentence in the `requirement` field instead of a cost, so their prices are
 * genuinely unknown here rather than assumed equal.
 */
export const GUILD_SEASON_RELIC_TOKEN_COST: Readonly<Record<string, number>> = {
  Rare: 75,
  Epic: 150,
}

/**
 * Guild chest payouts per week, by currency.
 *
 * The four columns are contribution thresholds — the 100, 250, 500 and 750
 * boxes — and they are cumulative claims, not alternatives: a player who
 * reaches 750 has claimed all four. That is why `total` is the sum and not the
 * last column.
 */
export interface GuildChestPayout {
  readonly currency: 'Gems' | 'Tokens' | 'Bits'
  readonly perBox: readonly [number, number, number, number]
  readonly total: number
}

export const GUILD_CHEST_PAYOUTS: readonly GuildChestPayout[] = [
  { currency: 'Gems', perBox: [5, 10, 15, 30], total: 60 },
  { currency: 'Tokens', perBox: [10, 20, 40, 80], total: 150 },
  { currency: 'Bits', perBox: [10, 25, 50, 100], total: 185 },
]

/** Contribution thresholds the four chests unlock at, in order. */
export const GUILD_CHEST_THRESHOLDS: readonly [number, number, number, number] = [100, 250, 500, 750]

/**
 * Systems a player cannot reach without joining a guild.
 *
 * Recorded as ids so a planner can refuse to price them rather than quietly
 * producing a plan the account can never execute.
 */
export const GUILD_EXCLUSIVE_SYSTEMS: readonly string[] = [
  'guardian',
  'guardian.chip',
  'guardian.slot',
]

/** Save keys that carry guild state, so a reader knows what to look for. */
export const GUILD_SAVE_KEYS: readonly string[] = [
  'guildManager',
  'lastGuildID',
  'lastGuildSeason',
  'bits',
  'bitsPurchasedThisSeason',
  'totalBitsEarned',
  'totalBitsSpent',
  'guildChestClaimedWeek',
]

/**
 * How the box-reward table is shaped, stated because reading it naively drops
 * seventeen of eighteen rows.
 *
 * The first column is a sparse label: only the *ninth* coin row carries the
 * word `Coins`, and the other seventeen have an empty string there. The row's
 * real identity is its LAST column, `Tier`. Keying that table by `row[0]`
 * yields one usable row and no error.
 */
export const GUILD_BOX_TABLE_ROW_KEY_COLUMN = 'Tier' as const

/** The row indexes in the box table that are currency payouts rather than coins. */
export function guildBoxCurrencyRows(): readonly (readonly (string | number | boolean | null)[])[] {
  const table = REFERENCE_TABLES[GUILD_BOX_REWARD_TABLE_KEY]
  const currencies = new Set<string>(GUILD_CHEST_PAYOUTS.map(payout => payout.currency))
  return table.rows.filter(row => typeof row[0] === 'string' && currencies.has(row[0]))
}
