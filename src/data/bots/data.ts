/**
 * A stat's value at a level, as a number.
 *
 * The single place the ladder is evaluated. Levels outside 0..maxLevel clamp rather than
 * extrapolating, because a level a bot cannot reach has no value.
 */
export function botStatValueAt(stat: BotStatDefinition, level: number): number {
  const clamped = Math.max(0, Math.min(stat.maxLevel, Math.floor(Number(level) || 0)))
  return stat.base + stat.perLevel * clamped
}

/** The same value formatted the way the game shows it. */
export function formatBotStatValue(stat: BotStatDefinition, level: number): string {
  return `${formatNumber(botStatValueAt(stat, level))}${stat.unit}`
}

function getTierStatRows(bot: BotData, tier: BotUpgradeTier, labLevels: BotLabLevels = {}): BotStatRow[] {
  const tierData = getTierData(bot, tier)
  if (!tierData) return []

  return tierData.statOrder.map((name) => {
    const stat = tierData.stats[name]
    // A lab shifts the whole ladder; it does not change its shape.
    const adjustment = stat && tier === 'base' ? resolveBotLabAdjustment(bot, name, labLevels) : 0

    const levels = tierData.costs.map((cost, level) => {
      // The shared cost ladder is 31 long and no stat uses all of it. Levels past a stat's
      // own ceiling are blank rows, not upgrades that can be bought.
      if (!stat || level > stat.maxLevel) {
        return { level, value: '', number: Number.NaN, cost }
      }
      const value = botStatValueAt(stat, level) + adjustment
      return { level, value: `${formatNumber(value)}${stat.unit}`, number: value, cost }
    })

    return { name, levels }
  })
}

/**
 * The highest level a single bot stat actually reaches.
 *
 * Every bot carries one shared `costs` ladder of 31 entries, and no stat uses all of it. Flame
 * Bot's Damage runs to 30; its Cooldown and Range stop at 15. Reading `costs.length` as "levels
 * available" therefore offers upgrades that do not exist and charges medals for them — 14,700 of
 * them on Flame Bot Cooldown, which is most of the total.
 *
 * The ceiling is a property of the STAT, not of the bot, and it is already in the stat's own level
 * table. This reads it there rather than anywhere restating it.
 */
export function botStatMaxLevel(bot: BotData, statName: string, tier: BotUpgradeTier = 'base'): number {
  return getTierData(bot, tier)?.stats?.[statName]?.maxLevel ?? 0
}

