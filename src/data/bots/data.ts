/**
 * Stat values are authored as display strings — `'20s'`, `'2x'`, `'18m'` — and every consumer
 * parses them back to numbers. The medal planner does this 3.5 MILLION times for a single
 * plan, because the beam search re-derives each bot's metrics for every candidate it scores.
 *
 * The set of distinct strings is tiny and fixed: it is the catalog. Memoising turns the
 * regex-and-parse into a Map lookup, which is where most of a plan's time was going.
 *
 * The real fix is for the numbers not to be strings at all. Until the catalog carries typed
 * values with their units, this keeps the cost off the hot path without changing a result.
 */
const parsedNumberCache = new Map<string, number>()
const parsedUnitCache = new Map<string, string>()

function parseBaseNumber(value: string): number {
  const cached = parsedNumberCache.get(value)
  if (cached !== undefined) return cached
  const parsed = Number.parseFloat(value.replace(/[^\d.-]/g, ''))
  parsedNumberCache.set(value, parsed)
  return parsed
}

function parseUnit(value: string): string {
  const cached = parsedUnitCache.get(value)
  if (cached !== undefined) return cached
  const unit = value.replace(/[\d.-]/g, '')
  parsedUnitCache.set(value, unit)
  return unit
}

function formatNumber(value: number): string {
  if (!Number.isFinite(value)) return '0'
  const rounded = Math.round(value * 100) / 100
  return Number.isInteger(rounded) ? String(rounded) : rounded.toFixed(2).replace(/\.0+$/, '').replace(/(\.\d*[1-9])0+$/, '$1')
}

function resolveBotLabAdjustment(bot: BotData, statName: string, labLevels: BotLabLevels): number {
  const lab = bot.labInfo.find(entry => entry.name === statName)
  if (!lab) return 0

  const appliedLevel = Math.max(0, Math.min(Number(lab.maxLevel) || 0, Number(labLevels[statName] ?? 0)))
  if (!Number.isFinite(appliedLevel) || appliedLevel === 0) return 0

  const maxLevel = Number(lab.maxLevel) || 0
  if (maxLevel <= 0) return 0

  const totalAdjustment = parseBaseNumber(lab.maxValue)
  if (!Number.isFinite(totalAdjustment)) return 0

  return (totalAdjustment / maxLevel) * appliedLevel
}

