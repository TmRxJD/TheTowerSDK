export type WorkshopCostKey = keyof typeof WSP_WORKSHOP_COST_LEVELS

export function getWorkshopCostLevelsByKey(key: string): WorkshopCostLevels | null {
  const levels = WSP_WORKSHOP_COST_LEVELS[key as WorkshopCostKey]
  return levels && typeof levels === 'object' ? (levels as WorkshopCostLevels) : null
}

export function getWorkshopCostByKeyAndLevel(key: string, level: number): number | null {
  const levels = getWorkshopCostLevelsByKey(key)
  if (!levels) return null
  const normalizedLevel = Math.max(0, Math.floor(Number(level) || 0))
  const value = levels[normalizedLevel]
  return Number.isFinite(Number(value)) ? Number(value) : null
}

export function getWorkshopMaxLevelByKey(key: string): number | null {
  const levels = getWorkshopCostLevelsByKey(key)
  if (!levels) return null
  const keys = Object.keys(levels).map(entry => Number(entry)).filter(entry => Number.isFinite(entry))
  if (keys.length === 0) return null
  return Math.max(...keys)
}

export function getWorkshopCostsByKey(key: string): number[] | null {
  const levels = getWorkshopCostLevelsByKey(key)
  if (!levels) return null
  const sortedLevelKeys = Object.keys(levels).map(entry => Number(entry)).filter(entry => Number.isFinite(entry)).sort((a, b) => a - b)
  return sortedLevelKeys.map(level => Number(levels[level] || 0))
}
