/**
 * One name per battle condition, whatever the source called it.
 *
 * ## The defect this exists for
 *
 * `TIER_DATA` records a condition called `ELS Reduction` at every tier from 14
 * to 24. `TIER_BATTLE_CONDITION_DEFINITIONS` has no such entry — it calls the
 * same condition `Skip Reduction - Subtract`. So:
 *
 * - `getTierBattleConditionLevel(24, 'Skip Reduction - Subtract')` returns **0**,
 *   though the condition is at level 55 there.
 * - `Skip Reduction - Subtract` reads as "defined but never used at any tier",
 *   which is how it looks in a coverage sweep and is not true.
 * - `battle-condition-config.ts` had to bolt `| 'ELS Reduction'` onto a type
 *   union derived from the definitions, and hand-write a description for it,
 *   because the lookup returns `undefined`. That patch is the symptom.
 *
 * Nothing errors in any of those cases. Supported by the model, never set by
 * the wiring, nothing anywhere reports it.
 *
 * ## What ELS means here, and what it does not
 *
 * **ELS = Enemy Level Skip.** Native confirmation, three ways: the v28.3 getter
 * is `GetEnemyLevelSkipReductionSubtract` with the sibling
 * `GetEnemyLevelSkipReductionMultiply`; it reads `heatLevel[22]`; and it calls
 * its counter-lab, research index 209, whose localised name is
 * **"Enemy Level Skip Reduction"** — the game's own words, localisation term
 * 2887. That is the canonical name; `ELS Reduction` is our shorthand and
 * `Skip Reduction - Subtract` is the UI's later phrasing (term 3196).
 *
 * It is NOT Energy Shield, and this is the dangerous part: everywhere else in
 * this monorepo `ELS` means the Energy Shield workshop stat (the ELS planner,
 * `els-upgrade-path.ts`). `Energy Shields Down` is a *different* battle
 * condition with its own getter, `GetEnergyShieldModifier`. Reading the tier
 * table's `ELS Reduction` as an energy-shield debuff, or "correcting" it to
 * `Energy Shields Down`, produces a plausible and completely wrong model — the
 * first draft of this file did exactly that before the dump was checked.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    canonicalBattleConditionName, BATTLE_CONDITION_ALIAS_ENTRIES, ELS_REDUCTION_TIER_NAME, ELS_REDUCTION_DEFINED_NAME, ELS_REDUCTION_GAME_NAME
 * depends    —
 * used by    src/data/battle-conditions/index, src/data/index, src/data/tiers/data, src/knowledge/compartments/progression, src/mechanics/calculators/specs-generated
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

/**
 * Alternate spellings, mapped to the name `TIER_BATTLE_CONDITION_DEFINITIONS`
 * uses.
 *
 * Deliberately small. This is for names that already exist in shipped data or
 * in a primary source, not a place to invent tolerant matching — a resolver
 * that accepts anything hides the next drift instead of surfacing it.
 */
const BATTLE_CONDITION_ALIASES: Readonly<Record<string, string>> = {
  /* Used by every tier from 14 up; native getter GetEnemyLevelSkipReductionSubtract. */
  'ELS Reduction': 'Skip Reduction - Subtract',
  /* The game's own name for it — localisation term 2887, lab research 209. */
  'Enemy Level Skip Reduction': 'Skip Reduction - Subtract',
  'Enemy Level Skip Reduction - Subtract': 'Skip Reduction - Subtract',
  'Enemy Level Skip Reduction - Multiply': 'Skip Reduction - Multiply',
  /*
   * `TIER_DATA` writes the raw display string for Boss's Ultimate WITHOUT the
   * possessive ("Boss Ultimate Lvl 20") while its `name` field keeps it. The
   * game's own strings take the possessive — see the `naming` compartment,
   * which fixed three of these in the catalog on 2026-08-16 — so the possessive
   * form is canonical and the raw string is the outlier.
   */
  'Boss Ultimate': "Boss's Ultimate",
}

/**
 * The name a condition is defined under, given any spelling seen in our data.
 *
 * Own keys only. Condition names arrive from saves, from the community sheet and from
 * tool input, and plain indexing resolves `constructor`, `toString` and `valueOf` to
 * `Object.prototype` — so this returned the `Object` **function** for a name of
 * "constructor", from a signature that promises a string. An unknown name has always
 * meant "use it as given", and that is now true for every unknown name.
 */
export function canonicalBattleConditionName(name: string): string {
  return Object.prototype.hasOwnProperty.call(BATTLE_CONDITION_ALIASES, name)
    ? BATTLE_CONDITION_ALIASES[name]!
    : name
}

/** Every alias, for tests and for tools that need to accept both spellings. */
export const BATTLE_CONDITION_ALIAS_ENTRIES: readonly (readonly [string, string])[] =
  Object.entries(BATTLE_CONDITION_ALIASES)

/**
 * The one alias that is not cosmetic.
 *
 * Exported by name because a caller who only learns one thing from this file
 * should learn this one.
 */
export const ELS_REDUCTION_TIER_NAME = 'ELS Reduction' as const
export const ELS_REDUCTION_DEFINED_NAME = 'Skip Reduction - Subtract' as const

/**
 * What the GAME calls it, which is neither of the above.
 *
 * Localisation term 2887, and the name of counter-lab research 209. Recorded
 * because "official name" is a question that gets asked and previously had no
 * answer in this repo — both names in use here are ours or the UI's.
 */
export const ELS_REDUCTION_GAME_NAME = 'Enemy Level Skip Reduction' as const
