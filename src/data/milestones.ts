export function getMilestoneTierData(tier: number): MilestoneTierData | undefined {
  return MILESTONE_TIER_DATA.find(entry => entry.tier === tier)
}

export function getMilestoneTrackData(tier: number, track: MilestoneTrackKey): MilestoneTierTrackData | undefined {
  const tierData = getMilestoneTierData(tier)
  if (!tierData) return undefined
  return track === 'standard' ? tierData.standard : tierData.premium
}
