import { parseNumberInput } from '../formatting/index'

export type MilestoneTrackKey = 'standard' | 'premium'

export type MilestoneRewardKind = 'resource' | 'unlock' | 'skin' | 'relic' | 'tier'

export interface MilestoneWaveRewardData {
  wave: number
  rewards: readonly string[]
}

export interface MilestoneTrackTotals {
  coinsText: string
  coinsValue: number
  gemsText: string
  gemsValue: number
  stonesText: string
  stonesValue: number
}

export interface MilestoneTierTrackData {
  tier: number
  track: MilestoneTrackKey
  waveRewards: readonly MilestoneWaveRewardData[]
  totals: MilestoneTrackTotals
}

export interface MilestoneTierData {
  tier: number
  standard: MilestoneTierTrackData
  premium: MilestoneTierTrackData
}

export interface MilestoneRewardRow {
  tier: number
  track: MilestoneTrackKey
  wave: number
  rewardIndex: number
  reward: string
  kind: MilestoneRewardKind
}

export interface MilestoneTrackTotalRow {
  tier: number
  track: MilestoneTrackKey
  coinsText: string
  coinsValue: number
  gemsText: string
  gemsValue: number
  stonesText: string
  stonesValue: number
}

function createWave(wave: number, ...rewards: string[]): MilestoneWaveRewardData {
  return { wave, rewards }
}

function parseMilestoneNumericAmount(value: string, unit: 'Coins' | 'Gems' | 'Stones'): number {
  const normalized = String(value || '')
    .replace(new RegExp(`\\s*${unit}$`, 'i'), '')
    .trim()

  return parseNumberInput(normalized)
}

function createTrackTotals(coinsText: string, gemsText: string, stonesText: string): MilestoneTrackTotals {
  return {
    coinsText,
    coinsValue: parseMilestoneNumericAmount(coinsText, 'Coins'),
    gemsText,
    gemsValue: parseMilestoneNumericAmount(gemsText, 'Gems'),
    stonesText,
    stonesValue: parseMilestoneNumericAmount(stonesText, 'Stones'),
  }
}

function createTrackData(
  tier: number,
  track: MilestoneTrackKey,
  waveRewards: readonly MilestoneWaveRewardData[],
  totals: MilestoneTrackTotals,
): MilestoneTierTrackData {
  return {
    tier,
    track,
    waveRewards,
    totals,
  }
}

function classifyMilestoneReward(reward: string, wave: number): MilestoneRewardKind {
  const normalized = String(reward || '').trim().toLowerCase()
  if (!normalized) return 'unlock'

  if (/^tier\s+\d+$/i.test(reward)) return 'tier'
  if (/(coins|gems|stones)$/i.test(reward)) return 'resource'
  if (wave === 2500 && !/(coins|gems|stones)$/i.test(reward)) return 'skin'
  if (/skin$/i.test(reward)) return 'skin'
  if (/^relic:/i.test(reward) || wave === 4500) return 'relic'
  return 'unlock'
}

