/** A save file's first two bytes when it is gzip-compressed, which it normally is. */
const GZIP_MAGIC = [0x1f, 0x8b] as const

function toBytes(input: Uint8Array | ArrayBuffer): Uint8Array {
  return input instanceof Uint8Array ? input : new Uint8Array(input)
}

export function isGzipped(input: Uint8Array | ArrayBuffer): boolean {
  const bytes = toBytes(input)
  return bytes.length >= 2 && bytes[0] === GZIP_MAGIC[0] && bytes[1] === GZIP_MAGIC[1]
}

/**
 * Authenticate/decrypt a TDS1 container if present, then gunzip with the platform decompressor.
 *
 * `DecompressionStream` has been in every current browser since 2023. Where it is missing this
 * says so rather than returning the compressed bytes, which would reach the reader as a stream
 * whose header does not match anything and fail somewhere much less obvious.
 */
export async function gunzipBytes(input: Uint8Array | ArrayBuffer, options?: SaveDecodeOptions): Promise<Uint8Array> {
  const bytes = await decryptSave(toBytes(input), options)
  if (!isGzipped(bytes)) return bytes

  if (typeof DecompressionStream === 'undefined') {
    throw new Error(
      'This save is gzip-compressed and DecompressionStream is unavailable here. '
      + 'Use thetowersdk/node in Node, or supply already-decompressed bytes.',
    )
  }

  const stream = new Blob([bytes as BlobPart]).stream().pipeThrough(new DecompressionStream('gzip'))
  return new Uint8Array(await new Response(stream).arrayBuffer())
}

/**
 * Save bytes to a root: local decryption with caller keys, then decompression and parsing.
 *
 * The result is the object every extractor in `thetowersdk/save` takes.
 */
export async function decodeSaveFile(
  input: Uint8Array | ArrayBuffer,
  options?: SaveDecodeOptions,
): Promise<Record<string, unknown>> {
  const inflated = await gunzipBytes(input, options)
  const json = readToolExportJson(inflated)
  if (json) return json
  /* The same explanation as the synchronous path: this is the one a file input reaches. */
  const parsed = nrbfToJSON(readStreamOrExplain(inflated))

  /*
   * A non-object root means the bytes were not a save, and saying so here is the difference
   * between one clear error and a dozen extractors each reporting that it found nothing.
   */
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('Not a playerInfo.dat: the NRBF root decoded to something other than an object.')
  }
  return parsed as Record<string, unknown>
}

/**
 * The same decode, when the caller has already handled the gunzip.
 *
 * Useful inside a Worker that receives inflated bytes, or with a save that was never compressed.
 */
export function decodeInflatedSave(inflated: Uint8Array): Record<string, unknown> {
  const json = readToolExportJson(inflated)
  if (json) return json
  const parsed = nrbfToJSON(readStreamOrExplain(inflated))
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('Not a playerInfo.dat: the NRBF root decoded to something other than an object.')
  }
  return parsed as Record<string, unknown>
}

/**
 * Every failure here has to be a sentence, because the input is a file someone picked.
 *
 * The reader reports what it can — `Invalid NRBF stream` for noise, `RecordType not supported` for
 * a byte that is not a record type. A file cut short reads a record header, believes it, and runs
 * off the end: the caller got `TypeError: Cannot read properties of undefined (reading '…')` from
 * somewhere in the middle of the parser. That is unactionable in a browser, where the usual cause
 * is a partially-copied file, and it is the one case a user can fix.
 *
 * The original is kept as `cause`, so a bug report still carries where it happened.
 */
function readStreamOrExplain(inflated: Uint8Array): unknown {
  try {
    return NRBFReader.readStream(inflated)
  }
  catch (error) {
    if (error instanceof RangeError || error instanceof TypeError) {
      /*
       * `cause` is assigned rather than passed: the constructor option is ES2022 and this package
       * targets ES2020, so the two-argument form does not type-check here.
       */
      const explained = new Error(
        'This save file is incomplete or corrupt — the decoder ran past the end of the data. '
        + 'A partial copy off a device is the usual cause; copy it again and retry.',
      )
      ;(explained as Error & { cause?: unknown }).cause = error
      throw explained
    }
    throw error
  }
}
