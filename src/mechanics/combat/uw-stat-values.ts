/**
 * Ultimate weapon stat values, read off the stone chart.
 *
 * Game data lookup: which chart a weapon's stats live in, what a stat reads at
 * a level, and the default level for a stat. It was filed under
 * `game-input-data` and named for the dropdown the site renders from it, but
 * nothing here is about a dropdown -- `uptime-core` and the coin simulation
 * both read stat VALUES from it.
 *
 * The option and label builders that do render dropdowns stayed behind.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    UwStatLevelEntry, UwStatSpec, findUwChartKeyFromWeaponName, computeDefaultUwStatStoneLevel, findUwStatSpec, parseUwStatNumericValue, computeUwStatStoredValue, buildUwStatLevelEntries
 * depends    src/data/ultimate-weapons/stones, src/support/own-lookup
 * used by    src/mechanics/calculators/specs-generated, src/mechanics/combat/index, src/mechanics/resource-drops/coin-multipliers, src/mechanics/uptime/compute
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { ownLookup } from '../../support/own-lookup'
import { uwStoneChartData } from '../../data/ultimate-weapons/stones'

/** One level of a UW stat: the level, and the value the chart shows for it. */
export interface UwStatLevelEntry {
  value: number
  baseValue: number
}

export interface UwStatSpec {
  weaponKey: string
  statName: string
}

const UW_WEAPON_NAME_TO_CHART_KEY: Readonly<Record<string, string>> = {
  'Golden Tower': 'golden_tower',
  'Death Wave': 'death_wave',
  'Black Hole': 'black_hole',
  'Poison Swamp': 'poison_swamp',
  'Chrono Field': 'chrono_field',
  'Smart Missiles': 'smart_missiles',
  'Inner Land Mines': 'inner_land_mines',
  'Spotlight': 'spotlight',
  'Chain Lightning': 'chain_lightning',
}

export function findUwChartKeyFromWeaponName(weaponName: string): string | null {
  return ownLookup(UW_WEAPON_NAME_TO_CHART_KEY, weaponName) ?? null
}

/** Canonical field label shared by every UW stat level dropdown (progress, calculators, uptime). */

/** First stone level option for resets / empty-state defaults. */
export function computeDefaultUwStatStoneLevel(weaponName: string, statDisplayName: string): number {
  const spec = findUwStatSpec(weaponName, statDisplayName)
  if (!spec) return 0
  const entries = buildUwStatLevelEntries(spec)
  return entries[0]?.value ?? 0
}

export function findUwStatSpec(weaponName: string, statDisplayName: string): UwStatSpec | null {
  const weaponKey = findUwChartKeyFromWeaponName(weaponName)
  if (!weaponKey) return null

  const weapon = uwStoneChartData[weaponKey]
  if (!weapon) return null

  const normalized = statDisplayName.trim().toLowerCase()
  const stat = weapon.stats.find(entry => entry.name.trim().toLowerCase() === normalized)
  if (!stat) return null

  return { weaponKey, statName: stat.name }
}



export function parseUwStatNumericValue(raw: string | number): number {
  if (typeof raw === 'number') return Number.isFinite(raw) ? raw : 0
  const parsed = Number.parseFloat(String(raw).replace(/[^\d.-]/g, ''))
  return Number.isFinite(parsed) ? parsed : 0
}

/**
 * Uptime stores UW fields as stone level indices (hub sync + unified dropdown).
 * Legacy saves may store the resolved stat value (seconds/qty/angle) directly.
 */
export function computeUwStatStoredValue(
  spec: UwStatSpec,
  stored: number | null | undefined,
): number {
  const numericStored = Number(stored)
  if (!Number.isFinite(numericStored)) return 0

  const entries = buildUwStatLevelEntries(spec)
  if (!entries.length) return numericStored

  const byLevel = entries.find(entry => entry.value === numericStored)
  if (byLevel) return parseUwStatNumericValue(byLevel.baseValue)

  const byBaseValue = entries.find(
    entry => parseUwStatNumericValue(entry.baseValue) === numericStored,
  )
  if (byBaseValue) return numericStored

  return numericStored
}

export function buildUwStatLevelEntries(spec: UwStatSpec): readonly UwStatLevelEntry[] {
  const weapon = uwStoneChartData[spec.weaponKey]
  if (!weapon) return []

  const stat = weapon.stats.find(entry => entry.name === spec.statName)
  if (!stat) return []

  return stat.levels.map(entry => ({
    value: entry.level,
    baseValue: typeof entry.value === 'number' ? entry.value : Number.parseFloat(String(entry.value).replace(/[^\d.-]/g, '')) || entry.level,
  }))
}
