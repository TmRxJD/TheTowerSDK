/** Keep three evidenced v29 benefits distinct from legacy Vault identities/costs.
 * The Oct 2026 reports describe 5% increments additive within one Vault bucket;
 * that bucket multiplies other categories. Spotlight's coefficient has weaker
 * same-multiplier corroboration than the directly quoted Damage/UW labels.
 * This helper does not certify runtime behavior or any other v29 node.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    computeV29VaultDamageBonus, computeV29VaultFreeUpgradeBonus
 * depends    src/mechanics/vault/constants, src/mechanics/vault/types
 * used by    src/calculators/specs.generated, src/mechanics/vault/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { V29_VAULT_DAMAGE_FRACTION_PER_LEVEL, V29_VAULT_DAMAGE_POLICY, V29_VAULT_DAMAGE_SOURCE_URLS } from './constants'
import type { V29VaultDamageBonus, V29VaultDamageNode, V29VaultDamagePolicy, V29VaultFreeUpgradeBonus, V29VaultFreeUpgradeNode, V29VaultFreeUpgradePolicy } from './types'
import { V29_VAULT_FREE_UPGRADE_FRACTION_PER_LEVEL, V29_VAULT_FREE_UPGRADE_POLICY, V29_VAULT_FREE_UPGRADE_SOURCE_URLS } from './constants'

/** Return fractions, not percent points. Requires an explicit source policy.
 * Unknown nodes/policies and noninteger/out-of-range levels return null.
 * Levels 0..5 refer to these three v29 nodes only, never legacy node IDs.
 */
export function computeV29VaultDamageBonus(node: string, level: number, policy: V29VaultDamagePolicy): V29VaultDamageBonus | null {
  if (policy !== V29_VAULT_DAMAGE_POLICY || !Number.isInteger(level) || level < 0 || level > 5
    || !['Damage', 'Ultimate Damage', 'Spotlight Bonus'].includes(node)) return null
  const fraction = V29_VAULT_DAMAGE_FRACTION_PER_LEVEL * level
  return { node: node as V29VaultDamageNode, level, fraction, multiplier: 1 + fraction,
    confidence: node === 'Spotlight Bonus' ? 'corroborated-community' : 'direct-community',
    nativeParity: false, sourceUrls: V29_VAULT_DAMAGE_SOURCE_URLS }
}
/** Return a relative fraction for one category's `freeUpgradeChance.vaultPct`.
 * Sept 2026 player's measured 407.16% vector uses a separate x1.25 Vault
 * multiplier after enhancement and relics; it does not add 25 chance points.
 * Unknown categories/policies and invalid levels are unsupported, not zero.
 */
export function computeV29VaultFreeUpgradeBonus(node: string, level: number, policy: V29VaultFreeUpgradePolicy): V29VaultFreeUpgradeBonus | null {
  if (policy !== V29_VAULT_FREE_UPGRADE_POLICY || !Number.isInteger(level) || level < 0 || level > 5
    || !['Free Attack Upgrade', 'Free Defense Upgrade', 'Free Utility Upgrade'].includes(node)) return null
  const fraction = V29_VAULT_FREE_UPGRADE_FRACTION_PER_LEVEL * level
  return { node: node as V29VaultFreeUpgradeNode, level, fraction, multiplier: 1 + fraction,
    confidence: 'direct-player-measurement', nativeParity: false, sourceUrls: V29_VAULT_FREE_UPGRADE_SOURCE_URLS }
}