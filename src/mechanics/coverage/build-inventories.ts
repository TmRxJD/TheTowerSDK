/**
 * Build the file-based coverage inventories from the tree and the oracle.
 *
 * The seeded inventories were a snapshot: rows written once on 2026-08-14 and
 * never revisited. By 2026-08-18 the mechanics inventory had 159 rows against
 * 191 real modules, so 32 files — including every module added since — were
 * invisible to a check whose entire purpose is spotting things nothing covers.
 *
 * This derives the rows instead, so a new module appears in the inventory the
 * moment it exists, unlinked and visible rather than absent.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    LINKED_REASON, InventorySpec, buildCoverageEntries
 * depends    src/mechanics/coverage/oracle-links, src/mechanics/coverage/schema
 * used by    —
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import fs from 'node:fs'
import path from 'node:path'
import { oracleLinksByModule, sourceModulesIn, NO_ORACLE_LINK_REASON } from './oracle-links'
import type { CoverageEntry, CoverageSurface } from './schema'

/**
 * `packages/sdk`, from THIS file rather than from `process.cwd()`.
 *
 * `spec.dir` is package-relative (`src/mechanics`), and `sourceModulesIn` used
 * to hand it straight to `fs.existsSync`. Run from `packages/sdk` that resolves;
 * run from the monorepo root it points at the SITE's `src/`, finds no
 * `src/mechanics`, and returns an EMPTY list -- so
 * `coverage-inventories-are-current` compared a real 208-row inventory against
 * nothing and failed with a diff listing every module. The same call in a
 * generator would have written the empty list out.
 *
 * A test that passes or fails depending on which directory you ran it from is
 * worse than one that just fails.
 */
const PACKAGE_ROOT = path.resolve(__dirname, '../../..')

/** `spec.dir`, anchored to the package so the caller's cwd cannot change it. */
function resolveSpecDir(dir: string): string {
  const resolved = path.isAbsolute(dir) ? dir : path.join(PACKAGE_ROOT, dir)
  if (!fs.existsSync(resolved)) {
    // Loud. An inventory built from a directory that is not there is empty, and
    // an empty inventory reads as "nothing to cover" rather than "nothing found".
    throw new Error(`coverage inventory: ${dir} does not exist (looked in ${resolved})`)
  }
  return resolved
}

export const LINKED_REASON = 'Linked to knowledge-oracle nodes via implementedBy.'

export interface InventorySpec {
  dir: string
  surface: CoverageSurface
  idPrefix: string
}

/** One entry per module under `spec.dir`, in stable label order. */
export function buildCoverageEntries(spec: InventorySpec): CoverageEntry[] {
  const dir = resolveSpecDir(spec.dir)
  const links = oracleLinksByModule(dir)
  return sourceModulesIn(dir)
    .map(({ module }) => module)
    .sort()
    .map(label => {
      const graphNodeIds = links[label] ?? []
      const modeled = graphNodeIds.length > 0
      return {
        id: `${spec.idPrefix}${label}`,
        surface: spec.surface,
        label,
        graphNodeIds,
        coverageStatus: modeled ? 'modeled' : 'unmodeled',
        // The file the row is about. Derived from the label rather than stored,
        // so a renamed module cannot leave a row pointing at a path that is
        // gone — the row simply moves with it.
        sources: [`${spec.dir}/${label}.ts`],
        reason: modeled ? LINKED_REASON : NO_ORACLE_LINK_REASON,
      } satisfies CoverageEntry
    })
}
