import { clampCampaignTier } from '../../data'

const F32 = Math.fround

/** Wave bands for protector slot — thresholds 80 / 160 / 320 / 751. */
export const NEW_WAVE_PROTECTOR_SLOT_WAVE_BANDS_V29 = [80, 160, 320, 751] as const

export const NEW_WAVE_PROTECTOR_TIER_STEP_V29 = 0.04 as const
export const NEW_WAVE_PROTECTOR_CHANCE_CAP_V29 = 100 as const
export const NEW_WAVE_PROTECTOR_TIER12_FLOOR_V29 = 11 as const

/** Banker's-round helper (half-to-even) used by NewWave protector tier factor. */
export function newWaveBankersRound(value: number): number {
  const floor = Math.floor(value)
  const frac = value - floor
  if (frac === 0.5) {
    return floor % 2 === 0 ? floor : floor + 1
  }
  return Math.round(value)
}

/** Protector slot count from wave (bands at 80 / 160 / 320 / 751). */
export function newWaveProtectorSpawnSlotV29(wave: number): number {
  const w = Math.max(1, Math.floor(Number(wave) || 1))
  if (w < NEW_WAVE_PROTECTOR_SLOT_WAVE_BANDS_V29[0]) return 0
  if (w < NEW_WAVE_PROTECTOR_SLOT_WAVE_BANDS_V29[1]) return 1
  if (w < NEW_WAVE_PROTECTOR_SLOT_WAVE_BANDS_V29[2]) return 2
  if (w < NEW_WAVE_PROTECTOR_SLOT_WAVE_BANDS_V29[3]) return 3
  return 4
}

/** Tier multiplier before slot multiply — `1 + (tier-1)*0.04` banker's-rounded. */
export function newWaveProtectorTierFactorV29(tier: number): number {
  const t = Math.max(2, Math.floor(Number(tier) || 1))
  const linear = F32(1 + F32((t - 1) * NEW_WAVE_PROTECTOR_TIER_STEP_V29))
  return newWaveBankersRound(linear)
}

/**
 * Protector chance int written to Main.chanceProtectorEnemy.
 * Tier 1 returns 0 (skips the multiply path).
 */
export function newWaveProtectorChanceV29(tier: number, wave: number): number {
  const t = clampCampaignTier(tier)
  if (t < 2) return 0
  const slot = newWaveProtectorSpawnSlotV29(wave)
  if (slot <= 0) return 0
  let chance = newWaveProtectorTierFactorV29(t) * slot
  if (t >= 12) {
    chance = Math.max(0, t + chance - NEW_WAVE_PROTECTOR_TIER12_FLOOR_V29)
  }
  return Math.min(NEW_WAVE_PROTECTOR_CHANCE_CAP_V29, Math.max(0, chance))
}

/**
 * Tier 1 non-tournament tank write: `chanceTankEnemy += chanceProtectorEnemy`.
 * Higher tiers do not take this additive path.
 */
export function applyNewWaveTankWriteV29(input: {
  tier: number
  priorTankChance: number
  protectorChance: number
  isTournament?: boolean
}): number {
  const t = clampCampaignTier(input.tier)
  const protector = Math.max(0, Math.floor(Number(input.protectorChance) || 0))
  const prior = Math.max(0, Math.floor(Number(input.priorTankChance) || 0))
  if (t !== 1 || input.isTournament) return prior
  return prior + protector
}

/** Protector cap clamp — values >= 100 store as 100. */
export function clampNewWaveProtectorChanceV29(chance: number): number {
  const c = Math.max(0, Math.floor(Number(chance) || 0))
  return c >= NEW_WAVE_PROTECTOR_CHANCE_CAP_V29 ? NEW_WAVE_PROTECTOR_CHANCE_CAP_V29 : c
}

/** Residual normal chance — reads fast/tank/ranged then `100 - sum`. */
export function newWaveNormalChanceResidualV29(input: {
  fast: number
  tank: number
  ranged: number
}): number {
  const fast = Math.max(0, Math.floor(Number(input.fast) || 0))
  const tank = Math.max(0, Math.floor(Number(input.tank) || 0))
  const ranged = Math.max(0, Math.floor(Number(input.ranged) || 0))
  return Math.max(0, NEW_WAVE_PROTECTOR_CHANCE_CAP_V29 - fast - tank - ranged)
}

/**
 * Initial `protectorEnemyWavesUntilNextCanSpawn` for the NewWave gate.
 *
 * tier >3 → −1, tier >6 picks −2 vs −1, tier <10 bumps −3→−2; then `+ 10`.
 */
export function newWaveProtectorWavesUntilNextCanSpawnV29(tier: number): number {
  const t = Math.max(1, Math.floor(Number(tier) || 1))
  const gt3 = t > 3 ? -1 : 0
  let high = -3
  if (t < 10) high += 1
  const offset = t > 6 ? high : gt3
  return 10 + offset
}

export type NewWaveProtectorGateState = {
  wavesUntilNext: number
}

/** Whether the spawn gate allows a protector this wave (counter exhausted). */
export function newWaveProtectorGateOpenV29(state: NewWaveProtectorGateState): boolean {
  return Math.floor(Number(state.wavesUntilNext) || 0) <= 0
}

/** One NewWave step — decrements counter by 2 when gate closed. */
export function advanceNewWaveProtectorGateV29(
  state: NewWaveProtectorGateState,
): NewWaveProtectorGateState {
  const current = Math.floor(Number(state.wavesUntilNext) || 0)
  if (current <= 0) {
    return { wavesUntilNext: current }
  }
  return { wavesUntilNext: Math.max(0, current - 2) }
}

export function initialNewWaveProtectorGateStateV29(tier: number): NewWaveProtectorGateState {
  return { wavesUntilNext: newWaveProtectorWavesUntilNextCanSpawnV29(tier) }
}
