/**
 * Ordinary spawn chances for coin-weight estimation - protector excluded.
 *
 * Protectors are spawn-gated (wave/tier slots), not part of the tier-weight
 * mix that `SpawnRandomBasicEnemy` draws from. Including protector share in
 * coin weight drove basic to 0% at tier 21+ while saves show large basic kill
 * counts - see knowledge trap on protector vs coin mix.
 *
 * Scene extract (`MAIN_SPAWN_TYPE_SCENE_CHANCES_V29`, level1 Main Inspector)
 * stores absolute starter chance ints (normal 70, fast 15, tank 15, ranged 0,
 * protector 0). Those are NOT tier-weight coefficients. Coin mix uses fitted
 * coeffs in `COIN_MIX_TIER_SPAWN_COEFF_V29` (~3.294/3.019/2.881) only —
 * multiplying scene ints × high tier weight crushes Basic to 0.
 *
 * In-game, NewWave overwrites tank/protector/normal; fast/ranged stay
 * scene-serialized as absolute ints. Modeling their high-tier evolution still
 * needs the NewWave/tier formula, not raw scene × weight.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    ordinarySpawnChancesForCoinMix
 * depends    src/data, src/mechanics/waves/info-panel-constants, src/mechanics/waves/info-panel-stats, src/mechanics/waves/main-spawn-type-chances-constants
 * used by    src/mechanics/calculators/specs-generated, src/mechanics/resource-drops/wave-ordinary-coin-weight, src/mechanics/waves/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { clampCampaignTier } from '../../data'
import { WAVE_INFO_TIER_SPAWN_WEIGHT_TABLE } from './info-panel-constants'
import type { WaveInfoSpawnChances } from './info-panel-stats'
import { COIN_MIX_TIER_SPAWN_COEFF_V29 } from './main-spawn-type-chances-constants'

const F32 = Math.fround

function tierSpawnWeight(tier: number): number {
  const t = clampCampaignTier(tier)
  if (t < 9) return F32(1 + F32((t - 1) * 0.04))
  const idx = Math.min(WAVE_INFO_TIER_SPAWN_WEIGHT_TABLE.length - 1, t - 9)
  return WAVE_INFO_TIER_SPAWN_WEIGHT_TABLE[idx] ?? 1
}

function scaledSpawnShare(base: number, weight: number): number {
  return Math.min(64, Math.round(base * weight))
}

/**
 * Spawn chance weights for ordinary coin mix - fast/tank/ranged from fitted
 * tier-weight coeffs × tier weight; basic fills remainder. Protector is always
 * 0 (spawn-gated, not in the random basic draw pool used for coin averaging).
 *
 * Does not use `MAIN_SPAWN_TYPE_SCENE_CHANCES_V29` — those are absolute level1
 * Inspector defaults, not coin-mix bases.
 */
export function ordinarySpawnChancesForCoinMix(tier: number, _wave: number): WaveInfoSpawnChances {
  const weight = tierSpawnWeight(tier)

  const fast = scaledSpawnShare(COIN_MIX_TIER_SPAWN_COEFF_V29.fast, weight)
  const tank = scaledSpawnShare(COIN_MIX_TIER_SPAWN_COEFF_V29.tank, weight)
  const ranged = scaledSpawnShare(COIN_MIX_TIER_SPAWN_COEFF_V29.ranged, weight)
  const basic = Math.max(0, 100 - fast - tank - ranged)
  return { Basic: basic, Fast: fast, Tank: tank, Ranged: ranged, Protector: 0 }
}
