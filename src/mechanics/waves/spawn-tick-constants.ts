/** Basic-enemy spawn attempts per tick. */
export const WAVE_SPAWN_RANDOM_BASIC_CALL_SITE_COUNT_V29 = 3 as const

export const WAVE_SPAWN_CALIBRATED_RANDOM_BASIC_GATE_PASS_RATE_V29 = 1 as const
export const WAVE_SPAWN_CALIBRATED_ENEMY_DOUBLE_SPAWN_CHANCE_V29 = 0.25 as const

export function defaultCalibratedWaveSpawnYieldV29(): {
  randomBasicCallSites: typeof WAVE_SPAWN_RANDOM_BASIC_CALL_SITE_COUNT_V29
  randomBasicGatePassRate: typeof WAVE_SPAWN_CALIBRATED_RANDOM_BASIC_GATE_PASS_RATE_V29
  enemyDoubleSpawnChance: typeof WAVE_SPAWN_CALIBRATED_ENEMY_DOUBLE_SPAWN_CHANCE_V29
} {
  return {
    randomBasicCallSites: WAVE_SPAWN_RANDOM_BASIC_CALL_SITE_COUNT_V29,
    randomBasicGatePassRate: WAVE_SPAWN_CALIBRATED_RANDOM_BASIC_GATE_PASS_RATE_V29,
    enemyDoubleSpawnChance: WAVE_SPAWN_CALIBRATED_ENEMY_DOUBLE_SPAWN_CHANCE_V29,
  }
}

/**
 * Expected enemies produced when the wave-spawn timer fires once.
 *
 * Each spawn attempt passes its gate at `randomBasicGatePassRate`, and the double-spawn roll adds
 * one more enemy at `enemyDoubleSpawnChance`. The gate pass rate is not the spawn tick cap.
 */
export function expectedEnemiesPerSpawnTickFromWaveGates(input: {
  randomBasicCallSites?: number
  /** @deprecated Use `randomBasicGatePassRate`. */
  enemySpawnChance?: number
  randomBasicGatePassRate?: number
  enemyDoubleSpawnChance?: number
}): number {
  const sites = Math.max(0, Math.floor(Number(input.randomBasicCallSites ?? WAVE_SPAWN_RANDOM_BASIC_CALL_SITE_COUNT_V29) || 0))
  const gatePass = Math.max(
    0,
    Math.min(1, Number(input.randomBasicGatePassRate ?? input.enemySpawnChance ?? 0) || 0),
  )
  const doubleChance = Math.max(0, Math.min(1, Number(input.enemyDoubleSpawnChance ?? 0) || 0))
  return sites * gatePass + doubleChance
}
