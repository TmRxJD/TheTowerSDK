/**
 * Bridge account + wave context -> WaveSpawnYieldInput for coin / drop simulators.
 *
 * The spawn chance is the **0-100 master spawn gate** each new wave sets from the Wave
 * Accelerator chart (+ wave-band bonuses). Under the calibrated path it is still treated as a
 * tick-count multiplier; under the quantum model it is the master threshold.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    moreEnemiesResistanceFromHeat, waveSpawnDoubleChanceFromEliteChart, resolveWaveSpawnYieldFromAccount, expectedEnemiesPerSpawnTickFromAccount, expectedEnemiesPerWaveFromAccount
 * depends    src/mechanics/enemies/elite-spawn-chance, src/mechanics/enemies/get-resistance-level, src/mechanics/uptime/compute, src/mechanics/waves/accelerator-spawn-rate-cap, src/mechanics/waves/spawn-tick-constants, src/mechanics/waves/types (+1 more)
 * used by    src/calculators/specs.generated, src/mechanics/resource-drops/coin-multipliers, src/mechanics/resource-drops/simulate-wave-coins, src/mechanics/resource-drops/simulate-wave-econ, src/mechanics/waves/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { waveInfoEliteEffectiveDoubleSpawnPct } from '../enemies/elite-spawn-chance'
import { getResistanceLevel } from '../enemies/get-resistance-level'
import { computeWaveCombatDurationSeconds } from '../uptime/compute'
import { enemySpawnRateCapFromWaveAcceleratorChart } from './accelerator-spawn-rate-cap'
import {
  WAVE_SPAWN_RANDOM_BASIC_CALL_SITE_COUNT_V29,
  expectedEnemiesPerSpawnTickFromWaveGates,
} from './spawn-tick-constants'
import type { WaveSpawnYieldInput } from './types'
import {
  expectedEnemiesPerSpawnQuantumV29,
  expectedEnemiesPerSpawnTickFromGatesV29,
  expectedEnemiesPerWaveFromQuantumV29,
  newWaveEnemyDoubleSpawnThresholdV29,
} from './update-spawn-gate-pass'
import type { ResolveWaveSpawnYieldInput } from './types'

export function moreEnemiesResistanceFromHeat(heatLevel: number | null | undefined): number {
  const heat = Math.max(0, Math.floor(Number(heatLevel) || 0))
  if (heat <= 0) return 1
  return getResistanceLevel({
    heatLevel: heat,
    globalResistanceReduction: 0,
    conditionResistanceReduction: 0,
  })
}

export function waveSpawnDoubleChanceFromEliteChart(input: {
  tier: number
  wave: number
  enemyBalanceMastery?: number | null
}): number {
  const pct = waveInfoEliteEffectiveDoubleSpawnPct(input.tier, input.wave, {
    enemyBalanceMastery: input.enemyBalanceMastery,
  })
  return Math.max(0, Math.min(1, pct / 100))
}

export function resolveWaveSpawnYieldFromAccount(
  input: ResolveWaveSpawnYieldInput | null | undefined,
): WaveSpawnYieldInput | undefined {
  if (input == null) return undefined
  const wave = Math.max(1, Math.floor(Number(input.wave) || 1))
  const tier = Math.max(1, Math.floor(Number(input.tier) || 1))
  const sites = Math.max(0, Math.floor(Number(input.randomBasicCallSites ?? WAVE_SPAWN_RANDOM_BASIC_CALL_SITE_COUNT_V29) || 0))
  const gatePass = input.randomBasicGatePassRate != null ? Math.max(0, Math.min(1, Number(input.randomBasicGatePassRate) || 0)) : 1
  // Elite chart keeps additive-probe backward compat; quantum uses enemyDoubleSpawnThreshold (base 5).
  const doubleChance = input.enemyDoubleSpawnChance != null ? Math.max(0, Math.min(1, Number(input.enemyDoubleSpawnChance) || 0)) : waveSpawnDoubleChanceFromEliteChart({ tier, wave, enemyBalanceMastery: input.enemyBalanceMastery })
  return {
    randomBasicCallSites: sites,
    randomBasicGatePassRate: gatePass,
    enemyDoubleSpawnChance: doubleChance,
    useSpawnGates: input.useSpawnGates === true,
    useSpawnQuantum: input.useSpawnQuantum,
    waveLengthSeconds: input.waveLengthSeconds,
    enemyDoubleSpawnThreshold:
      input.enemyDoubleSpawnThreshold != null
        ? Number(input.enemyDoubleSpawnThreshold)
        : input.useSpawnGates
          ? newWaveEnemyDoubleSpawnThresholdV29({
              tier,
              themeBucketBase: input.doubleSpawnThemeBucketBase,
            })
          : undefined,
    spawnTickCap: input.spawnTickCap,
    moreEnemiesResistance:
      input.moreEnemiesResistance != null
        ? Number(input.moreEnemiesResistance)
        : input.moreEnemiesHeatLevel != null
          ? moreEnemiesResistanceFromHeat(input.moreEnemiesHeatLevel)
          : undefined,
  }
}

/**
 * Expected enemies per spawn tick / quantum from account context.
 * Under the quantum model (default when useSpawnGates): per-quantum EV (master x cluster).
 * Under additive probe (useSpawnQuantum:false): sum of site EVs.
 * Calibrated path: uniform gate formula.
 */
export function expectedEnemiesPerSpawnTickFromAccount(input: ResolveWaveSpawnYieldInput): number {
  const yieldInput = resolveWaveSpawnYieldFromAccount(input)
  if (!yieldInput) return 0
  if (yieldInput.useSpawnGates) {
    const cap = enemySpawnRateCapFromWaveAcceleratorChart({
      wave: Math.max(1, Math.floor(Number(input.wave) || 1)),
      waveAcceleratorMastery: input.waveAcceleratorMastery,
    })
    const threshold = yieldInput.spawnTickCap ?? cap
    if (yieldInput.useSpawnQuantum !== false) {
      return expectedEnemiesPerSpawnQuantumV29({
        enemySpawnChanceThreshold: threshold,
        enemyDoubleSpawnThreshold: yieldInput.enemyDoubleSpawnThreshold,
        moreEnemiesResistance: yieldInput.moreEnemiesResistance,
      })
    }
    return expectedEnemiesPerSpawnTickFromGatesV29({
      spawnTickCap: threshold,
      enemyDoubleSpawnChance: yieldInput.enemyDoubleSpawnChance,
      moreEnemiesResistance: yieldInput.moreEnemiesResistance,
    })
  }
  return expectedEnemiesPerSpawnTickFromWaveGates({
    randomBasicCallSites: yieldInput.randomBasicCallSites ?? undefined,
    randomBasicGatePassRate: yieldInput.randomBasicGatePassRate ?? 1,
    enemyDoubleSpawnChance: yieldInput.enemyDoubleSpawnChance ?? undefined,
  })
}

/** Full-wave expected ordinary enemies (quantum or calibrated tick-count model). */
export function expectedEnemiesPerWaveFromAccount(
  input: ResolveWaveSpawnYieldInput & { enemyBalanceMult?: number },
): number {
  const yieldInput = resolveWaveSpawnYieldFromAccount(input)
  if (!yieldInput) return 0
  const wave = Math.max(1, Math.floor(Number(input.wave) || 1))
  const cap = enemySpawnRateCapFromWaveAcceleratorChart({
    wave,
    waveAcceleratorMastery: input.waveAcceleratorMastery,
  })
  const eb = input.enemyBalanceMult ?? 1
  if (yieldInput.useSpawnGates && yieldInput.useSpawnQuantum !== false) {
    return expectedEnemiesPerWaveFromQuantumV29({
      waveLengthSeconds: yieldInput.waveLengthSeconds ?? computeWaveCombatDurationSeconds(false),
      enemySpawnChanceThreshold: yieldInput.spawnTickCap ?? cap,
      enemyDoubleSpawnThreshold: yieldInput.enemyDoubleSpawnThreshold,
      moreEnemiesResistance: yieldInput.moreEnemiesResistance,
      enemyBalanceMult: eb,
    })
  }
  return cap * eb * expectedEnemiesPerSpawnTickFromAccount(input)
}
