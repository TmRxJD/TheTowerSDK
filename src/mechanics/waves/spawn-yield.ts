/** Save-calibrated effective enemies per spawn tick. */
export const WAVE_SPAWN_CALIBRATED_ENEMIES_PER_TICK = 3.25 as const

export {
  WAVE_SPAWN_CALIBRATED_ENEMY_DOUBLE_SPAWN_CHANCE_V29,
  WAVE_SPAWN_CALIBRATED_RANDOM_BASIC_GATE_PASS_RATE_V29,
  defaultCalibratedWaveSpawnYieldV29,
} from './spawn-tick-constants'

/** v29 basic-enemy spawn attempts per tick. */
export const WAVE_SPAWN_RANDOM_BASIC_CALL_SITES_DEFAULT = WAVE_SPAWN_RANDOM_BASIC_CALL_SITE_COUNT_V29

export function expectedEnemiesPerSpawnTick(input: WaveSpawnYieldInput = {}): number {
  const sites = Math.max(
    0,
    Math.floor(Number(input.randomBasicCallSites ?? WAVE_SPAWN_RANDOM_BASIC_CALL_SITES_DEFAULT) || 0),
  )

  const gatePass =
    input.randomBasicGatePassRate ?? input.enemySpawnChance ?? input.spawnGatePassRate
  const doubleChance = input.enemyDoubleSpawnChance

  if (gatePass != null || doubleChance != null) {
    return expectedEnemiesPerSpawnTickFromWaveGates({
      randomBasicCallSites: sites,
      randomBasicGatePassRate: clamp(Number(gatePass ?? 1), 0, 1),
      enemyDoubleSpawnChance: clamp(Number(doubleChance ?? 0), 0, 1),
    })
  }

  if (sites === WAVE_SPAWN_RANDOM_BASIC_CALL_SITES_DEFAULT) {
    return WAVE_SPAWN_CALIBRATED_ENEMIES_PER_TICK
  }
  return WAVE_SPAWN_CALIBRATED_ENEMIES_PER_TICK * (sites / WAVE_SPAWN_RANDOM_BASIC_CALL_SITES_DEFAULT)
}

export function killsPerWaveFromSpawnContext(input: {
  wave: number
  enemyBalanceMult: number
  waveAcceleratorMastery: number | null
  spawnYield?: WaveSpawnYieldInput
}): number {
  const cap = enemySpawnRateCapFromWaveAcceleratorChart({
    wave: input.wave,
    waveAcceleratorMastery: input.waveAcceleratorMastery,
  })
  if (input.spawnYield?.useSpawnGates) {
    const useQuantum = input.spawnYield.useSpawnQuantum !== false
    if (useQuantum) {
      const length =
        input.spawnYield.waveLengthSeconds ??
        computeWaveCombatDurationSeconds(false)
      const threshold = input.spawnYield.spawnTickCap ?? cap
      return expectedEnemiesPerWaveFromQuantumV29({
        waveLengthSeconds: length,
        enemySpawnChanceThreshold: threshold,
        enemyDoubleSpawnThreshold: input.spawnYield.enemyDoubleSpawnThreshold,
        moreEnemiesResistance: input.spawnYield.moreEnemiesResistance,
        enemyBalanceMult: input.enemyBalanceMult,
      })
    }
    // legacy additive probe: chart cap as tick count x per-tick site EV sum
    const yieldPerTick = expectedEnemiesPerSpawnTickFromGatesV29({
      spawnTickCap: input.spawnYield.spawnTickCap ?? cap,
      enemyDoubleSpawnChance: input.spawnYield.enemyDoubleSpawnChance,
      moreEnemiesResistance: input.spawnYield.moreEnemiesResistance,
    })
    return cap * Math.max(0, Number(input.enemyBalanceMult) || 0) * yieldPerTick
  }
  const yieldPerTick = expectedEnemiesPerSpawnTick(input.spawnYield)
  return cap * Math.max(0, Number(input.enemyBalanceMult) || 0) * yieldPerTick
}

