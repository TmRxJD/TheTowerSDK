/** Trade-off perk indices for common enemy header stats. */
export const ENEMY_HEADER_PERK_INDICES = {
  enemyHpTradeOff: 42,
  enemyAttackTradeOffUp: 43,
  rangedAttackTradeOffDown: 44,
  enemyAttackTradeOffDown: 45,
  bossHpTradeOffDown: 40,
  bossHpTradeOffUp: 48,
} as const

/** Improve Trade-off Perks lab — `Lab.researchBenefit[88]` scales `PerkBenefitUp`. */
export const IMPROVE_TRADE_OFF_PERKS_LAB_INDEX = 88

/** `perkBenefitUpBase` @ improve-lab 0 for trade-off perks scaled by improve lab. */
export const TRADE_OFF_ENEMY_HP_BENEFIT_BASE = 0.5
export const TRADE_OFF_ENEMY_DMG_BENEFIT_BASE = 0.5
export const TRADE_OFF_SPEED_DMG_MULTIPLIER = 2.5
export const TRADE_OFF_RANGED_DMG_MULTIPLIER = 3
export const TRADE_OFF_BOSS_HP_DOWN_MULT = 0.3
/** Boss HP ×8 perk base — `1 − (−7) = 8`. */
export const TRADE_OFF_BOSS_HP_X8_UP_BASE = -7

/** Pre-perk wave base damage on the run-header path. */
export function waveBaseDamageForHeader(getWaveBaseDamage: number): number {
  if (!Number.isFinite(getWaveBaseDamage) || getWaveBaseDamage <= 0) return 0
  return Math.floor(getWaveBaseDamage)
}

