/**
 * Ray charged shots are distinct from the wave panel's plain base-damage number.
 * The existing enemy-type table owns the shot multiplier; do not apply it again
 * to an already projected payload. Charge timing is public mechanic evidence,
 * not a recovered native attack-clock implementation.
 * https://the-tower.notion.site/Ray-1bf91383b93f804aa072dfb44619b324
 * https://www.reddit.com/r/TheTowerGame/comments/1mb5ami/
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    RAY_ATTACK_PROFILE, rayAttackPayloadDamage
 * depends    src/mechanics/enemies/type-mults
 * used by    src/calculators/specs.generated, src/mechanics/enemies/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { ENEMY_MULT_BY_TYPE_TABLE } from './type-mults'

/** Game seconds; the first shot charges for the same duration as later shots. */
export const RAY_ATTACK_PROFILE = Object.freeze({ firstDelaySeconds: 30, periodSeconds: 30 })

/** Convert the plain Ray wave-panel damage to one unmitigated charged shot. */
export function rayAttackPayloadDamage(panelWaveDamage: number): number {
  if (!Number.isFinite(panelWaveDamage) || panelWaveDamage < 0)
    throw new Error('RAY_PANEL_DAMAGE_FINITE_NONNEGATIVE_REQUIRED')
  const payload = panelWaveDamage * ENEMY_MULT_BY_TYPE_TABLE.Ray.damage
  if (!Number.isFinite(payload)) throw new Error('RAY_ATTACK_PAYLOAD_OVERFLOW')
  return payload
}
