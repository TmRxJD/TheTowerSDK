/** Enemy Level Skip lab benefit % for a given lab level (0 → 0). */
export function getImproveTradeOffLabPct(improveTradeOffLabLevel: number): number {
  const lab = findToolLabBySlug(IMPROVE_TRADE_OFF_LAB_SLUG)
  return lab
    ? computeLabValueAtLevel(lab, clamp(Math.floor(improveTradeOffLabLevel), 0, MAX_IMPROVE_TRADE_OFF_LAB_LEVEL))
    : improveTradeOffLabLevel
}

export function getTradeOffImproveMult(improveTradeOffLabLevel: number): number {
  return tradeOffImproveMultFromLabPercent(getImproveTradeOffLabPct(improveTradeOffLabLevel))
}

/** Fill the known enemy-stat lab slugs, clamped; input is expected slug-keyed. */
function normalizeEnemyLabLevels(raw: EnemyLabLevels): EnemyLabLevels {
  const out: EnemyLabLevels = {}
  for (const slug of ENEMY_STATS_CALCS_RESEARCH_LAB_SLUGS) {
    const value = raw[slug]
    out[slug] = Number.isFinite(value) ? clamp(Math.floor(value as number), 0, computeResearchLabMaxLevel(slug)) : 0
  }
  return out
}

export function getPerkMultipliers(
  enemyType: EnemyWaveEnemyType,
  perks: EnemyStatsPerkState,
  improveTradeOffLabLevel = 0,
): { hp: number, damage: number } {
  return waveInfoDisplayMultipliers({
    enemyType,
    toggles: perks,
    improveTradeOffLabPct: getImproveTradeOffLabPct(improveTradeOffLabLevel),
  })
}

export function battleConditionsAtWave(
  wave: number,
  modifiers: Pick<EnemyStatsModifierState, 'tier' | 'tournament' | 'league' | 'battleConditions'>,
): BattleConditionSelection[] {
  return getWaveInfoBattleConditions(
    modifiers.tier,
    modifiers.tournament,
    modifiers.league,
    wave,
    modifiers.battleConditions,
  )
}

/** Wave → skip/BC-adjusted enemy stat level. */
export function resolveStatLevel(
  wave: number,
  skipPct: number,
  skipCountOverride: number | null,
  modifiers: EnemyStatsModifierState,
): number {
  const w = Math.max(1, Math.floor(wave))
  const conditionsAtWave = battleConditionsAtWave(w, modifiers)
  return computeEnemyStatLevelWithBcLabs(
    w,
    skipPct,
    skipCountOverride,
    modifiers.bcCounterLabLevels,
    modifiers.tier,
    modifiers.tournament,
    modifiers.league,
    conditionsAtWave,
  )
}

/** Stored skip % → tier/BC-adjusted effective skip % for this wave. Not wave-scaled. */
export function computeEffectiveSkipPct(
  skipPct: number,
  bcCounterLabLevels: Record<string, number>,
  tier: number,
  wave: number,
  tournament = false,
  tournamentLeague: TournamentLeague | null = null,
  battleConditions: readonly BattleConditionSelection[] = [],
): number {
  const stored = clamp(skipPct, 0, 100) / 100
  if (!tournament && tier < BC_TIER_MIN) {
    return clamp(stored * 100, 0, 100)
  }
  const adjustments = buildWorkshopTierSkipChanceAdjustments(
    tier,
    bcCounterLabLevels,
    tournament,
    tournamentLeague,
    wave,
    battleConditions as BattleConditionSelection[],
  )
  return clamp(applyTierBattleConditionsToSkipChance(stored, adjustments) * 100, 0, 100)
}

export interface AdjustedEnemyWaveStats {
  tier: number
  wave: number
  enemyType: EnemyWaveEnemyType
  effectiveHpWave: number
  effectiveDamageWave: number
  baseHp: number
  baseDamage: number
  adjustedHp: number
  adjustedDamage: number
  hpPerkMultiplier: number
  damagePerkMultiplier: number
  hpLabMultiplier: number
  damageLabMultiplier: number
}

export function getAdjustedEnemyWaveStats(
  tier: number,
  wave: number,
  enemyType: EnemyWaveEnemyType,
  perks: EnemyStatsPerkState,
  modifiers: EnemyStatsModifierState = DEFAULT_ENEMY_STATS_MODIFIERS,
): AdjustedEnemyWaveStats {
  const t = clampCampaignTier(tier)
  const w = Math.max(1, Math.floor(wave))
  // Run wave → skip/BC-adjusted stat level → GetWaveBase* → type mults + Wave Info BC rules.
  const hpWave = resolveStatLevel(w, modifiers.healthSkipPct, modifiers.healthSkipCount, modifiers)
  const damageWave = resolveStatLevel(w, modifiers.attackSkipPct, modifiers.attackSkipCount, modifiers)

  const waveContext = modifiers.tournament ? { tournament: true as const } : false
  const basicHp = getBasicEnemyWaveStats(t, hpWave, waveContext)
  const basicDamage = getBasicEnemyWaveStats(t, damageWave, waveContext)
  // Overcharge's attack damage is pinned to wave 1, so its row needs the tier's wave-1 base.
  const waveOneDamage = getBasicEnemyWaveStats(t, 1, waveContext)
  const conditionsAtWave = battleConditionsAtWave(w, modifiers)

  const effectivePerks = modifiers.tournament ? NO_PERKS : perks

  const enemyLabBenefitAtLevel = (slug: string, level: number) => {
    const lab = findToolLabBySlug(slug)
    return lab
      ? computeLabValueAtLevel(lab, clamp(Math.floor(level), 0, computeResearchLabMaxLevel(slug)))
      : 0
  }

  const bossHealthLabRecord = findToolLabBySlug('boss_health')
  const bossHealthLabValuePerLevel = typeof bossHealthLabRecord?.value === 'number'
    ? bossHealthLabRecord.value
    : 0.3

  const enemyLabLevels = normalizeEnemyLabLevels({
    ...Object.fromEntries(ENEMY_STATS_CALCS_RESEARCH_LAB_SLUGS.map(slug => [slug, 0])),
    ...modifiers.enemyLabLevels,
  })

  const hpLabMult = enemyType === 'Boss'
    ? waveInfoBossHpWorkshopMult(enemyLabLevels, enemyLabBenefitAtLevel, bossHealthLabValuePerLevel)
    : waveInfoEnemyLabMultiplierForRow(enemyType, 'hp', enemyLabLevels, enemyLabBenefitAtLevel)
  const attackLabMult = waveInfoEnemyLabMultiplierForRow(enemyType, 'attack', enemyLabLevels, enemyLabBenefitAtLevel)

  const pipeline = computeWaveInfoDisplayStats({
    waveBaseHp: basicHp.hp,
    waveBaseDamage: basicDamage.damage,
    waveOneBaseDamage: waveOneDamage.damage,
    wave: w,
    tier: t,
    enemyType,
    battleConditions: conditionsAtWave,
    bcLabLevels: mergeWorkshopBcLabLevels(modifiers.bcCounterLabLevels, modifiers.enemyLabLevels),
    labBenefitIncreaseAtLevel: bcCounterLabBenefitIncreaseAtLevel,
    enemyLabLevels,
    enemyLabBenefitAtLevel,
    bossHealthLabValuePerLevel,
    bossUltimateHeatFactor: modifiers.tournament && modifiers.league
      ? computeBossUltimateHeatFactor(modifiers.league, w)
      : 1,
    perks: effectivePerks,
    improveTradeOffLabPct: getImproveTradeOffLabPct(modifiers.improveTradeOffLabLevel),
  })

  return {
    tier: t,
    wave: w,
    enemyType,
    effectiveHpWave: hpWave,
    effectiveDamageWave: damageWave,
    baseHp: Math.floor(pipeline.stages.afterTypeRulesHp),
    baseDamage: Math.floor(waveBaseDamageForHeader(pipeline.stages.afterTypeRulesDamage)),
    adjustedHp: pipeline.hp,
    adjustedDamage: pipeline.damage,
    hpPerkMultiplier: pipeline.stages.hpPagePerkMult,
    damagePerkMultiplier: pipeline.stages.damagePagePerkMult,
    hpLabMultiplier: hpLabMult,
    damageLabMultiplier: attackLabMult,
  }
}

export interface EnemyWavePanelResult {
  tier: number
  wave: number
  waveBaseHp: number
  waveBaseDamage: number
  healthEffectiveSkipPct: number
  attackEffectiveSkipPct: number
  rows: AdjustedEnemyWaveRow[]
  footer: ReturnType<typeof computeWaveInfoPanelSummary>
}

export interface EnemyWavePanelInput {
  tier: number
  wave: number
  perks?: EnemyStatsPerkState
  modifiers?: Partial<EnemyStatsModifierState>
  /** Masteries/lab levels for the footer + spawn extras; all optional (default 0). */
  cardOptions?: {
    enemyBalanceMastery?: number | null
    waveAcceleratorMastery?: number | null
    waveAcceleratorLevel?: number | null
    protectorRadiusLabLevel?: number
    protectorDamageReduction?: number
  }
  /** Which enemy types to include, in order. Defaults to all. */
  enemyTypes?: readonly EnemyWaveEnemyType[]
}

/**
 * The whole Wave Info panel for one tier/wave: every enemy type's HP, damage,
 * spawn chance, speed and mass, plus the wave base row, the wave footer, and the
 * effective skip percentages. This is exactly what the site's From-Wave view shows.
 */
export function computeEnemyWavePanel(input: EnemyWavePanelInput): EnemyWavePanelResult {
  const perks = input.perks ?? NO_PERKS
  const modifiers: EnemyStatsModifierState = {
    ...DEFAULT_ENEMY_STATS_MODIFIERS,
    ...input.modifiers,
    tier: input.tier,
    wave: input.wave,
  }
  const t = clampCampaignTier(input.tier)
  const w = Math.max(1, Math.floor(input.wave))
  const types = input.enemyTypes ?? ENEMY_WAVE_TYPE_OPTIONS
  const conditionsAtWave = battleConditionsAtWave(w, modifiers)

  const rows: AdjustedEnemyWaveRow[] = types.map(enemyType => {
    const row = getAdjustedEnemyWaveStats(t, w, enemyType, perks, modifiers)
    const extras = computeWaveInfoPanelEnemyExtras({
      tier: t,
      wave: w,
      enemyType,
      battleConditions: conditionsAtWave,
      bcLabLevels: mergeWorkshopBcLabLevels(modifiers.bcCounterLabLevels, modifiers.enemyLabLevels),
      labBenefitIncreaseAtLevel: bcCounterLabBenefitIncreaseAtLevel,
      enemyBalanceMastery: input.cardOptions?.enemyBalanceMastery ?? undefined,
      tournament: modifiers.tournament,
      league: modifiers.league,
    })
    return {
      enemyType,
      spawnChancePct: extras.spawnChancePct,
      spawnColumn: extras.spawnColumn,
      baseHp: row.baseHp,
      baseDamage: row.baseDamage,
      adjustedHp: row.adjustedHp,
      adjustedDamage: row.adjustedDamage,
      speed: extras.speed,
      mass: extras.mass,
      hpPerkMultiplier: row.hpPerkMultiplier,
      damagePerkMultiplier: row.damagePerkMultiplier,
    }
  })

  // Wave base row: Basic-type stats before per-type rules, as the site shows it.
  const waveBase = getAdjustedEnemyWaveStats(t, w, 'Basic', perks, modifiers)

  const footer = computeWaveInfoPanelSummary(t, w, {
    protectorRadiusLabLevel: input.cardOptions?.protectorRadiusLabLevel ?? modifiers.enemyLabLevels.protector_radius ?? 0,
    protectorDamageReduction: input.cardOptions?.protectorDamageReduction,
    healthSkips: modifiers.healthSkipCount ?? 0,
    attackSkips: modifiers.attackSkipCount ?? 0,
    waveAcceleratorMastery: input.cardOptions?.waveAcceleratorMastery ?? undefined,
    waveAcceleratorLevel: input.cardOptions?.waveAcceleratorLevel ?? undefined,
    enemyBalanceMastery: input.cardOptions?.enemyBalanceMastery ?? undefined,
    tournament: modifiers.tournament,
  })

  return {
    tier: t,
    wave: w,
    waveBaseHp: waveBase.baseHp,
    waveBaseDamage: waveBase.baseDamage,
    healthEffectiveSkipPct: computeEffectiveSkipPct(
      modifiers.healthSkipPct,
      modifiers.bcCounterLabLevels,
      t,
      w,
      modifiers.tournament,
      modifiers.league,
      conditionsAtWave,
    ),
    attackEffectiveSkipPct: computeEffectiveSkipPct(
      modifiers.attackSkipPct,
      modifiers.bcCounterLabLevels,
      t,
      w,
      modifiers.tournament,
      modifiers.league,
      conditionsAtWave,
    ),
    rows,
    footer,
  }
}
