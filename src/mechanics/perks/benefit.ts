/**
 * `Perks.PerkBenefitUp` and `PerkBenefitDown`, as the game computes them.
 *
 * Verified against the game at v28.3.0. There is one arithmetic core and five
 * routing rules around it, and the routing is the part everything gets wrong.
 *
 * ## The core
 *
 *     raw = base[i] + increase[i] * quantity
 *
 * `base` is 1 for the seven "x1.15"-style perks and 0 for everything else — it
 * is the implicit 1, not a flag about which formula to use. The wiki prints two
 * formulas; the game has this one.
 *
 * ## The routing
 *
 * | perks | result |
 * |---|---|
 * | 4, 7 and every UW perk 20-28 | `raw`, with NO lab scaling |
 * | other standard perks 0-14 | `raw * (1 + StandardPerksBonus)` |
 * | trade-offs 40, 41, 44, 46, 47, 49 | `raw * (1 + ImproveTradeOffPerks)` |
 * | trade-offs 42, 43, 45 | `1 - raw * (1 + ImproveTradeOffPerks)` |
 * | trade-off 48 | `1 - raw * (1 + ImproveTradeOffPerks / 2)` |
 *
 * Two different labs, and they are easy to swap: research **83** is Standard
 * Perks Bonus and **88** is Improve Trade-off Perks. An earlier note in this
 * repo said the standard formula used 88; it does not, and using the trade-off
 * lab to scale a standard perk would be wrong in a way no test would notice
 * because both numbers are small and both are "a lab".
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    PERK_LAB_RESEARCH_INDEX, PERK_INDICES_WITHOUT_LAB_SCALING, PERK_INDICES_RETURNING_COMPLEMENT, PERK_INDEX_WITH_HALF_LAB, PerkBenefitInput, perkMaxLevel, computePerkBenefitUp, computePerkBenefitDown (+2 more)
 * depends    src/data/generated, src/support/own-lookup
 * used by    src/knowledge/compartments/perks, src/mechanics/calculators/specs-generated, src/mechanics/index, src/mechanics/perks/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { ownLookup } from '../../support/own-lookup'
import {
  V283_PERK_BENEFIT_DOWN,
  V283_PERK_BENEFIT_UP_BASE,
  V283_PERK_BENEFIT_UP_INCREASE,
  V283_PERK_MAX_LEVEL,
} from '../../data/generated'

/** `researchBenefitIncrease` indices the two perk labs occupy. */
export const PERK_LAB_RESEARCH_INDEX = {
  standardPerksBonus: 83,
  improveTradeOffPerks: 88,
} as const

/** Perks whose benefit ignores both labs entirely. */
export const PERK_INDICES_WITHOUT_LAB_SCALING: readonly number[] = [
  4, 7,
  20, 21, 22, 23, 24, 25, 26, 27, 28,
]

/** Trade-offs whose benefit is returned as `1 - value`, i.e. a survival multiplier. */
export const PERK_INDICES_RETURNING_COMPLEMENT: readonly number[] = [42, 43, 45, 48]

/** The one trade-off that gets only half the lab's effect. */
export const PERK_INDEX_WITH_HALF_LAB = 48

export interface PerkBenefitInput {
  /** Perk catalog index. */
  index: number
  /** How many times it has been taken this run. Clamped to the perk's maximum. */
  quantity: number
  /** `Standard Perks Bonus` lab benefit, as a fraction (0.08 for 8%). */
  standardPerksBonus?: number
  /** `Improve Trade-off Perks` lab benefit, as a fraction. */
  improveTradeOffPerks?: number
  /** Return the value of ONE level, the way the game's UI preview does. */
  onlyOneLevel?: boolean
}

function table(source: unknown, index: number): number | undefined {
  // Own keys only: these tables are indexed by a save value, and a plain lookup returns a
  // prototype member for `constructor` or `toString` — from a `number | undefined` return.
  return ownLookup(source as Record<string, number>, String(index))
}

/** The maximum times a perk can be taken, from the game. */
export function perkMaxLevel(index: number): number | null {
  return table(V283_PERK_MAX_LEVEL, index) ?? null
}

/**
 * The benefit a perk contributes at a given quantity.
 *
 * Returns `null` for an index the game has no perk at — the index space is
 * 0-14, 20-28 and 40-49, and the gaps are real rather than unfilled.
 */
export function computePerkBenefitUp(input: PerkBenefitInput): number | null {
  const { index } = input
  const max = perkMaxLevel(index)
  if (max === null) return null

  const base = table(V283_PERK_BENEFIT_UP_BASE, index) ?? 0
  const increase = table(V283_PERK_BENEFIT_UP_INCREASE, index) ?? 0

  const quantity = input.onlyOneLevel
    ? 1
    : Math.min(Math.max(0, Math.floor(input.quantity)), max)
  const raw = base + increase * quantity

  if (PERK_INDICES_WITHOUT_LAB_SCALING.includes(index)) return raw

  if (index <= 19) {
    return raw * (1 + (input.standardPerksBonus ?? 0))
  }

  const tradeOffLab = input.improveTradeOffPerks ?? 0
  if (index === PERK_INDEX_WITH_HALF_LAB) {
    return 1 - raw * (1 + tradeOffLab / 2)
  }
  if (PERK_INDICES_RETURNING_COMPLEMENT.includes(index)) {
    return 1 - raw * (1 + tradeOffLab)
  }
  return raw * (1 + tradeOffLab)
}

/**
 * The penalty side of a trade-off perk.
 *
 * Flat: the Improve Trade-off Perks lab raises the benefit only, which is what
 * the wiki says and what the table shows — there is no lab term here.
 */
export function computePerkBenefitDown(index: number): number | null {
  const value = table(V283_PERK_BENEFIT_DOWN, index)
  return value ?? null
}

/**
 * Does this perk's returned value carry an implicit 1?
 *
 * The question people mean when they ask whether a perk is "multiplicative".
 * With no implicit 1, stacking is LINEAR: two stacks of a `base = 0` perk give
 * `2 * increase`, not `1 + 2 * increase`.
 */
export function perkCarriesIdentityTerm(index: number): boolean {
  return (table(V283_PERK_BENEFIT_UP_BASE, index) ?? 0) === 1
}

/**
 * Total benefit for a whole run's worth of perks.
 *
 * Takes quantities per index and returns the benefit per index. Deliberately
 * does NOT combine them into one number: the values land on different stats
 * through different operations, and a single "total perk multiplier" is the
 * kind of summary that reads as useful and is never correct.
 */
export function computePerkBenefits(
  quantities: Readonly<Record<number, number>>,
  labs: Pick<PerkBenefitInput, 'standardPerksBonus' | 'improveTradeOffPerks'> = {},
): Map<number, number> {
  const out = new Map<number, number>()
  for (const [key, quantity] of Object.entries(quantities)) {
    const index = Number(key)
    const value = computePerkBenefitUp({ index, quantity, ...labs })
    if (value !== null) out.set(index, value)
  }
  return out
}
