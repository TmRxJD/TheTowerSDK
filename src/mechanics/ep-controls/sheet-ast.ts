/**
 * Semantic sheet AST for Effective Paths planner panels.
 *
 * Built by `scripts/effective-paths/build-sheet-ast.mjs` from the enriched
 * control-surface capture (dataValidation → controlType) plus web-control-map.
 * layoutBlocks group controls under sheet section headers / paint clusters.
 *
 * This is the IR the web compiler gate validates against — not a second
 * hand-written inventory of what the page "should" show.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    EP_SHEET_AST_SHEET_VERSION, EP_SHEET_AST_SCHEMA_VERSION, epSheetAstTabs, epSheetAstControls, epSheetAstInteractiveControls, epSheetAstControlsMissingUi, epSheetAstBoundInteractiveControls
 * depends    src/mechanics/ep-controls/data/sheet-ast.v1.json, src/mechanics/ep-controls/types
 * used by    src/calculators/specs.generated, src/mechanics/ep-controls/control-relations, src/mechanics/ep-controls/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import astRaw from './data/sheet-ast.v1.json'
import type { EpSheetAstControl, EpSheetAstTab } from './types'

interface RawAst {
  schemaVersion: number
  sheetVersion: string
  builtAt: string
  stats: {
    interactive: number
    boundInteractive: number
    missingUiInteractive: number
  }
  interactiveControlTypes: readonly string[]
  tabs: Record<string, EpSheetAstTab>
}

const AST = astRaw as RawAst

export const EP_SHEET_AST_SHEET_VERSION = AST.sheetVersion
export const EP_SHEET_AST_SCHEMA_VERSION = AST.schemaVersion

export function epSheetAstTabs(): Readonly<Record<string, EpSheetAstTab>> {
  return AST.tabs
}

/** Every control across all layout blocks. */
export function epSheetAstControls(): EpSheetAstControl[] {
  return Object.values(AST.tabs).flatMap(tab =>
    tab.layoutBlocks.flatMap(block => [...block.controls]))
}

/**
 * Interactive controls a player can flip on a reachable tab.
 * Excludes mirrors (eRegen spill of eHP) — those are the same control twice.
 */
export function epSheetAstInteractiveControls(): EpSheetAstControl[] {
  return epSheetAstControls().filter(control =>
    control.interactive
    && !control.mirroredFrom
    && AST.tabs[control.tab]?.playerVisible !== false)
}

/**
 * Interactive controls that still need a web binding or UI.
 * Statuses that explain absence (header / display / ids_derived) are excluded.
 */
export function epSheetAstControlsMissingUi(): EpSheetAstControl[] {
  const explained = new Set([
    'header',
    'display_only',
    'ids_derived',
    'mirrored',
    'non_sheet',
  ])
  return epSheetAstInteractiveControls().filter(control =>
    control.webStatus === 'missing_ui'
    || control.webStatus === 'unmapped'
    || (!explained.has(control.webStatus) && !control.webKey
      && control.webStatus !== 'bound'
      && control.webStatus !== 'bound_buried'))
}

/** Bound interactive controls — the compiler gate's primary work list. */
export function epSheetAstBoundInteractiveControls(): EpSheetAstControl[] {
  return epSheetAstInteractiveControls().filter(control =>
    (control.webStatus === 'bound' || control.webStatus === 'bound_buried')
    && control.webKey != null)
}
