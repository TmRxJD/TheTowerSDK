export function normalizeIlmCalcsLocalState(
  input: Partial<IlmCalcsLocalState> | null | undefined,
  fallback: IlmCalcsLocalState = { settings: defaultIlmCalcsSettings() },
): IlmCalcsLocalState {
  const settings = normalizeIlmCalcsSettings(
    (input?.settings ?? input) as Partial<IlmCalcsSettings>,
    fallback.settings,
  )
  return { settings }
}

export function patchIlmCalcsSettings(
  current: IlmCalcsSettings,
  patch: Partial<IlmCalcsSettings> & {
    static?: Partial<IlmCalcsStaticSettings>
    scenario?: Partial<IlmCalcsScenarioSettings>
  },
): IlmCalcsSettings {
  return normalizeIlmCalcsSettings({
    static: { ...current.static, ...patch.static },
    scenario: { ...current.scenario, ...patch.scenario },
  }, current)
}
