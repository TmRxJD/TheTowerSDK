function clampPct(value: unknown, fallback: number): number {
  const n = Math.floor(Number(value))
  if (!Number.isFinite(n)) return fallback
  return clampAssistMultiplierEfficiencyPct(n)
}

function normalizeStaticSettings(
  input: Partial<IlmCalcsStaticSettings> | null | undefined,
  fallback: IlmCalcsStaticSettings,
): IlmCalcsStaticSettings {
  const src = (input ?? {}) as Partial<IlmCalcsStaticSettings> & Record<string, unknown>
  let dimensionCoreRarity = normalizeUniqueModuleRarity(
    src.dimensionCoreRarity,
    fallback.dimensionCoreRarity,
  )
  let acpRarity = normalizeUniqueModuleRarity(src.acpRarity, fallback.acpRarity)
  let singularityHarnessEquipped = src.singularityHarnessEquipped ?? fallback.singularityHarnessEquipped

  const primaryCoreRaw = (src.primaryCore ?? {}) as Record<string, unknown>
  if (primaryCoreRaw.templateId === ILM_UNIQUE_MODULE_IDS.dimensionCore) {
    dimensionCoreRarity = normalizeUniqueModuleRarity(primaryCoreRaw.rarity, dimensionCoreRarity)
  }
  const armorModule = src.armorModule as { templateId?: string; rarity?: string } | undefined
  if (armorModule?.templateId === ILM_UNIQUE_MODULE_IDS.antiCubePortal) {
    acpRarity = normalizeUniqueModuleRarity(armorModule.rarity, acpRarity)
  }
  const generatorModule = src.generatorModule as { templateId?: string } | undefined
  if (generatorModule?.templateId === ILM_UNIQUE_MODULE_IDS.singularityHarness) {
    singularityHarnessEquipped = true
  }

  const dcLegacy = src.dimensionCore as { equipped?: boolean; rarity?: string } | undefined
  if (dcLegacy?.equipped) {
    dimensionCoreRarity = normalizeUniqueModuleRarity(dcLegacy.rarity, 'Epic')
  }
  const acpLegacy = src.antiCubePortal as { equipped?: boolean; rarity?: string } | undefined
  if (acpLegacy?.equipped) {
    acpRarity = normalizeUniqueModuleRarity(acpLegacy.rarity, 'Epic')
  }
  const shLegacy = src.singularityHarness as { equipped?: boolean } | undefined
  if (shLegacy?.equipped) singularityHarnessEquipped = true

  return {
    attackDamageLevel: Math.max(1, clampLevel(src.attackDamageLevel, fallback.attackDamageLevel, 99999)),
    primaryCannon: normalizeModuleLevelRarity(
      src.primaryCannon as Partial<IlmModuleLevelRarity> | undefined,
      fallback.primaryCannon,
    ),
    assistCannon: normalizeModuleLevelRarity(
      src.assistCannon as Partial<IlmModuleLevelRarity> | undefined,
      fallback.assistCannon,
    ),
    primaryCore: normalizeCoreModuleLevelRarity(
      primaryCoreRaw as Partial<IlmCoreModuleLevelRarity>,
      fallback.primaryCore,
    ),
    assistCore: normalizeCoreModuleLevelRarity(
      src.assistCore as Partial<IlmCoreModuleLevelRarity> | undefined,
      fallback.assistCore,
    ),
    assistEffPct: clampPct(src.assistEffPct, fallback.assistEffPct),
    dimensionCoreRarity,
    acpRarity,
    singularityHarnessEquipped: Boolean(singularityHarnessEquipped),
    damageLevel: clampLevel(src.damageLevel, fallback.damageLevel, 30),
    quantityLevel: clampLevel(src.quantityLevel, fallback.quantityLevel, 3),
    cooldownLevel: clampLevel(src.cooldownLevel, fallback.cooldownLevel, 15),
    chargedMinesLevel: clampLevel(src.chargedMinesLevel, fallback.chargedMinesLevel, 14),
    chronoJumpLabLevel: clampLevel(src.chronoJumpLabLevel, fallback.chronoJumpLabLevel, 10),
    chargedMinesActive: src.chargedMinesActive ?? fallback.chargedMinesActive,
    shockMultiplierLabLevel: clampLevel(src.shockMultiplierLabLevel, fallback.shockMultiplierLabLevel, 30),
    protectorReductionLabLevel: clampLevel(
      src.protectorReductionLabLevel,
      fallback.protectorReductionLabLevel,
      20,
    ),
    amplifyBotBonusLevel: clampLevel(src.amplifyBotBonusLevel, fallback.amplifyBotBonusLevel, 30),
  }
}

function normalizeScenarioSettings(
  input: Partial<IlmCalcsScenarioSettings> | null | undefined,
  fallback: IlmCalcsScenarioSettings,
  legacyMineAgeWaves?: number,
): IlmCalcsScenarioSettings {
  const src = input ?? {}
  const mineAgeWaves = src.mineAgeWaves != null
    ? clampNonNegative(src.mineAgeWaves, fallback.mineAgeWaves)
    : (legacyMineAgeWaves ?? fallback.mineAgeWaves)

  return {
    mineAgeWaves,
    timesHitByIlm: clampLevel(src.timesHitByIlm, fallback.timesHitByIlm, 999999),
    enemyShocked: src.enemyShocked ?? fallback.enemyShocked,
    shockStack: clampLevel(src.shockStack, fallback.shockStack, 999),
    enemyFlameTagged: src.enemyFlameTagged ?? fallback.enemyFlameTagged,
    amplifyBotOnEnemy: src.amplifyBotOnEnemy ?? fallback.amplifyBotOnEnemy,
    acpShockwaveActive: src.acpShockwaveActive ?? fallback.acpShockwaveActive,
    protectorAuraActive: src.protectorAuraActive ?? fallback.protectorAuraActive,
  }
}

