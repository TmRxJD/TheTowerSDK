function normalizeUniqueModuleRarity(
  value: unknown,
  fallback: IlmUniqueModuleRarityChoice,
): IlmUniqueModuleRarityChoice {
  if (value === ILM_MODULE_SUBSTAT_NONE) return ILM_MODULE_SUBSTAT_NONE
  if (value === 'Epic' || value === 'Legendary' || value === 'Mythic' || value === 'Ancestral') {
    return value
  }
  if (typeof value === 'string' && value.startsWith('Ancestral')) return 'Ancestral'
  return fallback
}

