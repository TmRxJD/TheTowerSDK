export interface IlmHitDamageBreakdown {
  hitDamage: number
  towerDamage: number
  ilmDamageMult: number
  moduleMult: number
  charge: number
  hitMultiplier: number
  ultimateCritDisplayFactor: number
}

export function computeIlmHitDamage(input: IlmHitDamageInput): IlmHitDamageBreakdown {
  const towerDamage = Math.max(0, input.towerDamage)
  const ilmDamageMult = Math.max(0, input.ilmDamageMult)
  const charge = Math.max(0, input.charge)
  const moduleMult = ultimateModuleMultiplier(input.moduleBonus ?? 0)
  const hitMultiplier = Math.max(0, input.hitMultiplier ?? 1)
  const ultimateCritDisplayFactor = Math.max(0, input.ultimateCritDisplayFactor ?? 1)

  const hitDamage = towerDamage
    * ilmDamageMult
    * moduleMult
    * charge
    * hitMultiplier
    * ultimateCritDisplayFactor

  return {
    hitDamage,
    towerDamage,
    ilmDamageMult,
    moduleMult,
    charge,
    hitMultiplier,
    ultimateCritDisplayFactor,
  }
}

