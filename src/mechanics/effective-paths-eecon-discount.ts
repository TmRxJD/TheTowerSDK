/**
 * `EPC_MOD_DISCOUNT`'s base — coins sunk into the equipped modules.
 *
 * Cumulative module upgrade cost over each of the preset's eight slots, with an
 * empty slot counting as one level. Measured, not inferred: with every slot
 * empty the live function returns `80,000` (eight slots at `10,000`), and with
 * one module at level 100 equipped it returns `16,296,510,000` — the table's
 * cumulative cost to level 100 plus `7 × 10,000` for the rest.
 */
export function moduleCoinsInvested(slotLevels: readonly number[]): number {
  let total = 0
  for (const slotLevel of slotLevels) {
    const level = Math.max(1, Math.floor(slotLevel || 0))
    for (let at = 1; at <= level; at++) total += moduleUpgradeCoinCost(at) ?? 0
  }
  return total
}

/**
 * Labs whose cost `EPC_LAB_DISCOUNT` does not count.
 *
 * These four are the only labs in the game's cost table with no row in
 * `DVT_Laboratory_Unlock`, and they are exactly the four the live function
 * ignores — setting any of them to its maximum moves its answer by nothing,
 * while every other lab moves it by its own remaining cost. They are also the
 * four most expensive labs by a wide margin, at `3.835e23` each against a
 * `4.9e22` total for everything else, so counting them would swamp the answer.
 */
export const LAB_DISCOUNT_UNCOUNTED_LABS: readonly string[] = [
  'overcharge_enemy_health',
  'overcharge_enemy_damage',
  'commander_enemy_health',
  'saboteur_enemy_health',
]

/**
 * `EPC_LAB_DISCOUNT`'s base — the coins every lab still has left to buy.
 *
 * Measured rather than guessed, on a frozen copy of the player state: setting a
 * lab to its maximum drops the live function by exactly that lab's remaining
 * cost, and setting every lab to its maximum takes it to within `1e18` of zero
 * from `4.897e22`. So it is remaining cost, summed over every counted lab.
 *
 * Two differences from the sheet's own answer, both understood:
 *
 * - Over the labs both carry, this lands within **0.035%**.
 * - It counts **40 labs the sheet's cost table does not have** — the masteries
 *   and the three Enemy Defense labs — worth another 0.7%. Those are levels a
 *   player really does have left to buy, so they are counted deliberately
 *   rather than dropped to match a table that predates them.
 *
 * The sheet's table also carries one row beyond each lab's maximum for 156
 * labs; `LAB_CATALOG` stops at the maximum, which is where the live function
 * stops too.
 */
export function labCoinsRemaining(levelOf: (labName: string) => number): number {
  const uncounted = new Set(LAB_DISCOUNT_UNCOUNTED_LABS)
  let total = 0
  for (const record of LAB_CATALOG) {
    if (uncounted.has(record.slug) || uncounted.has(record.name)) continue
    const level = Math.max(0, Math.floor(levelOf(record.slug) || levelOf(record.name) || 0))
    for (const entry of record.levels) {
      if (entry.level > level) total += entry.cost
    }
  }
  return total
}

/** A discount candidate, keyed as `EffectiveEconomyLevels['discount']` is. */
export type EffectiveEconomyDiscountKey = keyof EffectiveEconomyLevels['discount']

/**
 * The account totals the priority selector weighs.
 *
 * Coins, all of them, and all undiscounted — the discount level is applied by
 * {@link effectiveEconomyDiscountValue} rather than baked in here.
 */
export interface EffectiveEconomyDiscountTotals {
  /** `EPC_LAB_DISCOUNT`'s base — see the note above; not reproduced. */
  labCoins: number
  /** `WSPATTACK_TOTAL_COINS_INVESTED`. */
  enhancementAttackCoins: number
  /** `WSPDEFENSE_TOTAL_COINS_INVESTED`. */
  enhancementDefenseCoins: number
  /** `WSPUTILITY_TOTAL_COINS_INVESTED`. */
  enhancementUtilityCoins: number
  /** `EPC_MOD_DISCOUNT`'s base. */
  moduleCoins: number
}

/**
 * The five candidates `eEcon Discount!AY14` hides, and it is **on by default**.
 *
 * Read off the tab's own hide row: `CL2`, `CN2`, `CO2`, `CP2` and `CQ2` all
 * open with `OR(AY14, …)` and `CM2` — Labs Coin Discount — does not. So with
 * the sheet's shipped settings the discount path offers exactly one candidate.
 *
 * "Retroactive" is the sheet naming the oddity this port ran into while
 * modelling them: these five discount coins the player has **already spent**,
 * so their return is a retrospective saving rather than a cheaper next
 * purchase. The lab discount is the one that makes future levels cheaper.
 */
export const RETROACTIVE_DISCOUNT_LABS: readonly EffectiveEconomyDiscountKey[] = [
  'workshopUtilityDiscount',
  'enhancementAttackDiscount',
  'enhancementDefenseDiscount',
  'enhancementUtilityDiscount',
  'moduleCoinCost',
]

/** The lab behind each candidate, as the lab catalog names it. */
export const DISCOUNT_LAB_NAMES: Readonly<Record<EffectiveEconomyDiscountKey, string>> = {
  workshopUtilityDiscount: 'Workshop Utility Discount',
  labsCoinDiscount: 'Labs Coin Discount',
  enhancementAttackDiscount: 'Enhancement Attack - Coin Discount',
  enhancementDefenseDiscount: 'Enhancement Defense - Coin Discount',
  enhancementUtilityDiscount: 'Enhancement Utility - Coin Discount',
  moduleCoinCost: 'Module Coin Cost',
}

/** The fraction a level takes off, per candidate. */
const DISCOUNT_RATES: Readonly<Record<EffectiveEconomyDiscountKey, number>> = {
  workshopUtilityDiscount: 0.005,
  labsCoinDiscount: 0.003,
  enhancementAttackDiscount: 0.003,
  enhancementDefenseDiscount: 0.003,
  enhancementUtilityDiscount: 0.003,
  moduleCoinCost: 0.01,
}

/** Which total each candidate scales, or `null` for the multiplier one. */
const DISCOUNT_TOTALS: Readonly<
  Record<EffectiveEconomyDiscountKey, keyof EffectiveEconomyDiscountTotals | null>
> = {
  workshopUtilityDiscount: null,
  labsCoinDiscount: 'labCoins',
  enhancementAttackDiscount: 'enhancementAttackCoins',
  enhancementDefenseDiscount: 'enhancementDefenseCoins',
  enhancementUtilityDiscount: 'enhancementUtilityCoins',
  moduleCoinCost: 'moduleCoins',
}

/**
 * The five the priority selector chooses between, in the order it breaks ties.
 *
 * `IFS` returns the first branch whose gain equals the maximum, so the order is
 * the tie-break: Attack, Defense, Utility, Module, Laboratory. Workshop Utility
 * Discount is absent because the sheet never gates it — it competes every step.
 */
export const DISCOUNT_PRIORITY_ORDER: readonly EffectiveEconomyDiscountKey[] = [
  'enhancementAttackDiscount',
  'enhancementDefenseDiscount',
  'enhancementUtilityDiscount',
  'moduleCoinCost',
  'labsCoinDiscount',
]

/**
 * A candidate's value at a level.
 *
 * Coins for five of the six, and a cost multiplier for Workshop Utility
 * Discount — different quantities, which is why nothing sums these.
 */
export function effectiveEconomyDiscountValue(
  key: EffectiveEconomyDiscountKey,
  level: number,
  totals: EffectiveEconomyDiscountTotals,
): number {
  const at = Math.max(0, Math.floor(level))
  const rate = DISCOUNT_RATES[key]

  if (key === 'workshopUtilityDiscount') {
    const remaining = 1 - at * rate
    // The sheet's `1/(1-level*0.5%)` has a pole at level 200; the lab stops
    // well short, so a non-positive denominator means a level that cannot be.
    return remaining > 0 ? 1 / remaining : Number.POSITIVE_INFINITY
  }

  const total = totals[DISCOUNT_TOTALS[key] as keyof EffectiveEconomyDiscountTotals] ?? 0
  return total * (1 - at * rate)
}

/** Coins the next level saves. Zero for the multiplier candidate. */
export function effectiveEconomyDiscountSaving(
  key: EffectiveEconomyDiscountKey,
  level: number,
  totals: EffectiveEconomyDiscountTotals,
): number {
  if (key === 'workshopUtilityDiscount') return 0
  return effectiveEconomyDiscountValue(key, level, totals)
    - effectiveEconomyDiscountValue(key, level + 1, totals)
}

/** The relative return the sheet ranks a candidate by, per day of research. */
function relativeRoi(
  key: EffectiveEconomyDiscountKey,
  level: number,
  totals: EffectiveEconomyDiscountTotals,
  days: number,
): number {
  if (!Number.isFinite(days) || days <= 0) return 0

  const old = effectiveEconomyDiscountValue(key, level, totals)
  const next = effectiveEconomyDiscountValue(key, level + 1, totals)
  if (old <= 0 || next <= 0) return 0

  // Workshop Utility Discount grows and the rest shrink, so the ratio is taken
  // the way round that leaves a positive number in both cases.
  const ratio = key === 'workshopUtilityDiscount' ? next / old : old / next
  return (ratio - 1) / days
}

export interface EffectiveEconomyDiscountPlanOptions {
  totals: EffectiveEconomyDiscountTotals
  levels: EffectiveEconomyLevels['discount']
  steps?: number
  labModifiers?: LabCostModifiers
  /** A stop the player set, below the lab's own maximum. */
  targetLevels?: Partial<Record<EffectiveEconomyDiscountKey, number>>
  /**
   * Every candidate's return per step, not just the one bought.
   *
   * `eEcon Discount!CL4:CQ45` prices with the same two shapes `relativeRoi`
   * uses — `(New/Old-1)/Dur` for the multiplier and `(Old/New-1)/Dur` for the
   * rest — so the audit can compare them one for one.
   *
   * It fires for the CONTENDERS, which is the sheet's own board rather than all
   * six: `CM5` opens `CK5<>"Laboratory", ,` and each of the others gates on its
   * own category, so the sheet blanks every candidate except the multiplier and
   * the current priority. Emitting all six would invent a board neither side
   * ranks.
   */
  onCandidateRoi?: (entry: {
    step: number
    key: EffectiveEconomyDiscountKey
    name: string
    nextLevel: number
    roi: number
  }) => void

  /** Candidates to leave out entirely — a lab the player has not unlocked. */
  excludeKeys?: readonly EffectiveEconomyDiscountKey[]
  /**
   * `AY14`, which the sheet ships **on**: leave out the five candidates that
   * only discount coins already spent. Defaults to the sheet's own setting, so
   * a caller that says nothing gets the path the sheet would show.
   */
  hideRetroactiveDiscountLabs?: boolean
}

export interface EffectiveEconomyDiscountStep extends PathStep {
  /** Coins this step saves, or `0` for the multiplier candidate. */
  coinsSaved: number
  /** The category the priority selector picked for this step. */
  priority: EffectiveEconomyDiscountKey | null
}

export interface EffectiveEconomyDiscountPlan {
  steps: EffectiveEconomyDiscountStep[]
  /** Coins the whole path saves. */
  totalCoinsSaved: number
  excluded: PathExclusion[]
}

/**
 * `CK5` — which single category may compete this step.
 *
 * Absolute coins saved per day, not relative, so the totals matter here and
 * only here. Returns `null` when nothing is left to buy.
 */
export function effectiveEconomyDiscountPriority(
  levels: EffectiveEconomyLevels['discount'],
  totals: EffectiveEconomyDiscountTotals,
  options: { labModifiers?: LabCostModifiers, capOf?: (key: EffectiveEconomyDiscountKey) => number } = {},
): EffectiveEconomyDiscountKey | null {
  let best: { key: EffectiveEconomyDiscountKey, gain: number } | null = null

  for (const key of DISCOUNT_PRIORITY_ORDER) {
    const level = Math.max(0, Math.floor(levels[key] ?? 0))
    const cap = options.capOf?.(key) ?? labMaxCatalogLevel(DISCOUNT_LAB_NAMES[key])
    if (level + 1 > cap) continue

    const days = labDurationDaysToReachLevel(
      DISCOUNT_LAB_NAMES[key], level + 1, options.labModifiers,
    )
    if (days === null || days <= 0) continue

    const gain = effectiveEconomyDiscountSaving(key, level, totals) / days
    // Strictly greater keeps the first of an equal pair, which is the sheet's
    // `IFS` tie-break rather than a preference of this port's own.
    if (!best || gain > best.gain) best = { key, gain }
  }

  return best?.key ?? null
}

/**
 * Plan the discount path.
 *
 * Each step: the priority selector picks one of the five, that one and Workshop
 * Utility Discount are scored by relative return per day, and the better is
 * bought.
 *
 * `value` is what the sheet's own Coins Saved column shows, which is two
 * different quantities: the coins the step saves for five of the candidates,
 * and the new cost multiplier for Workshop Utility Discount. Read it alongside
 * `id`. `coinsSaved` is always coins, and always `0` for the multiplier, so it
 * is the one that can be summed.
 */
export function planEffectiveEconomyDiscountPath(
  options: EffectiveEconomyDiscountPlanOptions,
): EffectiveEconomyDiscountPlan {
  const { totals, labModifiers } = options
  const steps = options.steps ?? 145

  const current = { ...options.levels }
  const skipped = new Set(options.excludeKeys ?? [])
  if (options.hideRetroactiveDiscountLabs !== false) {
    for (const key of RETROACTIVE_DISCOUNT_LABS) skipped.add(key)
  }
  const capOf = (key: EffectiveEconomyDiscountKey) => (skipped.has(key)
    ? 0
    : Math.min(
      options.targetLevels?.[key] ?? Number.POSITIVE_INFINITY,
      labMaxCatalogLevel(DISCOUNT_LAB_NAMES[key]),
    ))

  const excluded: EffectiveEconomyDiscountPlan['excluded'] = []
  for (const key of Object.keys(DISCOUNT_LAB_NAMES) as EffectiveEconomyDiscountKey[]) {
    if (skipped.has(key)) {
      const retroactive = options.hideRetroactiveDiscountLabs !== false
        && RETROACTIVE_DISCOUNT_LABS.includes(key)
      excluded.push({
        sheetName: DISCOUNT_LAB_NAMES[key],
        reason: retroactive
          ? 'only discounts coins already spent — the sheet hides these by default'
          : 'not unlocked yet',
      })
      continue
    }
    if (labMaxCatalogLevel(DISCOUNT_LAB_NAMES[key]) > 0) continue
    excluded.push({ sheetName: DISCOUNT_LAB_NAMES[key], reason: 'no maximum level known' })
  }

  const path: EffectiveEconomyDiscountStep[] = []
  let cumulativeCost = 0
  let totalCoinsSaved = 0

  for (let step = 1; step <= steps; step++) {
    const priority = effectiveEconomyDiscountPriority(current, totals, { labModifiers, capOf })
    const contenders: EffectiveEconomyDiscountKey[] = ['workshopUtilityDiscount']
    if (priority) contenders.push(priority)

    let best: {
      key: EffectiveEconomyDiscountKey, roi: number, days: number, level: number
    } | null = null

    for (const key of contenders) {
      const level = Math.max(0, Math.floor(current[key] ?? 0))
      if (level + 1 > capOf(key)) continue

      const days = labDurationDaysToReachLevel(
        DISCOUNT_LAB_NAMES[key], level + 1, labModifiers,
      )
      if (days === null || days <= 0) continue

      const roi = relativeRoi(key, level, totals, days)
      if (roi <= 0) continue
      options.onCandidateRoi?.({
        step, key, name: DISCOUNT_LAB_NAMES[key], nextLevel: level + 1, roi,
      })
      if (!best || roi > best.roi) best = { key, roi, days, level: level + 1 }
    }

    if (!best) break

    const from = best.level - 1
    const coinsSaved = effectiveEconomyDiscountSaving(best.key, from, totals)
    cumulativeCost += best.days
    totalCoinsSaved += coinsSaved
    current[best.key] = best.level

    path.push({
      step,
      id: `discount.${best.key}`,
      name: DISCOUNT_LAB_NAMES[best.key],
      level: best.level,
      cost: best.days,
      cumulativeCost,
      gain: coinsSaved,
      roi: best.roi,
      value: best.key === 'workshopUtilityDiscount'
        ? effectiveEconomyDiscountValue(best.key, best.level, totals)
        : coinsSaved,
      coinsSaved,
      priority,
    })
  }

  return { steps: path, totalCoinsSaved, excluded }
}
