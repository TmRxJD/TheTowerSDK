export function foldWaveEconRows(rows: readonly WaveEconSimRow[]): WaveEconTotals {
  let expectedKills = 0
  let expectedEliteKills = 0
  let rawKillCoins = 0
  let waveCoins = 0
  let cells = 0
  let skipCells = 0
  let moduleShards = 0
  let moduleShardsOneType = 0
  let rerollShards = 0
  let bossWaves = 0
  let fleetWaves = 0

  for (const row of rows) {
    expectedKills += row.expectedKills
    expectedEliteKills += row.expectedEliteKills
    rawKillCoins += row.rawKillCoins
    waveCoins += row.waveCoins
    cells += row.cells
    skipCells += row.skipCells
    moduleShards += row.moduleShards
    moduleShardsOneType += row.moduleShardsOneType
    rerollShards += row.rerollShards
    if (row.isBossWave) bossWaves += 1
    if (row.isFleetWave) fleetWaves += 1
  }

  return {
    expectedKills,
    expectedEliteKills,
    rawKillCoins,
    waveCoins,
    cells,
    skipCells,
    moduleShards,
    moduleShardsOneType,
    rerollShards,
    bossWaves,
    fleetWaves,
  }
}

