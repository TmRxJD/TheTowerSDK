export function enemyDropYieldBreakdownFromWaveEconRows(
  rows: readonly WaveEconSimRow[],
  input: EnemyDropsSimulationInput,
): EnemyDropsYieldBreakdown {
  const labs = getEnemyDropsLabBenefits(input)
  let cellsFromElites = 0
  let cellsFromWaveSkip = 0
  let moduleShardsFromShatter = 0
  let rerollShardsFromBosses = 0
  let commonModulesDropped = 0
  let rareModulesDropped = 0

  for (const row of rows) {
    cellsFromElites += row.cells - row.skipCells
    cellsFromWaveSkip += row.skipCells
    moduleShardsFromShatter += row.moduleShards
    rerollShardsFromBosses += row.rerollShards
    if (row.isBossWave) {
      commonModulesDropped += labs.commonDropChance
      rareModulesDropped += labs.rareDropChance
    }
  }

  return {
    cellsFromElites,
    cellsFromWaveSkip,
    totalCells: cellsFromElites + cellsFromWaveSkip,
    moduleShardsFromDrops: 0,
    moduleShardsFromShatter,
    totalModuleShards: moduleShardsFromShatter,
    rerollShardsFromBosses,
    commonModulesDropped,
    rareModulesDropped,
  }
}

export function enemyDropYieldBreakdownFromPerWave(
  input: EnemyDropsSimulationInput,
  options: { maxRows?: number; spawnYield?: WaveSpawnYieldInput } = {},
): EnemyDropsYieldBreakdown {
  const waveInput = waveEconInputFromEnemyDrops(input)
  const rows = simulateWaveEconRows(waveInput, options)
  return enemyDropYieldBreakdownFromWaveEconRows(rows, input)
}
