/**
 * Per-wave cells and shard yields from elites, bosses and fleets — the drops that come from
 * special enemies rather than ordinary kills — as expected values for one wave.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    computeWaveDropYield
 * depends    src/mechanics/enemies/drops-game-data, src/mechanics/enemies/drops-simulation, src/mechanics/enemies/elite-spawn-chance, src/mechanics/resource-drops/card-rewards, src/mechanics/resource-drops/types
 * used by    src/calculators/specs.generated, src/mechanics/resource-drops/index, src/mechanics/resource-drops/simulate-wave-econ
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import {
  averageEliteCellsPerKill,
  cellsPerKillBonusMult,
} from '../enemies/drops-simulation'
import {
  computeWaveInfoBossWaveInterval,
  expectedEliteKillsPerWave,
  fleetSpawnSchedule,
  isBossSpawnWave,
  isFleetSpawnWave,
} from '../enemies/elite-spawn-chance'
import {
  FLEET_MODULE_SHARD_PROC,
  FLEET_REROLL_SHARD_PROC,
  expectedFleetModuleShardsEv,
  getEnemyDropsLabBenefits,
  getExpectedBossRerollShardsPerKill,
  getFleetRewardRow,
  getShatterShards,
} from '../enemies/drops-game-data'
import type { ResourceDropsCoinSimulationInput } from './types'
import type { WaveDropYieldRow } from './types'
import { cellsPerEliteAfterCard } from './card-rewards'

/**
 * Elite chart slots are absolute expected spawns per wave, including EB mastery.
 * The base Enemy Balance card affects ordinary enemies only, not these slots.
 * Firsthand distinction: https://www.reddit.com/r/TheTowerGame/comments/1hw2vnh/
 * and https://www.reddit.com/r/TheTowerGame/comments/1pnyign/cards/ .
 * @param enemyBalanceMult Legacy positional argument, retained for compatibility;
 * irrelevant to elite, boss and fleet reward counts.
 */
export function computeWaveDropYield(
  input: ResourceDropsCoinSimulationInput,
  wave: number,
  enemyBalanceMult: number,
  wsMult: number,
): WaveDropYieldRow {
  void enemyBalanceMult
  const tier = input.tier
  const w = Math.max(1, Math.floor(wave))
  const labs = getEnemyDropsLabBenefits(input)
  const baseCellsPerElite =
    averageEliteCellsPerKill(tier) * cellsPerKillBonusMult(input.cellsPerKillBonusLevel)
    + labs.deathWaveCellsBonus

  const expectedEliteKills =
    expectedEliteKillsPerWave(tier, w, { enemyBalanceMastery: input.enemyBalanceActive === false ? -1 : input.enemyBalanceMasteryLevel })

  const cells = expectedEliteKills * cellsPerEliteAfterCard(baseCellsPerElite, input) * wsMult
  let moduleShards = 0
  let moduleShardsOneType = 0
  let rerollShards = 0

  const bossInterval = computeWaveInfoBossWaveInterval({ tier })
  const isBossWave = isBossSpawnWave(w, bossInterval)

  if (isBossWave) {
    rerollShards += getExpectedBossRerollShardsPerKill(tier, labs.rerollShardsBenefit) * wsMult
    const commonShatterYield = getShatterShards('common', labs.shatterBenefit)
    const rareShatterYield = getShatterShards('rare', labs.shatterBenefit)
    if (input.shatterCommonModules) {
      moduleShards += labs.commonDropChance * commonShatterYield * wsMult
    }
    if (input.shatterRareModules) {
      moduleShards += labs.rareDropChance * rareShatterYield * wsMult
    }
  }

  const isFleetWave = isFleetSpawnWave(tier, w)
  let fleetCount = 0
  if (isFleetWave) {
    fleetCount = fleetSpawnSchedule(tier)?.fleetsPerSpawn ?? 0
    const fleetReward = getFleetRewardRow(tier)
    if (fleetReward && fleetCount > 0) {
      rerollShards +=
        fleetCount * FLEET_REROLL_SHARD_PROC * fleetReward.rerollShards * wsMult
      moduleShards = expectedFleetModuleShardsEv(
        fleetCount,
        fleetReward.moduleShardsPerType,
        wsMult,
        'allTypes',
      )
      moduleShardsOneType = expectedFleetModuleShardsEv(
        fleetCount,
        fleetReward.moduleShardsPerType,
        wsMult,
        'oneType',
      )
    }
  }

  return {
    expectedEliteKills,
    cells,
    moduleShards,
    moduleShardsOneType,
    rerollShards,
    isBossWave,
    isFleetWave,
    fleetCount,
  }
}
