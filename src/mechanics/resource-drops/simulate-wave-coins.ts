/**
 * A run's coins simulated wave by wave. `forEachWaveCoinRow` streams the rows,
 * `accumulateWaveCoin` folds them into totals in constant memory, and `simulateWaveCoinRows` keeps
 * every row.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    forEachWaveCoinRow, accumulateWaveCoin, simulateWaveCoinRows
 * depends    src/mechanics/enemies/drops-wave-context, src/mechanics/resource-drops/coin-multipliers, src/mechanics/resource-drops/types, src/mechanics/resource-drops/wave-ordinary-coin-weight, src/mechanics/resource-drops/wave-skip-per-wave, src/mechanics/waves/accelerator-spawn-rate-cap (+1 more)
 * used by    src/calculators/specs.generated, src/mechanics/resource-drops/accumulate-wave-econ, src/mechanics/resource-drops/coin-simulation, src/mechanics/resource-drops/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { buildWaveContext } from '../enemies/drops-wave-context'
import { findWaveAcceleratorMasteryForSpawnCap, enemySpawnRateCapFromWaveAcceleratorChart } from '../waves/accelerator-spawn-rate-cap'
import { killsPerWaveFromSpawnContext } from '../waves/spawn-yield'
import type { ResourceDropsCoinSimulationInput } from './types'
import { spawnYieldForWave } from './coin-multipliers'
import { buildWaveSkipPerWaveAdjust, waveSkipIncomeEv } from './wave-skip-per-wave'
import { ordinaryCoinWeightAtTier } from './wave-ordinary-coin-weight'
import type { WaveCoinSimRow, WaveCoinSimTotals, WaveCoinSimulationOptions } from './types'


function emptyWaveCoinTotals(): WaveCoinSimTotals {
  return {
    expectedKills: 0,
    rawKillCoins: 0,
    skipKillCoins: 0,
    waveCoins: 0,
    skipWaveCoins: 0,
  }
}

function foldWaveCoinRow(totals: WaveCoinSimTotals, row: WaveCoinSimRow): void {
  totals.expectedKills += row.expectedKills
  totals.rawKillCoins += row.rawKillCoins
  totals.skipKillCoins += row.skipKillCoins
  totals.waveCoins += row.waveCoins
  totals.skipWaveCoins += row.skipWaveCoins
}

export function forEachWaveCoinRow(
  input: ResourceDropsCoinSimulationInput,
  options: WaveCoinSimulationOptions,
  visit: (row: WaveCoinSimRow) => void,
): void {
  const timeline = input.perkCoinTimeline ?? []
  if (timeline.length > 4096) throw new RangeError('Perk coin timeline exceeds 4096 events')
  let previousWave = 0
  for (const event of timeline) {
    if (!Number.isInteger(event.wave) || event.wave <= previousWave || event.wave > 1_000_000
      || !Number.isFinite(event.coinMultiplier) || event.coinMultiplier < 1
      || !Number.isFinite(event.killCoinMultiplier ?? 1) || (event.killCoinMultiplier ?? 1) < 1) {
      throw new RangeError('Perk coin timeline requires sorted unique positive waves and finite multipliers at least 1')
    }
    previousWave = event.wave
  }
  if (input.perkCoinTimeline !== undefined && (input.allCoinPerkLevel > 0 || input.hasCoinTradeOffPerk)) {
    throw new RangeError('Perk coin timeline requires neutral static coin perks')
  }
  let timelineIndex = 0
  let perkCoinMultiplier = 1
  let perkKillCoinMultiplier = 1
  const ctx = buildWaveContext(input)
  const wsAdjust = buildWaveSkipPerWaveAdjust(
    ctx.waveSkipSkipChance,
    ctx.waveSkipExpectedSkipsPerProc,
  )
  const waMastery = findWaveAcceleratorMasteryForSpawnCap(input.waveAcceleratorMasteryLevel)
  const coinsPerWaveMult = options.coinsPerWaveMult
  const introCap = Math.max(0, Math.floor(Number(input.introSprintZeroCoinWaveCap) || 0))
  const limit = Math.min(
    ctx.targetWave,
    Math.max(1, Math.floor(Number(options.maxRows ?? ctx.targetWave) || ctx.targetWave)),
  )
  const coinWeightPerKill = ordinaryCoinWeightAtTier(input.tier, input)
  let prevRawKillCoins = 0
  let prevPlayedBaseKillCoins = 0
  let prevRawWaveCoins = 0
  let prevPlayedBaseWaveCoins = 0

  for (let wave = 1; wave <= limit; wave += 1) {
    while (timelineIndex < timeline.length && timeline[timelineIndex]!.wave <= wave) {
      const event = timeline[timelineIndex++]!
      perkCoinMultiplier = event.coinMultiplier
      perkKillCoinMultiplier = event.killCoinMultiplier ?? 1
    }
    const spawnFraction = wsAdjust.spawnFraction
    const spawnTicks = enemySpawnRateCapFromWaveAcceleratorChart({ wave, waveAcceleratorMastery: waMastery })
    const spawnYield = options.spawnYield ?? spawnYieldForWave(input, wave)
    const fullKills = killsPerWaveFromSpawnContext({
      wave,
      enemyBalanceMult: ctx.enemyBalanceMult,
      waveAcceleratorMastery: waMastery,
      spawnYield,
    })
    const expectedKills = fullKills * spawnFraction
    const rawKillCoins = wave <= introCap
      ? 0
      : expectedKills * wave * coinWeightPerKill * perkCoinMultiplier * perkKillCoinMultiplier
    const playedBaseKillCoins = rawKillCoins
    const skipKillCoins = wave > 1 && wave > introCap
      ? waveSkipIncomeEv(
        prevRawKillCoins,
        prevPlayedBaseKillCoins,
        ctx.waveSkipSkipChance,
        ctx.waveSkipExpectedSkipsPerProc,
        spawnFraction,
        wsAdjust.incomeMultiplier,
      )
      : 0
    const playedBaseWaveCoins = wave <= introCap ? 0 : coinsPerWaveMult * spawnFraction * perkCoinMultiplier
    const skipWaveCoins = wave > 1 && wave > introCap
      ? waveSkipIncomeEv(
        prevRawWaveCoins,
        prevPlayedBaseWaveCoins,
        ctx.waveSkipSkipChance,
        ctx.waveSkipExpectedSkipsPerProc,
        spawnFraction,
        wsAdjust.incomeMultiplier,
      )
      : 0
    const waveCoins = playedBaseWaveCoins + skipWaveCoins

    visit({
      wave,
      spawnTicks,
      expectedKills,
      rawKillCoins: playedBaseKillCoins + skipKillCoins,
      waveCoins,
      skipKillCoins,
      skipWaveCoins,
      spawnFraction,
      coinWeightPerKill,
    })
    prevRawKillCoins = playedBaseKillCoins + skipKillCoins
    prevPlayedBaseKillCoins = playedBaseKillCoins > 0 ? playedBaseKillCoins : prevPlayedBaseKillCoins
    prevRawWaveCoins = playedBaseWaveCoins + skipWaveCoins
    prevPlayedBaseWaveCoins = playedBaseWaveCoins > 0 ? playedBaseWaveCoins : prevPlayedBaseWaveCoins
  }
}

export function accumulateWaveCoin(
  input: ResourceDropsCoinSimulationInput,
  options: WaveCoinSimulationOptions,
): WaveCoinSimTotals {
  const totals = emptyWaveCoinTotals()
  forEachWaveCoinRow(input, options, (row) => foldWaveCoinRow(totals, row))
  return totals
}

export function simulateWaveCoinRows(
  input: ResourceDropsCoinSimulationInput,
  options: WaveCoinSimulationOptions,
): WaveCoinSimRow[] {
  const rows: WaveCoinSimRow[] = []
  forEachWaveCoinRow(input, options, (row) => rows.push(row))
  return rows
}
