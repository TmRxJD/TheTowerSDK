/**
 * The enemy type mix, measured from a save rather than assumed.
 *
 * ## Why this file exists
 *
 * Coins from kills is `kills x coin value`, and the coin value depends entirely
 * on WHICH enemies died: basic is worth 1, fast and ranged 2, tank 4. The
 * shipped coin simulation replaces that whole question with one blended
 * constant, `RESOURCE_DROPS_AVG_ENEMY_COIN_WEIGHT = 1.15`.
 *
 * A save carries the answer directly. `totalEnemiesDestroyed*ThisRound` gives
 * per-type kill counts, and they partition the round exactly — see
 * `enemy-type-mix.test.ts`, where the six named types plus the basic residual
 * reproduce the round total to the unit.
 *
 * ## What the measurement says
 *
 * Basic is the SMALLEST of the four ordinary types, not the largest:
 *
 *     measured          basic 19.9%  fast 28.3%  tank 26.7%  ranged 25.2%
 *     table (deleted)   basic 56-65% and the rest split between the other three
 *
 * The consequence for coins:
 *
 *     measured weight   2.34 coins per kill, relative to a basic
 *     superseded guess  1.15
 *
 * That is independent of, and compounds with, the 3-4x kill-volume shortfall in
 * `kills-per-wave-vs-save.test.ts`.
 *
 * ## The correction this file already needed once
 *
 * The first version took `basic` as the RESIDUAL - round total minus the other
 * counters - and then "verified" that the counters partitioned the round. That
 * is a tautology: a residual is defined to close the sum, so the check could
 * not fail. It gave basic 171,255 and a weight of 2.20.
 *
 * The game keeps its own count, `totalEnemiesDestroyedNormalThisRound`, and it
 * says 109,691. The named type counters therefore reach 560,076 of 621,640
 * kills, and 9.9% of the round is attributed to NO type at all - even after
 * adding every elite subtype the save names. What that residue is has not been
 * established, so it is left out rather than folded into basic.
 *
 * ## What this does NOT claim
 *
 * One round, one account, one tier. The mix shifts with wave — the round
 * measured here spans waves 600 to 4875 — so this is a round-average, not a
 * per-wave function. Deriving the per-wave curve needs the base chances, and
 * two of the five (`chanceFastEnemy`, `chanceRangedEnemy`) are written by no
 * method in `Main`: they are Unity Inspector-serialised and live in the scene
 * assets, not the binary. Until those are extracted, this average is the best
 * measured figure available and is honest about being an average.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    ENEMY_TYPE_BASE_COIN_VALUE, OrdinaryEnemyType, EnemyTypeCounts, MEASURED_ENEMY_TYPE_KILLS, enemyTypeShares, ordinaryKillTotal, averageEnemyCoinWeight, measuredAverageEnemyCoinWeight
 * depends    —
 * used by    src/knowledge/compartments/enemies, src/mechanics/calculators/specs-generated, src/mechanics/index, src/mechanics/resource-drops-coin-simulation
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

/** Base coin value of each ordinary enemy type, relative to a basic. */
export const ENEMY_TYPE_BASE_COIN_VALUE = {
  basic: 1,
  fast: 2,
  tank: 4,
  ranged: 2,
} as const

export type OrdinaryEnemyType = keyof typeof ENEMY_TYPE_BASE_COIN_VALUE

export type EnemyTypeCounts = Record<OrdinaryEnemyType, number>

/**
 * Round-average mix measured from `test/playerInfo.dat`, waves 600-4875.
 *
 * Kill counts, not shares — shares are derived, so the two cannot drift apart.
 * Every value is a counter the game keeps; none is a residual. `basic` is
 * `totalEnemiesDestroyedNormalThisRound`.
 */
export const MEASURED_ENEMY_TYPE_KILLS: EnemyTypeCounts = {
  basic: 109691,
  fast: 156256,
  tank: 147353,
  ranged: 138923,
}

/** Fraction of ordinary kills that were each type. */
export function enemyTypeShares(counts: EnemyTypeCounts): Record<OrdinaryEnemyType, number> {
  const total = ordinaryKillTotal(counts)
  if (total <= 0) {
    return { basic: 0, fast: 0, tank: 0, ranged: 0 }
  }
  return {
    basic: counts.basic / total,
    fast: counts.fast / total,
    tank: counts.tank / total,
    ranged: counts.ranged / total,
  }
}

export function ordinaryKillTotal(counts: EnemyTypeCounts): number {
  return counts.basic + counts.fast + counts.tank + counts.ranged
}

/**
 * Average coin value per ordinary kill, relative to a basic.
 *
 * `RESOURCE_DROPS_AVG_ENEMY_COIN_WEIGHT` is this function applied to the
 * measured counts: 2.34, against the 1.15 it superseded.
 */
export function averageEnemyCoinWeight(counts: EnemyTypeCounts): number {
  const total = ordinaryKillTotal(counts)
  if (total <= 0) return 0
  let weighted = 0
  for (const type of Object.keys(ENEMY_TYPE_BASE_COIN_VALUE) as OrdinaryEnemyType[]) {
    weighted += counts[type] * ENEMY_TYPE_BASE_COIN_VALUE[type]
  }
  return weighted / total
}

/** The measured round-average weight, for comparison against an estimate. */
export function measuredAverageEnemyCoinWeight(): number {
  return averageEnemyCoinWeight(MEASURED_ENEMY_TYPE_KILLS)
}
