/**
 * Effective Paths — `UW CD`, the synced cooldown composite on the stone tab.
 *
 * `eEcon Stones!DW5` buys a Cooldown stone level on every unlocked GT / BH / DW
 * that currently sits at the longest cooldown (`CA5`), and prices the step as
 * the sum of those purchases. Hide row `DW2` is
 * `OR(NOT(AZ17), CA5<110)` — only when Keep CD Synced is on and the longest
 * cooldown is still at least 110 seconds.
 *
 * `CA5` itself is the sheet's simple chart form (`300-10*level` / `200-10*level`),
 * not the full econ cooldown with labs and substats — matching
 * `FORMULATEXT('eEcon Stones'!CA5)`.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    UW_CD_MIN_MAX_COOLDOWN_SECONDS, uwCooldownSecondsAt, uwCdMaxCooldownSeconds, isUwCdCandidateVisible, uwCdWeaponsBuyingNext, applyOneUwCdPurchase, applyUwCdPurchases, uwCdStoneCost (+1 more)
 * depends    src/mechanics/effective-paths-edamage-costs, src/mechanics/effective-paths-eecon-compute, src/mechanics/effective-paths-eecon-levels
 * used by    src/mechanics/calculators/specs-generated, src/mechanics/effective-paths-eecon-plan, src/mechanics/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

import type { EffectiveEconomyConfig } from './effective-paths-eecon-compute'
import type { EffectiveEconomyStoneLevels } from './effective-paths-eecon-levels'
import {
  ultimateWeaponMaxLevel,
  ultimateWeaponStatValue,
  ultimateWeaponStoneCost,
} from './effective-paths-edamage-costs'

/** Sheet hide threshold — `CA5<110` drops the candidate. */
export const UW_CD_MIN_MAX_COOLDOWN_SECONDS = 110

type CooldownStoneKey =
  | 'goldenTowerCooldownStone'
  | 'blackHoleCooldownStone'
  | 'deathWaveCooldownStone'

interface UwCdWeapon {
  weapon: string
  key: CooldownStoneKey
  unlocked: (config: EffectiveEconomyConfig) => boolean
}

const UW_CD_WEAPONS: readonly UwCdWeapon[] = [
  {
    weapon: 'Golden Tower',
    key: 'goldenTowerCooldownStone',
    unlocked: c => Boolean(c.weapons.goldenTower?.unlocked),
  },
  {
    weapon: 'Black Hole',
    key: 'blackHoleCooldownStone',
    unlocked: c => Boolean(c.weapons.blackHole?.unlocked),
  },
  {
    weapon: 'Death Wave',
    key: 'deathWaveCooldownStone',
    unlocked: c => Boolean(c.weapons.deathWave?.unlocked),
  },
]

/** Chart cooldown seconds at a stone level — what `CA5` and `GTcdNext` use. */
export function uwCooldownSecondsAt(weapon: string, stoneLevel: number): number {
  const value = ultimateWeaponStatValue(weapon, 'Cooldown', Math.max(0, Math.floor(stoneLevel)))
  return value ?? 0
}

/**
 * `eEcon Stones!CA5` — max of the three weapon chart cooldowns among unlocked.
 */
export function uwCdMaxCooldownSeconds(
  config: EffectiveEconomyConfig,
  stone: Pick<EffectiveEconomyStoneLevels, CooldownStoneKey>,
): number {
  let max = 0
  for (const entry of UW_CD_WEAPONS) {
    if (!entry.unlocked(config)) continue
    max = Math.max(max, uwCooldownSecondsAt(entry.weapon, stone[entry.key]))
  }
  return max
}

/** Whether `DW2` would leave UW CD visible. */
export function isUwCdCandidateVisible(
  config: EffectiveEconomyConfig,
  stone: Pick<EffectiveEconomyStoneLevels, CooldownStoneKey>,
  keepCooldownsSynced: boolean,
): boolean {
  if (!keepCooldownsSynced) return false
  return uwCdMaxCooldownSeconds(config, stone) >= UW_CD_MIN_MAX_COOLDOWN_SECONDS
}

/**
 * Which weapons get +1 on this composite purchase — `GTcdNext` / friends.
 *
 * `IF(CA5 > DVT_UW_STAT(..., level), 0, 1)` → buy when the weapon is still at
 * the shared maximum (or alone).
 */
export function uwCdWeaponsBuyingNext(
  config: EffectiveEconomyConfig,
  stone: Pick<EffectiveEconomyStoneLevels, CooldownStoneKey>,
): readonly UwCdWeapon[] {
  const ca5 = uwCdMaxCooldownSeconds(config, stone)
  if (ca5 <= 0) return []
  return UW_CD_WEAPONS.filter(entry => {
    if (!entry.unlocked(config)) return false
    return ca5 <= uwCooldownSecondsAt(entry.weapon, stone[entry.key])
  })
}

/** Stone levels after one UW CD purchase. */
export function applyOneUwCdPurchase(
  config: EffectiveEconomyConfig,
  stone: EffectiveEconomyStoneLevels,
): EffectiveEconomyStoneLevels {
  const buying = uwCdWeaponsBuyingNext(config, stone)
  if (!buying.length) return stone
  const next = { ...stone }
  for (const entry of buying) next[entry.key] = stone[entry.key] + 1
  return next
}

/** Stone CD levels after `purchases` composite steps from a base. */
export function applyUwCdPurchases(
  config: EffectiveEconomyConfig,
  stone: EffectiveEconomyStoneLevels,
  purchases: number,
): EffectiveEconomyStoneLevels {
  let next = stone
  const count = Math.max(0, Math.floor(purchases))
  for (let i = 0; i < count; i++) next = applyOneUwCdPurchase(config, next)
  return next
}

/**
 * Stones for one UW CD step from the given stone levels.
 *
 * Sum of `DVT_UW_COST` for each weapon buying — `GTCost+BHCost+DWCost`.
 */
export function uwCdStoneCost(
  config: EffectiveEconomyConfig,
  stone: Pick<EffectiveEconomyStoneLevels, CooldownStoneKey>,
): number | null {
  const buying = uwCdWeaponsBuyingNext(config, stone)
  if (!buying.length) return null
  let total = 0
  for (const entry of buying) {
    const cost = ultimateWeaponStoneCost(entry.weapon, 'Cooldown', stone[entry.key] + 1)
    if (cost === null) return null
    total += cost
  }
  return total
}

/**
 * How many further UW CD purchases remain before `CA5 < 110` or nothing prices.
 *
 * Upper-bounded by the sum of remaining chart levels so a path cannot loop.
 */
export function uwCdRemainingPurchases(
  config: EffectiveEconomyConfig,
  stone: EffectiveEconomyStoneLevels,
): number {
  let current = { ...stone }
  let remaining = 0
  const cap = UW_CD_WEAPONS.reduce((sum, entry) => {
    if (!entry.unlocked(config)) return sum
    const max = ultimateWeaponMaxLevel(entry.weapon, 'Cooldown') ?? 0
    return sum + Math.max(0, max - current[entry.key])
  }, 0)

  while (remaining < cap) {
    if (uwCdMaxCooldownSeconds(config, current) < UW_CD_MIN_MAX_COOLDOWN_SECONDS) break
    if (uwCdStoneCost(config, current) === null) break
    current = applyOneUwCdPurchase(config, current)
    remaining++
  }
  return remaining
}
