/**
 * Bot cooldown and duration in seconds, at a given upgrade level.
 *
 * These are formulas rather than lookups, and they earn that: each reproduces every row of
 * `BOT_UPGRADES_DATA` exactly — 16 cooldown levels on all five bots, and every duration level on
 * all four bots that have one. `bots-match-the-catalog.test.ts` asserts it row by row, which is
 * what Rule 9 of the organization contract requires before a formula may stand in for a table.
 *
 * They lived in `internal/game-input-data/bot-dropdown-math.ts`, where a control needed them first
 * — and where one of them was wrong for four years' worth of Thunder Bot levels without anything
 * noticing, because nothing in this package called either function. They were reachable only by a
 * consumer importing `thetowersdk/internal/*`.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    computeBotCooldownSecondsAtLevel, computeBotDurationSecondsAtLevel, computeBotDurationLabBonusSeconds
 * depends    src/mechanics/bots/constants
 * used by    src/mechanics/bots/index, src/mechanics/calculators/specs-generated
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import {
  BOT_COOLDOWN_LAB_CAP,
  BOT_COOLDOWN_LEVEL_COUNT,
  BOT_DURATION_LAB_CAP,
  BOT_DURATION_LEVEL_COUNT,
  FLAME_BOT_COOLDOWN_BASE_SECONDS,
  FLAME_BOT_COOLDOWN_FLOOR_SECONDS,
  FLAME_BOT_COOLDOWN_LAB_FLOOR_SECONDS,
  STANDARD_BOT_COOLDOWN_BASE_SECONDS,
  STANDARD_BOT_COOLDOWN_FLOOR_SECONDS,
  STANDARD_BOT_COOLDOWN_STEP_SECONDS,
  STANDARD_BOT_DURATION_BASE_SECONDS,
  STANDARD_BOT_DURATION_STEP_SECONDS,
  THUNDER_BOT_DURATION_BASE_SECONDS,
  THUNDER_BOT_DURATION_CAP_SECONDS,
  THUNDER_BOT_DURATION_STEP_SECONDS,
} from './constants'

/** Bot key prefixes, as the upgrade keys spell them. */
const FLAME_BOT = 'fb'
const THUNDER_BOT = 'tb'

function wholeLevel(value: number, cap: number): number {
  return Math.max(0, Math.min(cap, Math.floor(Number(value) || 0)))
}

/**
 * Cooldown in seconds between activations.
 *
 * Flame Bot runs its own shorter ladder; the other four share one. The lab reduces the result
 * rather than the base, and both have a floor — a lab that would take Flame Bot below five seconds
 * does not.
 */
export function computeBotCooldownSecondsAtLevel(
  prefix: string,
  level: number,
  labLevel: number,
): number {
  const lab = wholeLevel(labLevel, BOT_COOLDOWN_LAB_CAP)
  const cappedLevel = wholeLevel(level, BOT_COOLDOWN_LEVEL_COUNT - 1)

  if (prefix === FLAME_BOT) {
    const base = Math.max(
      FLAME_BOT_COOLDOWN_FLOOR_SECONDS,
      FLAME_BOT_COOLDOWN_BASE_SECONDS - (cappedLevel * STANDARD_BOT_COOLDOWN_STEP_SECONDS),
    )
    return Math.max(FLAME_BOT_COOLDOWN_LAB_FLOOR_SECONDS, base - lab)
  }

  return Math.max(
    STANDARD_BOT_COOLDOWN_FLOOR_SECONDS,
    STANDARD_BOT_COOLDOWN_BASE_SECONDS - (cappedLevel * STANDARD_BOT_COOLDOWN_STEP_SECONDS) - lab,
  )
}

/**
 * How long an activation lasts, in seconds.
 *
 * Thunder Bot is its own ladder: it starts at 5s and climbs by HALF a second per level to 15s at
 * level 20. This used to read `Math.min(15, 5 + level)` — a whole second per level — which
 * overstated every level above 0, reached the 15s cap at level 10 instead of 20, and reported
 * levels 11 to 20 as a flat band of identical 15s values. It disagreed with the catalog on 19 of
 * its 21 levels.
 *
 * The other four share a ladder that starts at 20s and climbs by half a second, with the duration
 * lab adding half a second per lab level on top.
 */
export function computeBotDurationSecondsAtLevel(
  prefix: string,
  level: number,
  labLevel: number,
): number {
  const rawLevel = Math.max(0, Math.floor(Number(level) || 0))

  if (prefix === THUNDER_BOT) {
    return Math.min(
      THUNDER_BOT_DURATION_CAP_SECONDS,
      Math.max(0, THUNDER_BOT_DURATION_BASE_SECONDS + (rawLevel * THUNDER_BOT_DURATION_STEP_SECONDS)),
    )
  }

  const lab = wholeLevel(labLevel, BOT_DURATION_LAB_CAP)
  const cappedLevel = Math.min(BOT_DURATION_LEVEL_COUNT - 1, rawLevel)
  return Math.max(
    0,
    STANDARD_BOT_DURATION_BASE_SECONDS
    + (cappedLevel * STANDARD_BOT_DURATION_STEP_SECONDS)
    + (lab * STANDARD_BOT_DURATION_STEP_SECONDS),
  )
}

/** Seconds the duration lab adds, independent of the bot's own level. */
export function computeBotDurationLabBonusSeconds(labLevel: number): number {
  return Math.max(0, Math.floor(Number(labLevel) || 0)) * STANDARD_BOT_DURATION_STEP_SECONDS
}
