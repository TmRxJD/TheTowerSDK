/**
 * What the Bot Bot's amplification and a bot's own uptime do to that bot's headline stat.
 *
 * These take stat values as the catalog writes them — a number with its unit, `"12s"` — and hand
 * one back the same way, so a planner can read a row, amplify it and show it without converting
 * twice. They were in `data/bots` beside the table they read, which made a catalog compute.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    estimateBotBotAmplificationMultiplier, estimateBotUptimeFraction, estimateAmplifiedBotMetricValue, estimateEffectiveAmplifiedBotMetricValue
 * depends    src/data/bots/data, src/mechanics/bots/hit-multiplier, src/mechanics/bots/overlap, src/mechanics/uptime/compute
 * used by    src/calculators/specs.generated, src/mechanics/bots/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { formatBotMetricValue, parseBotMetricUnit, parseBotMetricValue } from '../../data/bots/data'
import { computeUptimeRatio } from '../uptime/compute'
import { botBotBoostedMultiplier } from './hit-multiplier'
import { botBotAmplificationApplicationFraction } from './overlap'

/**
 * The average factor the Bot Bot applies to another bot's headline stat.
 *
 * `applicationFraction` is the share of enemy-instants inside the Bot Bot's radius while it
 * is up — see `botBotAmplificationApplicationFraction`. The Bot Bot's own `Maximum Power`
 * Bot+ value is deliberately NOT an argument: the game's three amplified effects read the
 * base `Bonus` stat and nothing else, and folding Bot+ in here inflated every one of them.
 */
export function estimateBotBotAmplificationMultiplier(botBotBonusValue: string, applicationFraction: number): number {
  const botBotBonus = Math.max(1, parseBotMetricValue(botBotBonusValue) || 1)
  return botBotBoostedMultiplier(botBotBonus, applicationFraction)
}

/**
 * Duration over cooldown.
 *
 * Flame has no Duration stat — the game returns a fixed 3 seconds for it — so pass
 * `FLAME_BOT_FIXED_DURATION_SECONDS` rather than looking a duration up for that bot.
 */
export function estimateBotUptimeFraction(durationValue: string, cooldownValue: string): number {
  return computeUptimeRatio(parseBotMetricValue(durationValue), parseBotMetricValue(cooldownValue))
}

export function estimateAmplifiedBotMetricValue(baseMetricValue: string, botBotBonusValue: string, applicationFraction: number): string {
  const baseMetric = parseBotMetricValue(baseMetricValue)
  if (!Number.isFinite(baseMetric)) return baseMetricValue
  const multiplier = estimateBotBotAmplificationMultiplier(botBotBonusValue, applicationFraction)
  const unit = parseBotMetricUnit(baseMetricValue)
  return formatBotMetricValue(baseMetric * multiplier, unit)
}

/**
 * A bot's stat averaged over its own uptime, with the Bot Bot's amplification averaged over
 * the fraction of the time IT applies.
 *
 * The two uptimes are separate on purpose: the amplified bot has to be up for its stat to
 * matter at all, and the Bot Bot has to be up for the amplification to land.
 */
export function estimateEffectiveAmplifiedBotMetricValue(
  baseMetricValue: string,
  botBotBonusValue: string,
  spatialOverlapFraction: number,
  botUptimeFraction: number,
  botBotUptimeFraction: number,
): string {
  const baseMetric = parseBotMetricValue(baseMetricValue)
  if (!Number.isFinite(baseMetric)) return baseMetricValue
  const targetUptime = Math.max(0, Math.min(1, botUptimeFraction))
  const applied = botBotAmplificationApplicationFraction({
    botBotBonus: Math.max(1, parseBotMetricValue(botBotBonusValue) || 1),
    temporalOverlapFraction: botBotUptimeFraction,
    spatialOverlapFraction,
  })
  const effectiveMultiplier = estimateBotBotAmplificationMultiplier(botBotBonusValue, applied)
  const unit = parseBotMetricUnit(baseMetricValue)
  return formatBotMetricValue(baseMetric * targetUptime * effectiveMultiplier, unit)
}
