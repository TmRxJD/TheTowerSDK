/**
 * `EP_UW_HEATUP` — what repeatedly hitting one target is worth.
 *
 * Missile Amplifier makes each successive hit on the same enemy stronger, so
 * the average hit is worth the midpoint of the ramp. A non-numeric hit count
 * means no ramp at all, and the sheet's `IFERROR` answers 1.
 */
export function ultimateWeaponHeatUp(
  missileAmplifier: number,
  hitsOnSameTarget: number | null | undefined,
): number {
  if (typeof hitsOnSameTarget !== 'number' || !Number.isFinite(hitsOnSameTarget)) return 1
  const value = missileAmplifier * (hitsOnSameTarget - 1) / 2 + 1
  return Number.isFinite(value) ? value : 1
}

export interface UltimateWeaponDamageInput {
  /** Death Wave. */
  deathWave: number
  /** Chain Lightning. */
  chainLightning: number
  /** Smart Missiles. */
  smartMissiles: number
  /** Spotlight's own damage, which is added *outside* the Spotlight bonus. */
  spotlightDamage: number
  /** Spotlight's coverage bonus, applied to every other weapon. */
  spotlightBonus: number
  /** Poison Swamp. */
  poisonSwamp: number
  /** Inner Land Mines. */
  innerLandMines: number
  /** The Core module's ultimate weapon damage bonus, and dissonance. */
  damageBoost: number
  /** Super Tower's ultimate weapon share — see the note below. */
  superTowerUltimateMastery: number
  /** The Ultimate Crit card. */
  ultimateCritCard: number
}

/**
 * `EP_UW_TOTAL_DAMAGE` — the ultimate weapons' contribution.
 *
 * ```text
 * boost × ((DW + SM + CL + PS + ILM) × SL × STmastery + SLM) × critCard × STmastery
 * ```
 *
 * Two things about that shape are deliberate and easy to "tidy" into being
 * wrong. Spotlight's own damage is added *after* the Spotlight bonus, because
 * a weapon does not light itself. And `superTowerUltimateMastery` genuinely
 * appears **twice** — once inside the bracket and once outside — so it is
 * squared for every weapon except Spotlight, which takes it once.
 */
export function ultimateWeaponTotalDamage(input: UltimateWeaponDamageInput): number {
  const lit = input.deathWave
    + input.smartMissiles
    + input.chainLightning
    + input.poisonSwamp
    + input.innerLandMines

  return input.damageBoost
    * (lit * input.spotlightBonus * input.superTowerUltimateMastery + input.spotlightDamage)
    * input.ultimateCritCard
    * input.superTowerUltimateMastery
}
