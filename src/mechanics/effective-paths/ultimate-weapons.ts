// ---------------------------------------------------------------------------
// Spotlight
// ---------------------------------------------------------------------------

/** `STAT_UW_SL_FINAL_ANGLE` — how wide each spotlight is, in degrees. */
export const spotlightAngle = plain

/**
 * `STAT_UW_SL_FINAL_LR` — what Light Range is worth.
 *
 * Spotlight's damage bonus is boosted by a share of your damage per meter.
 * Without the upgrade the sheet leaves the term at 1 rather than at zero.
 */
export function spotlightLightRange(
  lightRange: number | null | undefined,
  damagePerMeter: number,
): number {
  const has = typeof lightRange === 'number' && Number.isFinite(lightRange)
  return 1 + (has ? lightRange * (damagePerMeter - 1) : 0)
}

/**
 * `STAT_UW_SL_FINAL_DMG` — Spotlight's own damage; the perk adds half again.
 *
 * The sheet passes two vaults: `vault_uw` (`BM39`, shared UW Damage) and
 * `vault` (`BM33`, Spotlight's own row). Both are fractions here.
 */
export function spotlightDamage(input: {
  base: number
  substat: number
  lightRange: number
  relicPct: number
  /** `BM39` / keys UW Damage vault, as a fraction. */
  vaultPct: number
  /** `BM33` Spotlight-row vault, as a fraction. */
  weaponVaultPct?: number
  hasPerk: boolean
}): number {
  return (input.base + input.substat)
    * (1 + input.relicPct)
    * (1 + input.vaultPct)
    * (1 + (input.weaponVaultPct ?? 0))
    * (input.hasPerk ? 1.5 : 1)
    * input.lightRange
}

