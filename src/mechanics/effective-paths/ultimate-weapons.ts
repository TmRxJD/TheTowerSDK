/**
 * Effective Paths — the `STAT_UW_*` and `EP_UW_*` layer.
 *
 * The seven ultimate weapons the damage path cares about, and the two helpers
 * that combine them. Each weapon's stats are the same shape — a base from its
 * stone upgrades plus a module substat, sometimes floored, sometimes doubled by
 * a perk — so most of these are one line, and the interest is in which ones are
 * floored and which are not.
 *
 * `SL` and `SLM` are both Spotlight and are not the same thing: `SLM` is
 * Spotlight's own damage as a weapon, and `SL` is the coverage multiplier
 * Spotlight applies to the *other* weapons. They enter
 * {@link ultimateWeaponTotalDamage} in different places.
 *
 * Credit for the original formulas belongs to the Effective Paths maintainers —
 * see `effective-paths-credits.ts`.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    chainLightningChance, chainLightningDamage, chainLightningQuantity, deathWaveDamage, deathWaveCooldown, deathWaveCooldownWithMvn, deathWaveQuantity, smartMissileDamage (+11 more)
 * depends    —
 * used by    src/mechanics/calculators/specs-generated, src/mechanics/effective-paths/edamage-compute, src/mechanics/effective-paths/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

/** A stat that is a base plus its substat, with nothing else to it. */
const plain = (base: number, substat: number): number => base + substat

// ---------------------------------------------------------------------------
// Chain Lightning
// ---------------------------------------------------------------------------

/** `STAT_UW_CL_FINAL_CH` — Chain Lightning's proc chance. */
export const chainLightningChance = plain

/**
 * `STAT_UW_CL_FINAL_DMG` — Chain Lightning's damage; the perk doubles it.
 *
 * `vaultPct` is `BM31` as a fraction (`BN31 = BM31*5%`).
 */
export function chainLightningDamage(
  base: number,
  substat: number,
  hasPerk: boolean,
  vaultPct = 0,
): number {
  return (base + substat) * (hasPerk ? 2 : 1) * (1 + vaultPct)
}

/**
 * `STAT_UW_CL_FINAL_QTY` — how many bolts Chain Lightning throws.
 *
 * Floored, because a fraction of a bolt does not exist — and then Death Chain
 * adds six tenths on top, which is *not* floored. The sheet means that: the
 * remainder is a chance at another bolt rather than a whole one.
 */
export function chainLightningQuantity(
  base: number,
  substat: number,
  hasDeathChain: boolean,
): number {
  return Math.floor(base + substat) + (hasDeathChain ? 0.6 : 0)
}

// ---------------------------------------------------------------------------
// Death Wave
// ---------------------------------------------------------------------------

/** `STAT_UW_DW_FINAL_DMG` — Death Wave's damage (`BM30` vault as a fraction). */
export function deathWaveDamage(base: number, substat: number, vaultPct = 0): number {
  return (base + substat) * (1 + vaultPct)
}

/** `STAT_UW_DW_FINAL_CD` — Death Wave's cooldown, after Golden Combo. */
export function deathWaveCooldown(
  base: number,
  substat: number,
  goldenComboReduction: number,
): number {
  return (base + substat) * goldenComboReduction
}

/**
 * `STAT_UW_DW_FINAL_CD_MVN` — the same, unless the player runs Max Value Nuke.
 *
 * With MVN the cooldown is whatever that strategy dictates, so a number given
 * there wins outright over the computed one.
 */
export function deathWaveCooldownWithMvn(
  base: number,
  substat: number,
  goldenComboReduction: number,
  mvnCooldown: number | null | undefined,
): number {
  return typeof mvnCooldown === 'number' && Number.isFinite(mvnCooldown)
    ? mvnCooldown
    : deathWaveCooldown(base, substat, goldenComboReduction)
}

/** `STAT_UW_DW_FINAL_QTY` — Death Wave count, floored, with a perk worth one. */
export function deathWaveQuantity(base: number, substat: number, hasPerk: boolean): number {
  return Math.floor(base + substat + (hasPerk ? 1 : 0))
}

