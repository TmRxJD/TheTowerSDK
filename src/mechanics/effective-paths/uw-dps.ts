/**
 * Effective Paths — what each ultimate weapon contributes per second.
 *
 * `effective-paths-ultimate-weapons.ts` resolves a weapon's *stats*; this turns
 * those stats into damage per second, which is what the `UWs` factor sums.
 *
 * Six of the seven are a plain damage ÷ cooldown. Chain Lightning is not: it
 * procs per bullet, so its rate is a function of the tower's own fire rate and
 * of the game speed, and it is the only weapon whose output moves when a
 * bullet stat does.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    deathWaveDps, chainLightningDps, amplifiedChainLightningDps, smartMissilesDps, spotlightMissilesDps, poisonSwampDps, innerLandMinesDps, spotlightFinalBonus
 * depends    src/mechanics/effective-paths/damage-stats, src/mechanics/effective-paths/firing
 * used by    src/calculators/specs.generated, src/mechanics/effective-paths/edamage-compute, src/mechanics/effective-paths/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

import { areaOfEffectCardBoost } from './damage-stats'
import { realGameSpeed } from './firing'

/** The Area of Effect card, which every cooldown-based weapon takes. */
interface AreaOfEffectCard {
  hasAreaOfEffectCard: boolean
  areaOfEffectCardLevel: number
}

/**
 * `EP_DW_DPS` — the Effective Paths aggregate Death Wave estimate.
 * This sheet scenario estimate is not an event model of the persistent damage
 * pool. Quantity is Effect Wave count, not a number of pool additions per activation.
 *
 * The `5 + 1.5 × amp` term is the number of enemies a wave is assumed to pass
 * through, not a damage multiplier, which is why the Damage Amplifier lab pays
 * off far better than its name suggests.
 */
export function deathWaveDps(input: {
  unlocked: boolean
  damage: number
  quantity: number
  cooldownSeconds: number
  damageAmplifierLabLevel: number
}): number {
  if (!input.unlocked) return 0
  return (input.damage / input.cooldownSeconds)
    * input.quantity
    * (5 + input.damageAmplifierLabLevel * 1.5)
}

/**
 * `EP_CL_DPS` — Chain Lightning.
 *
 * Without Light Speed Shots, each bullet contributes its proc chance directly.
 * With the lab, the sheet groups bullets by the configured frame rate.
 *
 * This is why Chain Lightning appears on the *bullet* stats' payoff: raising
 * attack speed raises it, and no other weapon behaves that way.
 */
export function chainLightningDps(input: {
  damage: number
  quantity: number
  /** Proc chance a bullet, as a fraction. */
  chance: number
  attackSpeed: number
  rapidFire: number
  multishot: number
  /** Bounce shot *without* Astral Deliverance — the sheet's `DR`, not `DQ`. */
  bounce: number
  displayedGameSpeed: number
  framesPerSecond: number
  lightSpeedShots: boolean
}): number {
  if (!input.lightSpeedShots) {
    return input.damage * input.quantity * input.multishot * input.bounce
      * input.chance * input.attackSpeed * input.rapidFire
  }
  const speed = realGameSpeed(input.displayedGameSpeed)
  const fireRate = input.attackSpeed * input.rapidFire
  const bulletsPerFrame = fireRate * speed / input.framesPerSecond
  const procChancePerFrame = 1 - Math.pow(1 - input.chance, bulletsPerFrame)
  const procsPerSecond = input.framesPerSecond / speed * procChancePerFrame

  return input.damage
    * input.quantity
    * procsPerSecond
    * input.multishot
    * input.bounce
    * bulletsPerFrame
}

/** `EP_CL_DPS_AMP` — exact coverage-weighted Chain Lightning with Amplify Bot. */
export function amplifiedChainLightningDps(input: Parameters<typeof chainLightningDps>[0] & {
  coverage: number
  amplificationBonus: number
  echoHits: number
}): number {
  return (1 - input.coverage) * chainLightningDps(input)
    + input.coverage * input.amplificationBonus
      * chainLightningDps({ ...input, attackSpeed: input.attackSpeed * input.echoHits })
}

/**
 * `EP_SM_DPS` — Smart Missiles.
 *
 * Cover Fire is added *after* the cooldown divide because it is already a rate.
 */
export function smartMissilesDps(input: AreaOfEffectCard & {
  damage: number
  quantity: number
  cooldownSeconds: number
  coverFire: number
  heatUp: number
  areaOfEffect: number
}): number {
  return input.heatUp
    * input.areaOfEffect
    * (input.damage * input.quantity / input.cooldownSeconds + input.coverFire)
    * areaOfEffectCardBoost(input.hasAreaOfEffectCard, input.areaOfEffectCardLevel)
}

/**
 * `EP_SLM_DPS` — the Spotlight Missiles a lit Smart Missile fires.
 *
 * Unconditional: the caller gates it on both Spotlight and Smart Missiles
 * being unlocked, because neither alone produces any.
 */
export function spotlightMissilesDps(input: AreaOfEffectCard & {
  smartMissileDamage: number
  spotlightDamage: number
  /** The sheet passes `20 - level`, so the lab shortens it. */
  cooldownSeconds: number
  heatUp: number
  areaOfEffect: number
}): number {
  return input.heatUp
    * input.areaOfEffect
    * input.smartMissileDamage
    * input.spotlightDamage
    / input.cooldownSeconds
    * areaOfEffectCardBoost(input.hasAreaOfEffectCard, input.areaOfEffectCardLevel)
}

/** `EP_PS_DPS` — Poison Swamp. */
export function poisonSwampDps(input: AreaOfEffectCard & {
  unlocked: boolean
  damage: number
  durationSeconds: number
  cooldownSeconds: number
  deathCreep: number
  rend: number
}): number {
  if (!input.unlocked) return 0
  return input.damage
    * (input.durationSeconds / input.cooldownSeconds)
    * input.deathCreep
    * input.rend
    * areaOfEffectCardBoost(input.hasAreaOfEffectCard, input.areaOfEffectCardLevel)
}

/**
 * `EP_ILM_DPS` — Inner Land Mines.
 *
 * `detonationsPerSecond` already folds in Space Displacer's extra mines, which
 * is why it is a rate rather than a quantity and a cooldown.
 */
export function innerLandMinesDps(input: AreaOfEffectCard & {
  unlocked: boolean
  damage: number
  detonationsPerSecond: number
  /** The Chrono Jump lab, five per level, already multiplied by the `+` heat-up. */
  chronoJump: number
  chargedMines: number
  areaOfEffect: number
}): number {
  if (!input.unlocked) return 0
  return input.damage
    * input.detonationsPerSecond
    * (1 + input.chronoJump * input.chargedMines)
    * input.areaOfEffect
    * areaOfEffectCardBoost(input.hasAreaOfEffectCard, input.areaOfEffectCardLevel)
}

/**
 * `EP_SL_FINAL_BONUS` — Spotlight's bonus, weighted by how much it lights.
 *
 * A bonus that only reaches part of the field is worth only that part of it,
 * so a wide-angle Spotlight is worth more than its damage stat implies.
 */
export function spotlightFinalBonus(coverage: number, bonus: number): number {
  return 1 + (bonus - 1) * coverage
}
