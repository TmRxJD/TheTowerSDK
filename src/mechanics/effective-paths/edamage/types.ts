export interface EffectiveDamageShadow {
  /**
   * Spotlight's ultimate-weapon vault percentage, held at the base row's value.
   *
   * Every `eDamage Keys` candidate column ends on the BASE row's Spotlight:
   * `SL, $CY5`. `CY5` reads `$BM$39` — the ultimate weapon vault — so on the
   * one candidate that raises `BM39`, the sheet prices the bump through
   * `UWAdditionalDMG` and leaves Spotlight where it was.
   *
   * The port recomputes the whole composition, so it moved Spotlight too and
   * valued UW Damage at roughly twenty times the sheet's figure, ranking it
   * first where the sheet ranks it seventeenth. Every later step shifted with
   * it.
   *
   * Set for the whole keys band, not just UW Damage: all eleven columns reuse
   * `$CY5`, and for the other ten the frozen value is the recomputed one
   * anyway, so it is exact there and does nothing.
   */
  spotlightVaultPct?: number
  /** `CY5` held whole at the base row — see the use site. */
  frozenSpotlightBonus?: number
  /** `eDamage Keys!CU5` drops the assist substat — see the use site. */
  maxRendPrimarySubstatOnly?: boolean

  /**
   * COIN band only — Max Rend caps its assist substat with the wrong level.
   *
   * Every other column on `eDamage Coins` takes the cannon assist cap from
   * `CH5`, "Assist Module Substats - Cannon" (`=BC45`) — nine of them, from
   * crit through Range Mastery. Max Rend takes it from `CK5`, "Assist Module
   * BONUS - Cannon" (`=BC49`):
   *
   *     eDamage!DZ5        EPG_ASSIST_SUB_CAP($AN$4, $BL$42, CO5)   <- Substat
   *     eDamage Coins!DM5  EPG_ASSIST_SUB_CAP($AN$4, $BL$42, CK5)   <- Bonus
   *
   * Two cells carry it, `DM5` and the `Rend Armor Mult +` candidate column
   * `EP5`, and they are the only two on the tab that do. On `account-19` the
   * two levels are 26 and 2, so the cap is 0.27 against 0.03 and the tab's
   * `Max Rend Armor Multiplier` reads 15.100489250 where the port rebuilt
   * 14.982343250 — 0.78% low, and the ONLY factor of seven in `OtherMults`
   * that disagreed at all.
   *
   * Whether the sheet means it or fat-fingered a column, the port reproduces
   * it, the same as every other entry here.
   */
  maxRendAssistCapFromBonusLevel?: boolean

  /**
   * The ILM cooldown taken from the DISPLAY cell, which counts its substat
   * twice.
   *
   * `eDamage!EL5`, the base column, builds the cooldown from the raw weapon
   * value: `IlmCD, $BK$37 + $AM$41 + SubstatAssistCapCore*$AO$41`. Two
   * CANDIDATE columns build it from `$AY$10` instead — `FM5`
   * (Inner Land Mine - Chrono Jump) and `FS5` (Assist Module Substats - Core)
   * — and `AY10` is
   *
   *     =IF(BH37, MAX(37, BK37 + AM41 + AR41), )     AR41 = AO41 * $AO$24
   *
   * so it already carries the substat that the candidate then adds again:
   * 247.013 raw, 247.3254 from the display cell, and the candidate's cooldown
   * ends up `BK37 + 2*AM41 + cap*AO41`.
   *
   * A longer cooldown is fewer detonations, so this makes the sheet price
   * Chrono Jump slightly HIGH against its peers — 2.7e-5, one part in 37,000,
   * far too small to see without a peer comparison and far too structured to
   * be rounding.
   *
   * `AR41` is the assist substat at the core module's FULL efficiency
   * (`AO41 * $AO$24`), not the capped share the base column uses. It is 0 on
   * every captured account because that module carries no assist, but it is
   * modelled rather than assumed.
   */
  innerLandMineCooldownFromDisplayCell?: boolean

  /**
   * Optional UW DPS overrides (stone rebuild / probes).
   *
   * Pre-v5.10 the keys planner forced lab/stone borrows here because
   * `eDamage Keys` cross-referenced other tabs. v5.10+ Keys!DF5:DN5 compute
   * those weapons locally — the keys pathShadow no longer sets this field.
   * Kept for stone / ad-hoc shadows that still need a forced weapon value.
   */
  ultimateWeaponOverrides?: {
    deathWave?: number
    chainLightning?: number
    smartMissiles?: number
    spotlightMissiles?: number
    innerLandMines?: number
    poisonSwamp?: number
    superTowerUltimateMastery?: number
  }
  /**
   * Percentage points added to crit chance outside the card gate.
   *
   * `eDamage!EV5`, the Critical Chance Mastery shadow, writes `CC, DJ5 + 1%`
   * flat. The base column reaches crit chance through `EPD_CRIT_CHANCE`, whose
   * mastery term is nested inside `IF(has_card, …)` with
   * `has_card = AND($AY$39, $AY$47)`. So on an account with the cards master
   * off, the sheet's estimate of a mastery level credits a percentage point its
   * own base column refuses to apply — and then the purchase delivers nothing,
   * because the next row is computed by the base column again.
   *
   * The port reproduces that rather than correcting it: matching the sheet is
   * the job. Measured on `account-26` step 34 — sheet `1.83674216e-2`, port
   * `1.28635275e-2` before this, a ratio of 1.4278.
   */
  flatCriticalChanceBonus?: number
  /**
   * Super crit chance added while a candidate is priced.
   *
   * `eDamage Keys!DL5`, the Critical Chance candidate, bumps TWO inputs:
   *
   *   CC, CF5+1%,   ...   SCC, CH5+1%,
   *
   * where the Super Crit Chance candidate one column over bumps only
   * `SCC, CH5 + 2%`. Reproduced rather than judged: it is what the column
   * computes, and the port ranked Critical Chance below the sheet on four of
   * the five real accounts without it.
   */
  flatSuperCritChanceBonus?: number

  /**
   * The Spotlight Missiles cooldown to use while PRICING that lab.
   *
   * The base column `eDamage!EH5` reads the lab properly, `20 - CH5`. Its
   * shadow `FI5` passes the literal `2` — which is `20 - 18`, the cooldown at
   * the lab's cap.
   *
   * Unlike the other two fields here, this is NOT the sheet disagreeing with
   * itself. Its ROI column is the only one of the 34 that divides by the cost
   * of every remaining level rather than the next one:
   *
   *     GO5 = (FI5/$ES5-1) / SUM(ARRAYFORMULA(LABDURATION_SINGLE_ADJUSTED(
   *             $GO$4, SEQUENCE(18-CH5+1, 1, CH5+1))))
   *
   * So the column asks "what does FINISHING this lab buy, per day spent
   * finishing it" — value at the cap over cost to the cap — and the two halves
   * are consistent. The lab's whole effect is the cooldown, and a single level
   * of it is not a meaningful unit.
   *
   * Reading the shadow alone made it look like a bug and priced one level at
   * the value of the entire run to cap: parity went 96/100 to 89/100, with
   * failures appearing in BOTH directions, which is what a broken baseline
   * looks like rather than a mis-valued upgrade. See `costOf`, which owns the
   * matching half — the two must move together or neither is right.
   */
  spotlightMissilesCooldownSeconds?: number

  /**
   * Diagnostic slow without the 90% cap, used to find the first capped level.
   * Historical sheet candidates were uncapped; current v5.11.01.03 caps them.
   * The planner does not use this override to value candidates. Explicit
   * diagnostic calls can still reach a zero denominator at 100% reduction.
   */
  chronoSlowUnclamped?: boolean

  /**
   * Chrono slow held at the path-start row — sheet \ES\ on lab shadows /
   * \ET5\. Lab ROI columns multiply by absolute row-5 slow for the whole
   * fill-down; stone uses relative \EE5\ and must not freeze. Absent,
   * composition uses the recomputed slow (standalone calls).
   */
  frozenSlow?: number

  /**
   * Project Funding as it stands at the START of the path — the sheet's `$DH$5`.
   *
   * `eDamage!DA5` opens with tower damage divided by absolute `$DH$5` (PF).
   * Row 5's PF is held for the fill-down while each shadow multiplies its own
   * PF back in. Under Util Disso PF moves with Starting Cash — that lab's
   * whole benefit lives in the gap between the fixed divisor and the moving
   * multiplier. Compute both sides with one value and Starting Cash cancels
   * to a gain of zero (never appears in a path).
   *
   * Absent, the row divides by its own — which is what row 5 itself does.
   */
  projectFundingBaseline?: number

  /**
   * Gate the CANNON substat cap on the CORE module's assist flag.
   *
   * `eDamage Stone!FH5` — the shadow that prices Assist Module Substats -
   * Cannon — opens:
   *
   *     SubstatAssistCap,     EPG_ASSIST_SUB_CAP($AN$23, CN5+1, $BC$45)
   *     SubstatAssistCapCore, EPG_ASSIST_SUB_CAP($AN$23, CQ5,   $BC$48)
   *
   * `CN5` is the cannon stone ladder, so the first is the cannon cap — built
   * with `$AN$23`, which is the **Core** module's assist flag. The sheet does
   * use all three flags elsewhere (`$AN$4` cannon, `$AN$23` core, `$AN$47`
   * armor, 88 calls between them), so this is that column and not a convention.
   *
   * Verified by experiment on the working copy rather than inferred: flipping
   * `AN23` alone, with nothing else touched, moves the priced gain from
   * **-7.099%** to **+2.442%**. Negative is the whole point — the sheet offers
   * this upgrade (its own hide flag is `NOT(AN4)`, and `AN4` is true) and then
   * prices it below doing nothing, so it is never taken.
   *
   * The port gave each module its own flag, scored a real gain, and opened the
   * stone path with it on all ten accounts of the first sweep.
   */
  cannonAssistCapUsesCoreFlag?: boolean

  /**
   * Resolve every ultimate-weapon stat from its stone LEVEL, not the observed
   * value. The stone path only.
   *
   * The two tabs do not share a model, and this is the difference:
   *
   *     eDamage!EH5       STAT_UW_SL_FINAL_DMG($BI$33, ...)
   *     eDamage Stone!EE5 ... DVT_UW_STAT("Spotlight", "Multiplier", BY5) ...
   *
   * The planner tab takes the player's stat as OBSERVED — `BI`, `BJ`, `BK` are
   * what the save reports. The stone tab rebuilds each stat from the level
   * column it is about to increment, because that is the thing the path buys.
   *
   * Mixing the two is worse than either. Deriving only the bumped candidate,
   * while the baseline kept the observed value, priced a level-1 stat against a
   * fully-upgraded weapon and produced a NEGATIVE gain: `ILM Damage` was the
   * sheet's first pick on `account-3` at `4.21e-4` and the port would not take
   * it at all in six steps.
   *
   * So it is all or nothing, per path. The four other variants do not buy
   * stones and keep the observed values.
   */
  weaponStatsFromStoneLevels?: boolean

  /**
   * `eDamage Stone!EU5` / `EV5` — the SL Angle and SL Quantity candidates, which
   * rebuild Super Tower inline instead of calling the function the base column
   * calls, and get a different number out of it.
   *
   * The base column `DB5` is
   *
   *     EPD_SUPERTOWER_BONUS(RIGHT($AU$52, 1), $BC$37)
   *
   * whose bonus is `card × (1 + 3% × lab)`. The two candidate columns write
   *
   *     STB, $AV$52 * $BF$37
   *
   * where `$AV$52` is that same finished bonus and `$BF$37` is the lab factor
   * again — so the Super Tower lab is applied **twice**. On `account-9`, whose
   * card is level 5 and whose lab is 29, `$AV$52` is 7.667 and `$BF$37` is 1.87:
   * the base column gives 3.2223 and the candidate 5.4458, a flat **1.6900**
   * on the bullet half of those two candidates and nothing else.
   *
   * That factor was recorded as an unexplained "1.69x reconstruction" before it
   * was read; it is not a reconstruction, it is a double-count.
   *
   * Coverage is why only these two candidates carry it: they are the only ones
   * that move `SLC`, so they are the only ones that re-derive Super Tower at
   * all. Everything else reads `DB5` and inherits the base column's answer.
   *
   * The inline version also differs in two ways this sweep does NOT exercise,
   * transcribed here rather than guessed at: its mastery term is `0.35 × STB`
   * where the base column's is `1 + 0.35 × (STB - 1)`, and its cooldown reads
   * the mastery LAB alone where the base column adds the coin band's levels.
   * Every account in the sweep has Super Tower Mastery switched off, which
   * makes both branches unreachable and both claims unverified.
   */
  spotlightCandidateSuperTowerInline?: boolean
}

