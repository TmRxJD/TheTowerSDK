export interface EffectiveEconomyPlanOptions {
  config: EffectiveEconomyConfig
  levels: EffectiveEconomyLevels
  variant: EffectiveEconomyPlanVariant
  steps?: number
  maxLevels?: Readonly<Record<string, number>>
  targetLevels?: Readonly<Record<string, number>>
  excludeIds?: readonly string[]
  /**
   * Why a given `excludeIds` entry was left out, by id.
   *
   * `excludeIds` is one flat set fed from several places -- a lab the account
   * has not unlocked, and the sheet's display toggles -- and the reason it was
   * reported with was hard-coded to "not unlocked yet" for all of them. So
   * turning on "Hide UW Cooldown" told a player `DW Cooldown - not unlocked
   * yet` about a stat they had MAXED, which is a false statement about their
   * own account and sends them to the wrong screen to fix it.
   *
   * Callers that know the cause supply it here; anything unlabelled keeps the
   * old wording.
   */
  excludeReasons?: Readonly<Record<string, string>>
  /**
   * Every candidate the greedy loop prices, at every step — so a parity test
   * can compare against the sheet's `DV5:ES5` band candidate by candidate
   * rather than only noticing that step N differs.
   */
  onCandidateRoi?: (entry: {
    step: number
    id: string
    name: string
    nextLevel: number
    roi: number
    gain: number
    price: number
  }) => void
  /**
   * Whether an upgrade is on the board AT THIS STEP.
   *
   * The sheet re-evaluates each candidate column's gate on every ROW, so an
   * upgrade can be offered at step 1 and withdrawn later. `excludeIds` is the
   * right tool for one the currency cannot buy at all; this is for the ones
   * that come and go. See `PathPlanOptions.available`.
   */
  available?: (step: number, id: string) => boolean
  labModifiers?: LabCostModifiers
  moduleDiscountPercent?: number
  enhancementDiscounts?: WorkshopEnhancementDiscounts
  /**
   * `eEcon!AZ17` — "Keep GT|BH|DW CD Synced".
   *
   * Hides the three individual cooldown candidates (`DO2` / `DR2` / `DT2`) and
   * reveals `UW CD` (`DW2`) while the longest chart cooldown is still ≥ 110s.
   * The composite is planned through {@link applyUwCdPurchases}.
   */
  keepCooldownsSynced?: boolean
  /**
   * `eEcon!O3` — count research days only, rather than days plus farm time.
   *
   * The tab's cost mode, spelled `DO` against `D+FT` on the sheet, and read by
   * the hide rows of the four candidates that cost coins and no research time:
   * `NOT(O$3<>"DO")` drops all four when it is `DO`.
   *
   * Off is `D+FT`, where every candidate also carries the time to farm its
   * coins — see {@link costOf}. That is what the sheet ships, so an absent
   * value behaves as `D+FT` does.
   */
  daysOnly?: boolean
  /**
   * `IDS_PS_PLAYERDATA("Coin / Hour")` — coins the player farms in an hour.
   *
   * Turns a coin cost into days, at `cost / (rate * 23)`. Only read when
   * {@link daysOnly} is off, and defaults to
   * {@link SHEET_DEFAULT_COINS_PER_HOUR}, which is the sheet's own default.
   */
  coinsPerHour?: number
  /**
   * Whether the Workshop Enhancements lab is bought — `'Master Sheet'!$F$5`.
   * The coin path buys two enhancements and neither exists without it.
   */
  workshopEnhancementsUnlocked?: boolean
  /**
   * Workshop enhancement levels, keyed by display name or `WSP_*`
   * code. Used for `eEcon!EO2` / `EP2` — Coin Bonus and Free Upgrades stay
   * hidden until Utility enhancement spend clears their thresholds (see
   * {@link UTILITY_ENHANCEMENT_SPEND_UNLOCKS}).
   */
  enhancementLevels?: Readonly<Record<string, number>>
}

