/**
 * Effective Paths — what a stone upgrade costs.
 *
 * The stone path spends stones on assist-module capacity rather than coins and
 * research time on labs. Its cost curve is far simpler than the lab tables: the
 * sheet writes it inline as `12 + (level + 1) × 3`, so the price of a level
 * rises by three stones each time and nothing is looked up.
 *
 * Three upgrades are bought this way, and only three — the stone path's grid
 * has exactly three candidate columns:
 *
 * - **Assist Module Substats — Armor**, which raises the assist substat
 *   capacity that defense absolute, defense percent and wall health all read;
 * - **Assist Module Substats — Generator**, the same for max recovery;
 * - **Assist Module Bonus — Armor**, which raises assist *bonus* capacity, used
 *   only by armor.
 *
 * Card masteries and Dissonant Echo are not on this path despite feeding eHP —
 * they are bought with shards and relics.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    ASSIST_SUBSTAT_MAX_LEVEL, ASSIST_BONUS_MAX_LEVEL, assistUpgradeStoneCost, cumulativeAssistStoneCost
 * depends    —
 * used by    src/mechanics/calculators/specs-generated, src/mechanics/effective-paths/ehp-plan, src/mechanics/effective-paths/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */

/**
 * The highest assist *substat* capacity level. The sheet stops the path at 69,
 * and its own release notes record fixing this ("Assist stone levels stop at
 * 69"), so it is a real cap rather than an artefact of the grid.
 */
export const ASSIST_SUBSTAT_MAX_LEVEL = 69

/** The highest assist *bonus* capacity level. */
export const ASSIST_BONUS_MAX_LEVEL = 99

/**
 * Stones to take an assist-module upgrade from `nextLevel - 1` to `nextLevel`.
 *
 * Returns `null` below level 1, rather than extrapolating a price for a level
 * that cannot be bought.
 */
export function assistUpgradeStoneCost(nextLevel: number): number | null {
  if (!Number.isInteger(nextLevel) || nextLevel < 1) return null
  return 12 + nextLevel * 3
}

/**
 * Stones to go from `fromLevel` to `toLevel`.
 *
 * Useful for "what would finishing this cost?" rather than one step at a time.
 */
export function cumulativeAssistStoneCost(fromLevel: number, toLevel: number): number | null {
  if (!Number.isInteger(fromLevel) || !Number.isInteger(toLevel)) return null
  if (fromLevel < 0 || toLevel < fromLevel) return null

  let total = 0
  for (let level = fromLevel + 1; level <= toLevel; level++) {
    const step = assistUpgradeStoneCost(level)
    if (step === null) return null
    total += step
  }
  return total
}
