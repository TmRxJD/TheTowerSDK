/**
 * Effective Paths — the eEcon discount path.
 *
 * The third econ tab ranks six labs by coins *saved* rather than coins earned.
 * Nothing on it moves coins per kill, so it cannot be scored the way the other
 * three are; it needs its own model, and this is it.
 *
 * ## What each candidate is worth
 *
 * Established by probing `EPC_LAB_DISCOUNT` and `EPC_MOD_DISCOUNT` at levels
 * 0..40 on the working copy. Both are exactly linear, and every candidate has
 * the same shape — a total the player has, scaled down by a rate a level:
 *
 * | Candidate | Value | Rate |
 * |---|---|---|
 * | Workshop Utility Discount | `1/(1 − 0.005·level)` | 0.5% |
 * | Labs Coin Discount | `labCoins × (1 − 0.003·level)` | 0.3% |
 * | Enhancement Attack/Defense/Utility | `invested × (1 − 0.003·level)` | 0.3% |
 * | Module Coin Cost | `moduleCoins × (1 − 0.01·level)` | 1% |
 *
 * Workshop Utility Discount is the odd one: it is a cost *multiplier* rather
 * than a pile of coins, which is why it grows where the others shrink, and why
 * the sheet shows the multiplier itself in the Coins Saved column for that one
 * candidate rather than a number of coins.
 *
 * ## Why the totals are supplied rather than computed
 *
 * A candidate's own return is `Old/New − 1` over the level's research time, and
 * the total **cancels** out of that ratio. So ordering *within* a category
 * needs no account data at all.
 *
 * What does not cancel is `CK5`, the tab's "Discount Priority": it picks the
 * single category allowed to compete each step by *absolute* coins saved per
 * day. That needs four totals, and the sheet reads them from the player rather
 * than from anything on the tab — which is also why a copied tab cannot drive
 * them, exactly as `CV5` cannot be driven in the eEcon oracle.
 *
 * Three of the four are reproduced exactly:
 * `WSPATTACK/DEFENSE/UTILITY_TOTAL_COINS_INVESTED(levels, names)` is the
 * undiscounted cumulative enhancement cost summed over the category's six
 * stats, checked against the live function at five level sets.
 *
 * The fourth, `EPC_LAB_DISCOUNT`'s base, has a historical population comparison
 * plus deliberate catalog additions — see {@link labCoinsRemainingDetailed}.
 *
 * ## How the last two were pinned down
 *
 * The sheet holds no player data of its own: `_IDS` is one `IMPORTRANGE` of a
 * separate "IDS Master" spreadsheet, and every other tab reads that. Writing a
 * level into `Master Sheet` changes nothing, because those cells are formulas
 * mirroring `_IDS`; writing into `_IDS` breaks the import. Both were mistaken
 * for evidence that these functions ignore the player before the layout was
 * understood.
 *
 * What works is replacing the import with a frozen copy of its values, driving
 * that, and restoring the formula afterwards. Every claim above about what
 * these two functions read was measured that way.
 */

