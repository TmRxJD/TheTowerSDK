export interface LabLevelsResult {
  levels: EffectiveDamageLabLevels
  /** How the band was bound. */
  binding: 'headers' | 'fixed'
  /** Headers present in the band that this reader deliberately does not map. */
  dropped: string[]
  /** Lab-band headers present that it does not recognise. Should be empty. */
  unknown: string[]
  /** Fields the chosen binding did not supply. */
  missing: Array<keyof EffectiveDamageLabLevels>
}

const HEADER_TO_FIELD = new Map(LAB_BAND_HEADERS)

/** Excel column letters → 1-based index (`A`=1, `Z`=26, `AA`=27). */
function columnIndex(letters: string): number {
  let n = 0
  for (const ch of letters) {
    const code = ch.charCodeAt(0)
    if (code < 65 || code > 90) return -1
    n = n * 26 + (code - 64)
  }
  return n
}

const LAB_BAND_COL_MIN = columnIndex('BO')
const LAB_BAND_COL_MAX = columnIndex('CV')

function readNumber(raw: unknown): number | null {
  if (typeof raw === 'number' && Number.isFinite(raw)) return raw
  if (typeof raw === 'string' && raw.trim() !== '') {
    const n = Number(raw)
    return Number.isFinite(n) ? n : null
  }
  return null
}

/**
 * Read lab levels from an eDamage cell dump.
 *
 * Prefers row-4 headers inside `BO:CV` when any known lab header is present;
 * otherwise uses the live fixed `BP5:CV5` cells.
 */
export function effectiveDamageLabLevelsFromSheet(
  source: Record<string, unknown>,
): LabLevelsResult {
  const fromHeaders: Partial<EffectiveDamageLabLevels> = {}
  const dropped: string[] = []
  const unknown: string[] = []
  const seenHeaders = new Set<string>()

  for (const [addr, value] of Object.entries(source)) {
    const match = /^([A-Z]+)4$/.exec(addr)
    if (!match || typeof value !== 'string') continue
    const col = match[1]!
    const colIdx = columnIndex(col)
    if (colIdx < LAB_BAND_COL_MIN || colIdx > LAB_BAND_COL_MAX) continue

    const header = value.trim()
    if (header === '') continue
    seenHeaders.add(header)

    if (LAB_BAND_NON_LEVELS.has(header)) {
      dropped.push(header)
      continue
    }
    const field = HEADER_TO_FIELD.get(header)
    if (!field) {
      unknown.push(header)
      continue
    }
    const level = readNumber(source[`${col}5`])
    if (level !== null) fromHeaders[field] = level
  }

  const headerFieldCount = Object.keys(fromHeaders).length
  if (headerFieldCount > 0) {
    const levels = { ...ZERO_EFFECTIVE_DAMAGE_LEVELS.lab, ...fromHeaders }
    const missing = LAB_BAND_HEADERS
      .map(([, field]) => field)
      .filter(field => fromHeaders[field] === undefined)
    return { levels, binding: 'headers', dropped, unknown, missing }
  }

  const levels = { ...ZERO_EFFECTIVE_DAMAGE_LEVELS.lab }
  const missing: Array<keyof EffectiveDamageLabLevels> = []
  for (const [cell, field] of LAB_BAND_FIXED_CELLS) {
    const level = readNumber(source[cell])
    if (level === null) {
      missing.push(field)
      continue
    }
    levels[field] = level
  }
  return { levels, binding: 'fixed', dropped, unknown, missing }
}
