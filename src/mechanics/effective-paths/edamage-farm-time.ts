import { COIN_BAND_DELTA_FIELDS } from './edamage-coin-levels'
import type { EffectiveDamageLabLevels, EffectiveDamageLevels, EffectiveDamageUpgrade } from './types'

/** Current eDamage!IG4:JZ4 interleaves coin purchases with the research columns. */
const INSERTIONS: Readonly<Record<string, readonly string[]>> = {
  damage: ['enhancementDamage'],
  startingCash: ['enhancementCashBonus'],
  criticalFactor: ['enhancementCriticalFactor'],
  superCritMulti: ['enhancementSuperCritMult'],
  attackSpeed: ['enhancementAttackSpeed'],
  damagePerMeter: ['enhancementDamagePerMeter'],
  maxRendArmorMultiplier: ['enhancementRendArmor'],
  primaryModuleBonusCore: [
    'primaryModuleCannon', 'assistModuleCannon', 'primaryModuleCore', 'assistModuleCore',
  ],
}

export const FARM_TIME_EXTRA_CANDIDATES = Object.values(INSERTIONS).flat().length

export function farmTimeUpgrades(upgrades: readonly EffectiveDamageUpgrade[]): EffectiveDamageUpgrade[] {
  return upgrades.filter(upgrade => upgrade.band === 'lab').flatMap(upgrade => [
    upgrade,
    ...(INSERTIONS[upgrade.key] ?? []).map(key => {
      const coinUpgrade = upgrades.find(candidate => candidate.id === `coin.${key}`)
      if (!coinUpgrade) throw new Error(`Missing farm-time candidate coin.${key}`)
      return coinUpgrade
    }),
  ])
}

/** Carry prior coin-band purchases into the current board's one research column per lab. */
export function farmTimeLevels(levels: EffectiveDamageLevels): EffectiveDamageLevels {
  const lab = { ...levels.lab }
  const coin = { ...levels.coin }
  for (const key of COIN_BAND_DELTA_FIELDS) {
    lab[key as keyof EffectiveDamageLabLevels] += coin[key]
    coin[key] = 0
  }
  return { ...levels, lab, coin }
}
