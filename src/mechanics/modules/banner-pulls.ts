/**
 * Module banner pulls: the odds a banner gives each epic, what a module has
 * already spent on its way to Ancestral 5, and what reaching 5 stars costs in
 * gems on a featured banner versus the standard one.
 *
 * Every rule is read from v29.0.0 `ModuleManager` (oracle node `module.banner`):
 *
 * - A pull rolls the rarity, then `Range(0, 100)` against each module's Chance.
 * - `CheckBannerForAdjustedOdds`: a non-featured module owned at Ancestral 5
 *   keeps 0.25x its Chance, and the removed 0.75x is split evenly over the
 *   UNMAXED non-featured modules of that rarity (every type together). It only
 *   fires when the rarity has both a maxed and an unmaxed non-featured module.
 *   A lone unmaxed module is capped at 50, the overflow going back to the maxed
 *   ones. The featured module is never adjusted.
 * - Epic pity is 150 pulls, one counter across every banner.
 *
 * Nothing here is tied to one release: a banner is described only by the share
 * of epic pulls it gives the modules you want, which is what its in-game
 * drop-rate panel shows.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    MODULE_BANNER_RULES, moduleCopiesSpentToReach, MODULE_COPIES_TO_ANCESTRAL_5, moduleBannerEpicWeights, modulePullsPerEpic, moduleBannerPullBreakdown, estimateStandardSharePercent, estimateModuleBannerCost
 * depends    src/data/modules/levels, src/data/modules/merge, src/mechanics/modules/types, src/mechanics/primitives/unity-random
 * used by    src/calculators/specs.generated, src/mechanics/modules/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { MODULE_MERGE_RECIPES, moduleMergeCostInDrawnEpics } from '../../data/modules/merge'
import { MODULE_RARITIES, type ModuleRarity } from '../../data/modules/levels'
import { UnityRandom } from '../primitives/unity-random'
import type { ModuleCopiesSpent, ModuleBannerWeightsInput, ModuleEpicRateInput, ModuleBannerPullBreakdown, ModuleBannerCostInput, ModuleBannerPlanCost, ModuleBannerCostResult } from './types'

export const MODULE_BANNER_RULES = {
  /** Remote config, shown on every banner panel. Matches MODULE_PULL_CHANCE_PERCENT.Epic. */
  epicChancePercent: 2.5,
  
  epicPity: 150,
  gemsPerPull: 20,
  /** `MAX_RARITY_DROP_ADJUSTMENT_MULTIPLIER`. */
  maxedChanceMultiplier: 0.25,
  /** The lone-unmaxed cap in `CheckBannerForAdjustedOdds`. */
  loneUnmaxedCapPercent: 50,
  /** `Purchaser.Range(0, 100)` in `CreateModuleFromBanner`. */
  rollRange: 100,
} as const


function recipeForRung(label: ModuleRarity) {
  if (label.startsWith('Ancestral')) return MODULE_MERGE_RECIPES.find(recipe => recipe.addsStar) ?? null
  const plus = label.endsWith(' +')
  const name = plus ? label.slice(0, -2) : label
  return MODULE_MERGE_RECIPES.find(recipe =>
    recipe.baseRarity === name && recipe.basePlus === plus && !recipe.addsStar) ?? null
}

/**
 * What a natural epic has consumed to stand at `rarity`, walked from the merge
 * recipes. `null` rarity means not owned. Returns `null` for a rarity a natural
 * epic never sits at (Common, Rare, Rare +).
 */
export function moduleCopiesSpentToReach(rarity: ModuleRarity | null): ModuleCopiesSpent | null {
  if (rarity == null) return { sameModule: 0, sameTypeEpics: 0 }
  const start = MODULE_RARITIES.indexOf('Epic')
  const target = MODULE_RARITIES.indexOf(rarity)
  if (target < start) return null
  let sameModule = 1
  let sameTypeEpics = 0
  for (let index = start; index < target; index += 1) {
    const recipe = recipeForRung(MODULE_RARITIES[index])
    if (!recipe) return null
    const fodderCost = moduleMergeCostInDrawnEpics(recipe.fodderRarity, recipe.fodderPlus)
    if (fodderCost == null) return null
    const consumed = recipe.fodderCount * fodderCost
    if (recipe.matchMode === 'template') sameModule += consumed
    else sameTypeEpics += consumed
  }
  return { sameModule, sameTypeEpics }
}

const TO_ANCESTRAL_5 = moduleCopiesSpentToReach('Ancestral 5')
if (!TO_ANCESTRAL_5) throw new Error('MODULE_MERGE_RECIPES no longer reach Ancestral 5')

/** A natural epic's full bill to Ancestral 5: 18 of itself, 20 of its type. */
export const MODULE_COPIES_TO_ANCESTRAL_5: ModuleCopiesSpent = TO_ANCESTRAL_5


/**
 * Chance of each epic in the pool, as a percentage of epic pulls — a port of
 * `CheckBannerForAdjustedOdds`. Always sums to 100.
 */
export function moduleBannerEpicWeights(input: ModuleBannerWeightsInput): Map<string, number> {
  const featured = (input.featured ?? []).filter(id => input.pool.includes(id))
  const featuredSet = new Set(featured)
  const featuredPercent = featured.length ? (input.featuredPercent ?? 0) : 0
  const weights = new Map<string, number>()
  for (const id of featured) weights.set(id, featuredPercent)

  const others = input.pool.filter(id => !featuredSet.has(id))
  if (!others.length) return weights
  const base = (MODULE_BANNER_RULES.rollRange - featuredPercent * featured.length) / others.length
  for (const id of others) weights.set(id, base)

  const maxed = others.filter(id => input.maxed.has(id))
  const unmaxed = others.filter(id => !input.maxed.has(id))
  if (!maxed.length || !unmaxed.length) return weights

  const { maxedChanceMultiplier, loneUnmaxedCapPercent } = MODULE_BANNER_RULES
  const freed = (1 - maxedChanceMultiplier) * base * maxed.length
  for (const id of maxed) weights.set(id, maxedChanceMultiplier * base)
  if (unmaxed.length === 1 && base + freed > loneUnmaxedCapPercent) {
    weights.set(unmaxed[0], loneUnmaxedCapPercent)
    const overflow = (base + freed - loneUnmaxedCapPercent) / maxed.length
    for (const id of maxed) weights.set(id, (weights.get(id) ?? 0) + overflow)
  } else {
    for (const id of unmaxed) weights.set(id, base + freed / unmaxed.length)
  }
  return weights
}


function clampPercent(value: number): number {
  return Number.isFinite(value) ? Math.min(100, Math.max(0, value)) : 0
}

/**
 * Expected pulls per epic with pity: min(Geometric(p), pity) averages
 * (1 - (1 - p)^pity) / p. About 39.1 at 2.5% and 150.
 */
export function modulePullsPerEpic(input: ModuleEpicRateInput = {}): number {
  const p = clampPercent(input.epicChancePercent ?? MODULE_BANNER_RULES.epicChancePercent) / 100
  const pity = Math.max(1, Math.floor(input.epicPity ?? MODULE_BANNER_RULES.epicPity))
  if (p <= 0) return pity
  if (p >= 1) return 1
  return (1 - (1 - p) ** pity) / p
}


/**
 * What a single pull gives, before pity: each target's chance, any other epic,
 * and a non-epic. `targetSharesPercent` are each target's share of EPIC pulls,
 * as the banner panel shows them. Always sums to 100.
 */
export function moduleBannerPullBreakdown(input: {
  readonly targetSharesPercent: readonly number[]
  readonly epicChancePercent?: number
}): ModuleBannerPullBreakdown {
  const epic = clampPercent(input.epicChancePercent ?? MODULE_BANNER_RULES.epicChancePercent)
  const shares = input.targetSharesPercent.map(clampPercent)
  const total = shares.reduce((sum, share) => sum + share, 0)
  const scale = total > 100 ? 100 / total : 1
  return {
    targetsPercent: shares.map(share => epic * share * scale / 100),
    otherEpicPercent: epic * (100 - Math.min(100, total)) / 100,
    nonEpicPercent: 100 - epic,
  }
}

/**
 * One target's share of epic pulls on the standard banner, from the game's own
 * adjustment rule. `maxedCount` epics in the pool are owned at 5 stars; the
 * targets are unmaxed. Returns null when the counts cannot describe a pool.
 */
export function estimateStandardSharePercent(input: {
  readonly epicsInPool: number
  readonly maxedCount: number
  readonly targetCount: number
}): number | null {
  const pool = Math.floor(input.epicsInPool)
  const targets = Math.floor(input.targetCount)
  if (!(pool >= 1) || !(targets >= 1) || targets > pool) return null
  const maxedCount = Math.max(0, Math.min(pool - targets, Math.floor(input.maxedCount)))
  const ids = Array.from({ length: pool }, (_, index) => `epic-${index}`)
  const maxed = new Set(ids.slice(targets, targets + maxedCount))
  return moduleBannerEpicWeights({ pool: ids, maxed }).get(ids[0]) ?? null
}




const MAX_PULLS_PER_TRIAL = 2_000_000

function percentile(sorted: readonly number[], fraction: number): number {
  if (!sorted.length) return 0
  const index = Math.min(sorted.length - 1, Math.max(0, Math.round(fraction * (sorted.length - 1))))
  return sorted[index]
}

/**
 * Gems to collect every target's remaining copies, on featured banners versus
 * the standard banner. Simulated pull by pull with the shared pity counter.
 *
 * The standard share is held fixed. In the game a target that reaches 5 stars
 * drops to 0.25x and the rest rise, so the standard figure is conservative.
 */
export function estimateModuleBannerCost(input: ModuleBannerCostInput): ModuleBannerCostResult {
  const epicChancePercent = clampPercent(input.epicChancePercent ?? MODULE_BANNER_RULES.epicChancePercent)
  const epicPity = Math.max(1, Math.floor(input.epicPity ?? MODULE_BANNER_RULES.epicPity))
  const gemsPerPull = input.gemsPerPull ?? MODULE_BANNER_RULES.gemsPerPull
  const trials = Math.max(1, Math.floor(input.trials ?? 1000))
  const needs = input.targets.map(target => Math.max(0, Math.floor(target.copiesNeeded)))
  const totalCopiesNeeded = needs.reduce((sum, need) => sum + need, 0)
  const featuredShare = clampPercent(input.featuredSharePercent)
  const standardShare = needs.length ? Math.min(clampPercent(input.standardSharePercent), 100 / needs.length) : 0
  const rng = UnityRandom.fromSeed(input.seed ?? 1)

  const run = (plan: 'featured' | 'standard'): ModuleBannerPlanCost | null => {
    const share = plan === 'featured' ? featuredShare : standardShare
    if (totalCopiesNeeded > 0 && (share <= 0 || epicChancePercent <= 0)) return null
    const gemTotals: number[] = []
    let pullSum = 0
    let epicSum = 0
    let cappedTrials = 0
    for (let trial = 0; trial < trials; trial += 1) {
      let pulls = 0
      let epics = 0
      let pity = 0
      let capped = false
      const nextEpic = () => {
        for (;;) {
          pulls += 1
          pity += 1
          if (pity >= epicPity || rng.value() * 100 < epicChancePercent) { pity = 0; break }
        }
        epics += 1
      }
      if (plan === 'featured') {
        for (const need of needs) {
          let got = 0
          while (got < need) {
            if (pulls >= MAX_PULLS_PER_TRIAL) { capped = true; break }
            nextEpic()
            if (rng.value() * 100 < share) got += 1
          }
          if (capped) break
        }
      } else {
        const remaining = [...needs]
        let left = totalCopiesNeeded
        while (left > 0) {
          if (pulls >= MAX_PULLS_PER_TRIAL) { capped = true; break }
          nextEpic()
          const slot = Math.floor(rng.value() * 100 / share)
          if (slot < remaining.length && remaining[slot] > 0) {
            remaining[slot] -= 1
            left -= 1
          }
        }
      }
      if (capped) cappedTrials += 1
      gemTotals.push(pulls * gemsPerPull)
      pullSum += pulls
      epicSum += epics
    }
    gemTotals.sort((left, right) => left - right)
    return {
      gems: {
        mean: gemTotals.reduce((sum, value) => sum + value, 0) / gemTotals.length,
        p10: percentile(gemTotals, 0.1),
        p90: percentile(gemTotals, 0.9),
      },
      meanPulls: pullSum / trials,
      meanEpics: epicSum / trials,
      cappedTrials,
    }
  }

  const featured = run('featured')
  const standard = run('standard')
  const cheaper = featured && standard
    ? (featured.gems.mean <= standard.gems.mean ? 'featured' : 'standard')
    : featured ? 'featured' : standard ? 'standard' : null
  // Featured needs sum(copies) / share epics on average; equal the standard plan's epics.
  const breakEven = standard && standard.meanEpics > 0 ? 100 * totalCopiesNeeded / standard.meanEpics : null
  return {
    featured,
    standard,
    cheaper,
    breakEvenFeaturedSharePercent: breakEven != null && breakEven <= 100 ? breakEven : null,
    totalCopiesNeeded,
  }
}
