/**
 * In-run workshop growth above level 6000 in the 29.1.
 * Health and Health Regen keep their level-6000 base and scale it by the
 * Damage curve's ratio. Their older high-level curves must not be extrapolated.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    WORKSHOP_NORMAL_IN_RUN_CAP, workshopOvercapMultiplier, applyWorkshopOvercapMultiplier
 * depends    src/mechanics/workshop/damage
 * used by    src/calculators/specs.generated, src/mechanics/effective-paths/workshop-values, src/mechanics/workshop/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import { workshopDamageAtLevel } from './damage'

/** The normal in-run cap for Damage, Health and Health Regen. */
export const WORKSHOP_NORMAL_IN_RUN_CAP = 6000

/**
 * Health / Health Regen growth past the normal cap, before other modifiers.
 * Pass the actual in-run level after Infinity Threshold's free upgrades.
 */
export function workshopOvercapMultiplier(level: number): number {
  if (!Number.isFinite(level)) throw new RangeError('Workshop level must be finite')
  const effective = Math.max(WORKSHOP_NORMAL_IN_RUN_CAP, Math.floor(level))
  return workshopDamageAtLevel(effective) / workshopDamageAtLevel(WORKSHOP_NORMAL_IN_RUN_CAP)
}

/**
 * Apply the in-run Health / Health Regen rule to a value evaluated at
 * min(level, 6000). Damage already uses its full curve and must not use this.
 */
export function applyWorkshopOvercapMultiplier(valueAtCappedLevel: number, level: number): number {
  if (!Number.isFinite(valueAtCappedLevel) || valueAtCappedLevel < 0) {
    throw new RangeError('Workshop stat must be finite and nonnegative')
  }
  return valueAtCappedLevel * workshopOvercapMultiplier(level)
}
