/**
 * The types `mechanics/ep-graph/` exports, in one place — so a neighbouring module finds the shape it
 * needs here instead of declaring its own under a second name.
 */
/* ── file map ─────────────────────────────────────────────────────────────────
 * exports    EpGraphIndex, EpMutateResult, MermaidSlice, EpGraphValidation
 * depends    src/mechanics/ep-graph/schema
 * used by    src/mechanics/ep-graph/build-index, src/mechanics/ep-graph/index, src/mechanics/ep-graph/mutate, src/mechanics/ep-graph/render-mermaid, src/mechanics/ep-graph/validate, tooling/builders/index
 * ─────────────────────────────────────────────── generated by `npm run map` ──
 */
import type { EpGraph, EpGraphFamily, EpGraphNodeType, EpNodeStatus } from './schema'

// from build-index.ts

export interface EpGraphIndex {
  contentVersion: number
  sheetVersion: string
  byCell: Record<string, string[]>
  byLambda: Record<string, string[]>
  byFamily: Record<string, string[]>
  byStatus: Record<EpNodeStatus, string[]>
}

// from mutate.ts

export interface EpMutateResult {
  graph: EpGraph
  applied: number
  contentVersion: number
  issues: string[]
}

// from render-mermaid.ts

export interface MermaidSlice {
  name: string
  family: EpGraphFamily
  types?: EpGraphNodeType[]
  mermaid: string
}

// from validate.ts

export interface EpGraphValidation {
  errors: string[]
  warnings: string[]
}
